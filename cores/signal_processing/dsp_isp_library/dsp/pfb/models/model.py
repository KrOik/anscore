"""DSP-16 PFB channelizer: floating-point reference, bit-exact model,
coefficient-LUT generator and cycle-accurate oracle for rtl/pfb_stream.sv.

Conventions (must match the RTL):
  * input beat n carries x[n] = (re,im), each signed16 Q1.15; frame f covers
    n = f*M + r, r = 0..M-1; beat r is steered to polyphase branch r.
  * branch m output for frame f:
        v_f[m] = sum_{p=0}^{P-1} h[p*M+m] * x[(f-p)*M + m]
    with h = prototype lowpass taps, p = 0 the newest sample of the branch.
  * channel k of frame f: X_f[k] = sum_r v_f[r] * W_M^(r*k) evaluated as an
    in-place radix-2 DIT FFT on the bit-reversed branch vector.  Every stage
    is divided by two, so the emitted value is DFT(v)/M (Q1.15 in -> Q1.15
    out for in-channel tones of amplitude <= ~1).
  * per-channel gain g[k] signed Q2.16 is applied on output drain.

Fixed-point rules mirrored from the RTL:
  * coefficients signed18 Q1.17; FIR products 34 bits, accumulator 40 bits;
    v = sat16((acc + 2**16) >> 17)  (round half up toward +inf).
  * twiddle W_16^t Q1.15 (cos(0) saturated to 32767); complex multiply uses
    three low-32-bit 17x17 products; t = (g0+g1+0x4000)>>15 arithmetic.
  * butterfly outputs (a +/- t) are 18-bit, shifted >>>1 and truncated to the
    low 16 bits (deterministic wrap, same as fft64).
  * gain product 34 bits; out = sat16((p + 2**15) >> 16).
"""
import math
from pathlib import Path


def _s(v, b):
    """Wrap integer v to signed b bits."""
    v &= (1 << b) - 1
    return v - (1 << b) if v & (1 << (b - 1)) else v


def s16(v): return _s(v, 16)
def s35(v): return _s(v, 35)
def s41(v): return _s(v, 41)


def sat16(v):
    return -32768 if v < -32768 else (32767 if v > 32767 else v)


# W_16^t = cos(2 pi t/16) - j sin(2 pi t/16), Q1.15, stored as (cos, +sin)
# saturated to +-32767 (fft64 convention); index t = 0..7.
TW = []
for _t in range(8):
    _c = round(32768 * math.cos(2 * math.pi * _t / 16.0))
    _v = round(32768 * math.sin(2 * math.pi * _t / 16.0))
    TW.append((min(32767, max(-32768, _c)), min(32767, max(-32768, _v))))


def log2m(m):
    return m.bit_length() - 1


def bitrev(v, bits):
    r = 0
    for i in range(bits):
        r = (r << 1) | ((v >> i) & 1)
    return r


def prototype(M, P):
    """Blackman-windowed sinc prototype LPF, cutoff 1/(2M) cycles/sample,
    normalized to unit DC gain (sum h = 1).  Returns M*P floats."""
    n_taps = M * P
    d = (n_taps - 1) / 2.0
    fc = 0.5 / M
    h = []
    for n in range(n_taps):
        u = (n - d) * 2.0 * fc
        s = 1.0 if u == 0.0 else math.sin(math.pi * u) / (math.pi * u)
        w = (0.42 - 0.5 * math.cos(2 * math.pi * n / (n_taps - 1))
             + 0.08 * math.cos(4 * math.pi * n / (n_taps - 1)))
        h.append(2.0 * fc * s * w)
    g = sum(h)
    return [x / g for x in h]


def quantize(h):
    """Float taps -> signed18 Q1.17 integers."""
    return [max(-131072, min(131071, int(round(x * 131072.0)))) for x in h]


def emit_vh(path, coef):
    """Write pfb_coeffs.vh: index 0 lands in the low 18 bits."""
    body = ", ".join(("-18'sd%d" % -c) if c < 0 else ("18'sd%d" % c)
                     for c in reversed(coef))
    Path(path).write_text(
        "// generated by models/model.py --emit-vh; do not edit\n"
        "localparam integer PFB_NCOEF = %d;\n"
        "localparam [PFB_NCOEF*18-1:0] PFB_COEF = {%s};\n"
        % (len(coef), body))


def mul17(a, b):
    """Low 32 bits of a signed 17x17 product (shift-add model, no DSP)."""
    return _s(a * b, 32)


def _butterfly(xr, xi, i, j, twc, tws):
    ar, ai = xr[i], xi[i]
    br, bi = xr[j], xi[j]
    g0 = mul17(br + bi, twc)
    g1 = mul17(bi, tws - twc)
    g2 = mul17(br, twc + tws)
    tr = _s(g0 + g1 + 0x4000, 32) >> 15
    ti = _s(g0 - g2 + 0x4000, 32) >> 15
    xr[i] = s16(_s(ar + tr, 18) >> 1)
    xi[i] = s16(_s(ai + ti, 18) >> 1)
    xr[j] = s16(_s(ar - tr, 18) >> 1)
    xi[j] = s16(_s(ai - ti, 18) >> 1)


def fft_fixed(xr, xi, M):
    """In-place radix-2 DIT FFT on bit-reversed input; output is DFT/M.
    xr/xi are lists of signed16, length M; exactly mirrors the RTL stage/bf
    iteration order."""
    l2 = log2m(M)
    for s in range(1, l2 + 1):
        half = 1 << (s - 1)
        for bf in range(M // 2):
            pos = bf & (half - 1)
            blk = bf >> (s - 1)
            i = (blk << s) | pos
            j = i + half
            twa = pos << (4 - s)
            _butterfly(xr, xi, i, j, *TW[twa])


def fir_branch(hist_m, coef, m, M, P, ndepth):
    """One polyphase branch dot product; returns saturated signed16 pair."""
    ar = ai = 0
    for p in range(P):
        if p < ndepth:
            c = coef[p * M + m]
            hr, hi = hist_m[p]
            ar += c * hr
            ai += c * hi
    vr = sat16(_s(ar + 0x10000, 41) >> 17)
    vi = sat16(_s(ai + 0x10000, 41) >> 17)
    clip = (_s(ar + 0x10000, 41) >> 17 != vr) or (_s(ai + 0x10000, 41) >> 17 != vi)
    return vr, vi, clip


def float_frames(xs, M, P, h, gains=None):
    """Independent floating reference.  xs = flat list of complex inputs;
    returns list of frames, each a list of M complex channel outputs
    (DFT unscaled by 1/M, gains applied)."""
    gains = gains or [1.0] * M
    hist = [[0j] * P for _ in range(M)]
    frames = []
    for f in range(len(xs) // M):
        for r in range(M):
            hist[r] = [xs[f * M + r]] + hist[r][:P - 1]
        v = [sum(h[p * M + m] * hist[m][p] for p in range(P))
             for m in range(M)]
        frames.append([
            gains[k] * sum(v[r] * complex(math.cos(-2 * math.pi * r * k / M),
                                           math.sin(-2 * math.pi * r * k / M))
                           for r in range(M))
            for k in range(M)])
    return frames


class Oracle:
    """Cycle-accurate model of pfb_stream.  One tick() call per clk edge:
    emits the row (inputs + expected pre-edge outputs), then applies the
    sequential update.

    The FIR and FFT legs run in the same sub-phases as the RTL (see
    rtl/pfb_stream.sv): a tap is read, multiplied, accumulated in three cycles
    and a branch rounds and clips in two more; a butterfly reads, multiplies,
    collapses and writes in four.  Only the write and counter updates happen on
    the last sub-phase of each, which is why the legs take 3*M*P + 2*M and
    4*(M/2)*log2(M) cycles rather than M*P and (M/2)*log2(M)."""

    CAP, FIR, FFT, SNP = 'CAP', 'FIR', 'FFT', 'SNP'
    F_LD, F_MP, F_AC, F_RN, F_CL = 0, 1, 2, 3, 4
    S_LD, S_MP, S_TR, S_BT = 0, 1, 2, 3

    def __init__(self, M, P, coef):
        self.M, self.P, self.coef = M, P, coef
        self.hist = [[(0, 0)] * P for _ in range(M)]
        self.xr = [0] * M
        self.xi = [0] * M
        self.outr = [0] * M
        self.outi = [0] * M
        self.rows = []
        self.clock = 0
        self.outputs = []          # accepted beats: (tid, user, last, (re,im))
        self.reset()

    def reset(self):
        """Matches RTL rst_n: clears control state and gains, keeps the
        sample/working arrays (they are masked by ndepth or rewritten)."""
        self.st = self.CAP
        self.fs = self.F_LD
        self.rpos = 0
        self.draining = False
        self.dp = False
        self.gpr = (0, 0)
        self.ok = 0
        self.ndepth = 0
        self.fm = 0
        self.fp = 0
        self.stage = 0
        self.bf = 0
        self.acc = [0, 0]
        self.q = [0, 0]
        self.gain = [65536] * self.M
        self.mvalid = False
        self.mdata = (0, 0)
        self.mtid = 0
        self.muser = 0
        self.mlast = False
        self.cnt_in = 0
        self.cnt_frames = 0
        self.cnt_out = 0
        self.clip = 0
        self.cd = 0
        self.ce = 0
        self.outputs = []

    def tick(self, rst=1, cv=0, caddr=0, cgain=0, sv=0, sre=0, sim=0, mr=1):
        M, P = self.M, self.P
        l2 = log2m(M)
        sr = int(bool(rst) and self.st == self.CAP)
        cr = int(bool(rst) and self.st == self.CAP and self.rpos == 0
                 and not self.draining)
        busy = int(self.st != self.CAP or self.rpos != 0 or self.mvalid
                   or self.draining)
        sd = ((sim & 0xffff) << 16) | (sre & 0xffff)
        md = ((self.mdata[1] & 0xffff) << 16) | (self.mdata[0] & 0xffff)
        self.rows.append(
            "%d %d %x %x %d %x %d %d %d %d %x %x %x %d %d %d %d %d %d %d %d"
            % (rst, cv, caddr & 0x1f, cgain & 0x3ffff, sv, sd, mr,
               sr, cr, int(self.mvalid), md, self.mtid, self.muser,
               int(self.mlast), busy, self.cd, self.ce,
               self.cnt_in, self.cnt_frames, self.cnt_out, self.clip))
        self.clock += 1
        self.cd = self.ce = 0
        if not rst:
            self.reset()
            return
        # output slot accept
        if self.mvalid and mr:
            self.mvalid = False
            self.cnt_out += 1
            self.outputs.append((self.mtid, self.muser, self.mlast,
                                 self.mdata))
        # atomic gain write
        if cv and cr:
            if caddr < M:
                self.gain[caddr] = _s(cgain, 18)
                self.cd = 1
            else:
                self.ce = 1
        # output drain beat: one cycle forms and registers the gain product,
        # the next rounds, clips and presents it (never both in one cycle, so
        # the multiplier and the 35-bit rounding add sit in separate cycles).
        if self.draining:
            if not self.dp:
                g = self.gain[self.ok]
                self.gpr = (g * self.outr[self.ok], g * self.outi[self.ok])
                self.dp = True
            elif not self.mvalid or mr:
                pr = _s(self.gpr[0] + 0x8000, 35) >> 16
                pi = _s(self.gpr[1] + 0x8000, 35) >> 16
                re, im = sat16(pr), sat16(pi)
                if re != pr or im != pi:
                    self.clip = 1
                self.mvalid = True
                self.mdata = (re, im)
                self.mtid = self.ok
                self.muser = self.cnt_frames & 0xff
                self.mlast = (self.ok == M - 1)
                if self.ok == M - 1:
                    self.draining = False
                    self.cnt_frames += 1
                else:
                    self.ok += 1
                self.dp = False
        # state machine
        if self.st == self.CAP:
            if sv and sr:
                self.hist[self.rpos] = ([(s16(sre), s16(sim))]
                                        + self.hist[self.rpos][:P - 1])
                self.cnt_in += 1
                if self.rpos == M - 1:
                    self.rpos = 0
                    self.st = self.FIR
                    self.fs = self.F_LD
                    self.fm = 0
                    self.fp = 0
                    self.acc = [0, 0]
                    if self.ndepth < P:
                        self.ndepth += 1
                else:
                    self.rpos += 1
        elif self.st == self.FIR:
            if self.fs == self.F_LD:
                self.fs = self.F_MP
            elif self.fs == self.F_MP:
                self.fs = self.F_AC
            elif self.fs == self.F_AC:
                c = self.coef[self.fp * M + self.fm]
                hr, hi = (self.hist[self.fm][self.fp]
                          if self.fp < self.ndepth else (0, 0))
                self.acc[0] += c * hr
                self.acc[1] += c * hi
                if self.fp == P - 1:
                    self.fs = self.F_RN
                else:
                    self.fp += 1
                    self.fs = self.F_LD
            elif self.fs == self.F_RN:
                self.q = [_s(self.acc[0] + 0x10000, 41) >> 17,
                          _s(self.acc[1] + 0x10000, 41) >> 17]
                self.fs = self.F_CL
            else:  # F_CL: clip the registered rounding and write the FFT array
                vr, vi = sat16(self.q[0]), sat16(self.q[1])
                if vr != self.q[0] or vi != self.q[1]:
                    self.clip = 1
                addr = bitrev(self.fm, 4) >> (4 - l2)
                self.xr[addr] = vr
                self.xi[addr] = vi
                self.fp = 0
                self.acc = [0, 0]
                if self.fm == M - 1:
                    self.st = self.FFT
                    self.fs = self.S_LD
                    self.stage = 1
                    self.bf = 0
                else:
                    self.fm += 1
                    self.fs = self.F_LD
        elif self.st == self.FFT:
            if self.fs != self.S_BT:
                # read, multiply and collapse are only bookkeeping in the model:
                # no array or counter moves until the write phase.
                self.fs += 1
            else:
                s = self.stage
                half = 1 << (s - 1)
                pos = self.bf & (half - 1)
                blk = self.bf >> (s - 1)
                i = (blk << s) | pos
                j = i + half
                twa = pos << (4 - s)
                _butterfly(self.xr, self.xi, i, j, *TW[twa])
                self.fs = self.S_LD
                if self.bf == M // 2 - 1:
                    self.bf = 0
                    if self.stage == l2:
                        self.st = self.SNP
                    else:
                        self.stage += 1
                else:
                    self.bf += 1
        else:  # SNP: snapshot FFT result into the drain buffer when free
            if not self.draining:
                self.outr = self.xr[:]
                self.outi = self.xi[:]
                self.draining = True
                self.dp = False
                self.ok = 0
                self.st = self.CAP

    def frame_bursts(self):
        """Group accepted output beats into bursts; a new burst starts at
        tid == 0."""
        bursts = []
        cur = []
        for b in self.outputs:
            if b[0] == 0 and cur:
                bursts.append(cur)
                cur = []
            cur.append(b)
        if cur:
            bursts.append(cur)
        return bursts


def _self_test():
    for M in (4, 8, 16):
        for P in (2, 4):
            h = prototype(M, P)
            coef = quantize(h)
            # complex tone at channel centre k=1 must land in bin 1
            k = 1
            xs = [complex(round(12000 * math.cos(2 * math.pi * k * n / M)),
                          round(12000 * math.sin(2 * math.pi * k * n / M)))
                  for n in range(M * (P + 4))]
            o = Oracle(M, P, coef)
            o.reset()
            got = []
            # drive at full rate, drain always ready
            n = 0
            steps = 0
            while n < len(xs) and steps < 100000:
                o.tick(sv=1, sre=int(xs[n].real), sim=int(xs[n].imag), mr=1)
                if o.cnt_in == n + 1:
                    n += 1
                steps += 1
            while len(got) < M and steps < 100000:
                o.tick(mr=1)
                got = o.outputs
                steps += 1
            bursts = o.frame_bursts()
            assert bursts and len(bursts[-1]) == M
            last = bursts[-1]
            mags = [abs(complex(*b[3])) for b in last]
            assert max(range(M), key=lambda i: mags[i]) == k
            iso = 20 * math.log10(mags[k] / max(1e-9,
                    max(m for i, m in enumerate(mags) if i != k)))
            print("M=%d P=%d bin%d mag=%.0f isolation=%.1fdB"
                  % (M, P, k, mags[k], iso))
    print("self-test PASS")


