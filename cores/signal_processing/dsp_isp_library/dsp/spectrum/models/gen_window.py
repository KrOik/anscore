"""Window table and cosine ROM generator for the DSP-05 spectrum cores.

Periodic (DFT-even) window formulas, n = 0..N-1, t = 2*pi*n/N:
  hann:     w = 0.50 - 0.50*cos(t)
  hamming:  w = 0.54 - 0.46*cos(t)
  blackman: w = 0.42 - 0.50*cos(t) + 0.08*cos(2t)

Quantization to signed18 Q3.15 does NOT evaluate these formulas in floating
point per entry. It reproduces the hardware path exactly: quantized constants
(A0,A1,A2) = round(a*32768), a quarter-wave cosine ROM
T[i] = round(cos(2*pi*i/4096)*32768) for i = 0..1024, then
w = sat18(RNE((A0<<15) - A1*c1 + A2*c2, 2**15)) with
c1 = cos_q15(n*4096/N), c2 = cos_q15(2*n*4096/N).

Usage:
  python gen_window.py --type hann --n 256            # JSON table to stdout
  python gen_window.py --type blackman --n 64 --output table.json
  python gen_window.py --emit-rom ../rtl/window_cos_rom.sv
"""
import argparse, json
from pathlib import Path
from reference import (COS, coherent_gain, gen_window_table, check_log2n,
                       MAX_LOG2N)

ROM_HEADER = """// Generated by models/gen_window.py --emit-rom. Do not edit by hand.
// Quarter-wave cosine ROM, signed18 Q3.15:
//   T[i] = round(cos(2*pi*i/4096)*32768), i = 0..1024.
// Two synchronous read ports for theta and 2*theta lookups.
// Read-data registers are enabled; they hold while en=0.
module window_cos_rom(
 input wire clk,input wire en,
 input wire [10:0] addra,output reg signed [17:0] douta,
 input wire [10:0] addrb,output reg signed [17:0] doutb
);
reg signed [17:0] rom[0:1024];
initial begin
"""

ROM_FOOTER = """end
always @(posedge clk) begin
 if(en) begin
  douta <= rom[addra];
  doutb <= rom[addrb];
 end
end
endmodule
"""


def rom_text():
    lines = [ROM_HEADER]
    for i, v in enumerate(COS):
        lines.append(f' rom[{i}]=18\'sd{v};\n')
    lines.append(ROM_FOOTER)
    return ''.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--type', choices=['hann', 'hamming', 'blackman'],
                   default='hann')
    p.add_argument('--n', type=int, default=256,
                   help='block length, power of two 16..4096')
    p.add_argument('--output', type=Path)
    p.add_argument('--emit-rom', type=Path,
                   help='write synthesizable window_cos_rom.sv')
    a = p.parse_args()
    if a.emit_rom:
        a.emit_rom.write_text(rom_text())
        print('wrote', a.emit_rom)
        return
    log2n = a.n.bit_length() - 1
    if a.n != (1 << log2n) or not check_log2n(log2n):
        p.error('n must be a power of two in 16..4096')
    wtype = {'hann': 1, 'hamming': 2, 'blackman': 3}[a.type]
    table = gen_window_table(log2n, wtype)
    report = {'type': a.type, 'n': a.n,
              'format': 'signed18 Q3.15, index order n=0..N-1 arrival order',
              'coefficients': table,
              'coherent_gain': coherent_gain(table),
              'max_coefficient_q15': max(table),
              'amplitude_correction_hint':
                  'unity tone amplitude recovery needs ~1/CG gain; '
                  'scale_shift approximates it by powers of two only'}
    text = json.dumps(report, indent=2)
    if a.output:
        with a.output.open('x', encoding='utf-8') as f:
            f.write(text)
    else:
        print(text)


if __name__ == '__main__':
    main()
