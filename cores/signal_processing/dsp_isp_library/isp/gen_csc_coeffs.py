"""Generate the fixed specification coefficient ROM, never from DUT output."""
from pathlib import Path
from csc_model import matrix

def generate():
    lines=['// Generated by gen_csc_coeffs.py; Q16 signed specification constants.', 'case ({mode, standard, limited})']
    for mode,op in enumerate(('forward','inverse','gray')):
        for std in range(2):
            for limited in range(2):
                key=(mode<<2)|(std<<1)|limited
                lines.append(f"4'd{key}: begin")
                for bits in (8,10):
                    a,offset,bias=matrix(bits,('601','709')[std],bool(limited),op)
                    if op=='gray': a=a+((0,0,0),(0,0,0)); bias=bias+(0,0)
                    lines.append(('if' if bits==8 else 'else if')+f' (BITS == {bits}) begin')
                    for i,row in enumerate(a):
                        for j,c in enumerate(row): lines.append(f'c{i}{j} = {c};')
                    for i,o in enumerate(offset): lines.append(f'o{i} = {o};')
                    for i,b in enumerate(bias): lines.append(f'b{i} = {b};')
                    lines.append('end')
                lines.append('end')
    lines.extend(['default: begin end','endcase'])
    Path(__file__).with_name('csc_coeffs.vh').write_text('\n'.join(lines)+'\n')

if __name__=='__main__': generate()
