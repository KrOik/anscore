"""ISP-08 basic ISP references: BLC, external WB gains, DPC, gamma LUT, AWB stats.

Two independent references live here:

* ``float_*`` / ``float_pipeline`` -- real-valued semantics (Fraction where a
  rational matters, float pow for gamma).
* ``*_pixel`` / ``pipeline`` -- the bit-exact integer contract the RTL
  implements.

Pixel word: ``CH*BITS`` bits, channel ``c`` in slice ``[c*BITS +: BITS]``.
For ``CH=3`` the packing is ``{R, G, B}`` MSB->LSB (matching
``isp/csc_stream.v``), i.e. channel 0 = B (LSB slice), 1 = G, 2 = R.
For ``CH=1`` only channel 0 exists (gray / single-plane).

Static geometry: WIDTH x HEIGHT is fixed per build because the DPC stage
instantiates ``infra/window/stream_window_padded`` (3x3 REPLICATE), whose
geometry is a synthesis-time parameter.  The runtime config carries
``img_w``/``img_h`` fields that must equal the static geometry; anything else
is rejected with ``cfg_error``.

Pipeline order (documented, bit-exact): BLC -> WB gain -> DPC -> gamma.
AWB statistics tap the post-BLC / pre-WB bus (black-corrected linear data is
the defined statistics source for gain estimation).

Integer contract per stage (channel index c):
    blc_c    = (p_c >= off_c) ? p_c - off_c : 0                unsigned offset
    wb_c     = min(MPX, (blc_c * gain_c + 128) >> 8)           gain UQ4.8, RNE
    med8_c   = (s3 + s4) >> 1   over the 8 sorted 3x3 neighbors of c
    defect   = |wb_c - med8_c| > thr                           thr=MPX disables
    dpc_c    = defect ? med8_c : wb_c
    gamma    = sel==0 ? d_c : PWL(d_c)                         33-node table

Gamma PWL: node index = top 5 bits, frac = low BITS-5 bits, STEP=2^(BITS-5):
    out = y0 + ((y1 - y0) * frac + STEP/2) >> (BITS-5)
Nodes are generated by ``gamma_nodes`` and committed to ``rtl/gamma_table.vh``
(``emit_gamma_vh`` is the single source; ``test_models.py`` verifies the
committed file matches a fresh regeneration).
"""
from dataclasses import dataclass
from fractions import Fraction

GAIN_FRAC = 8          # WB gain UQ4.8: 1.0 -> 256
GAIN_W = 12            # WB gain field width, max gain 4095/256 ~= 16.0
GAMMA_NODES = 33       # 32 uniform segments over [0, MPX]
GAMMA_SELS = (0, 1, 2) # 0=bypass, 1=encode x^(1/2.2), 2=decode x^2.2


def _frame(frame):
    if not frame or not frame[0]:
        raise ValueError('empty frame')
    w = len(frame[0])
    if any(len(r) != w for r in frame):
        raise ValueError('ragged frame')
    if any(not isinstance(v, int) or isinstance(v, bool) or v < 0
           for r in frame for v in r):
        raise ValueError('pixels must be unsigned integers')
    return len(frame), w


def mpx(bits):
    return (1 << bits) - 1


def chan(px, c, bits):
    return (px >> (c * bits)) & mpx(bits)


def packpix(vals, bits):
    """Pack channel values LSB-first: v[0] is the LSB slice."""
    w = 0
    for c, v in enumerate(vals):
        w |= (v & mpx(bits)) << (c * bits)
    return w


@dataclass(frozen=True)
class Config:
    """Atomic runtime configuration; every field committed or rejected whole.

    ``img_w``/``img_h`` must equal the static WIDTH/HEIGHT the core was built
    with (``width``/``height`` here model the static parameters).  blc/wb are
    tuples of exactly 3 entries; entries >= CH are stored but unused.
    """
    img_w: int
    img_h: int
    blc: tuple = (0, 0, 0)           # unsigned per-channel black offsets
    wb: tuple = (256, 256, 256)      # UQ4.8 per-channel gains (256 = 1.0)
    dpc_thr: int = 0                 # |center - med8| > thr -> replace
    gamma_sel: int = 0               # 0 bypass, 1 encode 1/2.2, 2 decode 2.2
    width: int = 32                  # static geometry bound (module param)
    height: int = 24
    bits: int = 8
    ch: int = 3

    def __post_init__(self):
        if self.bits not in (8, 10):
            raise ValueError('bits must be 8 or 10')
        if self.ch not in (1, 3):
            raise ValueError('ch must be 1 or 3')
        if self.width < 1 or self.height < 1:
            raise ValueError('static geometry must be >= 1')
        if self.img_w != self.width or self.img_h != self.height:
            raise ValueError('img_w/img_h must equal static geometry')
        if len(self.blc) != 3 or len(self.wb) != 3:
            raise ValueError('blc/wb need exactly 3 channel fields')
        if any(not 0 <= v <= mpx(self.bits) for v in self.blc):
            raise ValueError('blc offset out of range')
        if any(not 0 <= v < (1 << GAIN_W) for v in self.wb):
            raise ValueError('wb gain out of range')
        if not 0 <= self.dpc_thr <= mpx(self.bits):
            raise ValueError('dpc_thr out of range')
        if self.gamma_sel not in GAMMA_SELS:
            raise ValueError('gamma_sel must be 0, 1 or 2')


def widths(bits=8, ch=3, width=32, height=24):
    """Single source of truth for derived RTL/vector widths (CLOG2 rules)."""
    def clog2(v):
        return max(1, (v - 1).bit_length())
    pw = ch * bits
    fp = width * height
    return {
        'bits': bits, 'ch': ch, 'pw': pw,
        'xw': max(1, clog2(width)), 'yw': max(1, clog2(height)),
        'cwx': clog2(width + 1), 'cwy': clog2(height + 1),
        'sumw': clog2(fp * mpx(bits) + 1),    # AWB per-channel frame sum
        'ow': clog2(fp + 8),                  # in-flight counter bound
        'ew': pw + 2,                         # expected word: {sof,eol,pix}
    }


def cfgw(bits, width, height):
    w = widths(bits, 3, width, height)
    return w['cwx'] + w['cwy'] + 3 * bits + 3 * GAIN_W + bits + 2


# --------------------------------------------------------------------------
# Bit-exact per-stage operators (the RTL contract)
# --------------------------------------------------------------------------

def blc_pixel(px, off, bits, ch):
    """Black-level correction: unsigned subtract, clamp at 0."""
    return sum(blc_chan(chan(px, c, bits), off[c], bits) << (c * bits)
               for c in range(ch))


def blc_chan(v, off, bits):
    return (v - off) if v >= off else 0


def wb_chan(v, gain, bits):
    """UQ4.8 gain with round-half-up and saturation."""
    return min(mpx(bits), (v * gain + 128) >> GAIN_FRAC)


def wb_pixel(px, gains, bits, ch):
    return sum(wb_chan(chan(px, c, bits), gains[c], bits) << (c * bits)
               for c in range(ch))


def window3x3(frame, x, y):
    """3x3 REPLICATE window taps, row-major (tap 4 = center)."""
    h, w = _frame(frame)
    taps = []
    for dy in (-1, 0, 1):
        yy = min(max(y + dy, 0), h - 1)
        for dx in (-1, 0, 1):
            xx = min(max(x + dx, 0), w - 1)
            taps.append(frame[yy][xx])
    return taps


def med8(vals):
    """Median of the 8 neighbors: mean of the two middle order statistics,
    floor.  Sorted ascending, med8 = (s[3] + s[4]) >> 1."""
    s = sorted(vals)
    assert len(s) == 8
    return (s[3] + s[4]) >> 1


def dpc_pixel_window(taps, thr, bits, ch):
    """DPC on one packed-pixel 3x3 window (tap 4 = center).  Per channel:
    defect = |center - med8(neighbors)| > thr -> out = med8 else center."""
    center = taps[4]
    outs = []
    for c in range(ch):
        ctr = chan(center, c, bits)
        nb = [chan(t, c, bits) for i, t in enumerate(taps) if i != 4]
        m = med8(nb)
        d = ctr - m if ctr >= m else m - ctr
        outs.append(m if d > thr else ctr)
    return packpix(outs, bits)


def gamma_nodes(bits, sel):
    """33-node table for PWL gamma.  sel=1: x^(1/2.2) encode;
    sel=2: x^2.2 decode; sel=0: identity (bypassed, table unused).
    Nodes are round-half-up of MPX * (x/MPX)^expo at x = i*STEP
    (i=32 lands on MPX)."""
    mp = mpx(bits)
    step = 1 << (bits - 5)
    if sel == 0:
        return [min(i * step, mp) for i in range(GAMMA_NODES)]
    e = 1.0 / 2.2 if sel == 1 else 2.2
    vals = []
    for i in range(GAMMA_NODES):
        x = min(i * step, mp)
        vals.append(min(mp, int(mp * ((x / mp) ** e) + 0.5)))
    return vals


def gamma_chan(v, sel, bits):
    """32-segment piecewise-linear LUT, RNE interpolation.  sel=0 bypasses."""
    if sel == 0:
        return v
    fb = bits - 5
    idx = v >> fb
    frac = v & ((1 << fb) - 1)
    nodes = gamma_nodes(bits, sel)
    y0, y1 = nodes[idx], nodes[idx + 1]
    return y0 + (((y1 - y0) * frac + (1 << (fb - 1))) >> fb)


def gamma_pixel(px, sel, bits, ch):
    return sum(gamma_chan(chan(px, c, bits), sel, bits) << (c * bits)
               for c in range(ch))


def dpc_frame(frame, thr, bits, ch):
    h, w = _frame(frame)
    return [[dpc_pixel_window(window3x3(frame, x, y), thr, bits, ch)
             for x in range(w)] for y in range(h)]


def apply_blc(frame, cfg):
    h, w = _frame(frame)
    return [[sum(blc_chan(chan(frame[y][x], c, cfg.bits), cfg.blc[c], cfg.bits)
                 << (c * cfg.bits) for c in range(cfg.ch))
             for x in range(w)] for y in range(h)]


def apply_wb(frame, cfg):
    h, w = _frame(frame)
    return [[wb_pixel(frame[y][x], cfg.wb, cfg.bits, cfg.ch)
             for x in range(w)] for y in range(h)]


def apply_gamma(frame, cfg):
    h, w = _frame(frame)
    return [[gamma_pixel(frame[y][x], cfg.gamma_sel, cfg.bits, cfg.ch)
             for x in range(w)] for y in range(h)]


def pipeline(frame, cfg, crosscheck=True):
    """Bit-exact end-to-end: BLC -> WB -> DPC -> gamma.  Returns the output
    frame (list of packed-pixel rows)."""
    h, w = _frame(frame)
    if w != cfg.img_w or h != cfg.img_h:
        raise ValueError('frame does not match config geometry')
    if max(v for r in frame for v in r) >= (1 << (cfg.ch * cfg.bits)):
        raise ValueError('pixel exceeds configured width')
    f = apply_blc(frame, cfg)
    awb = awb_sums(f, cfg.ch, cfg.bits)          # stats tap post-BLC
    f = apply_wb(f, cfg)
    f = dpc_frame(f, cfg.dpc_thr, cfg.bits, cfg.ch)
    f = apply_gamma(f, cfg)
    if crosscheck:
        # Independent re-check of the DPC stage with an explicit slow path.
        ref = apply_wb(apply_blc(frame, cfg), cfg)
        for y in range(h):
            for x in range(w):
                taps = window3x3(ref, x, y)
                for c in range(cfg.ch):
                    nb = sorted(chan(t, c, cfg.bits)
                                for i, t in enumerate(taps) if i != 4)
                    m = (nb[3] + nb[4]) >> 1
                    ctr = chan(ref[y][x], c, cfg.bits)
                    exp = m if abs(ctr - m) > cfg.dpc_thr else ctr
                    assert chan(f[y][x], c, cfg.bits) == \
                        gamma_chan(exp, cfg.gamma_sel, cfg.bits)
    return f, awb


def awb_sums(blc_frame, ch, bits):
    """Per-channel frame sums on post-BLC data (the defined AWB statistics)."""
    h, w = _frame(blc_frame)
    sums = [0, 0, 0]
    for r in blc_frame:
        for px in r:
            for c in range(ch):
                sums[c] += chan(px, c, bits)
    return sums


def gray_world_gains(sums, npix, ch=3):
    """Host-side gray-world AWB estimate (NOT in RTL): gains that equalize the
    channel means to their common mean, quantized to UQ4.8 with clamp.
    mean_c = sums[c]/npix; target = mean of channel means.
    gain_c = round_half_up(256 * target / mean_c), clamped to [0,4095];
    a zero mean yields the neutral gain 256 (documented degenerate rule).
    Accuracy: exact on scenes whose true illuminant makes equal channel
    means; biased otherwise - gray-world assumption, documented in SPEC."""
    means = [Fraction(sums[c], npix) for c in range(ch)]
    if ch == 1:
        return [256, 256, 256]
    target = sum(means) / 3
    out = []
    for c in range(3):
        if c < ch and means[c] > 0:
            g = int(256 * target / means[c] + Fraction(1, 2))
            out.append(min((1 << GAIN_W) - 1, g))
        else:
            out.append(256)
    return out


# --------------------------------------------------------------------------
# Float reference (independent real-valued semantics)
# --------------------------------------------------------------------------

def float_pipeline(frame, cfg):
    """Real-valued BLC/WB/DPC/gamma.  BLC and DPC are exact in integer
    arithmetic already; WB uses real gain*pixel; gamma uses real pow.
    Returns (out_frame_float, awb_sums)."""
    h, w = _frame(frame)
    sums = [0, 0, 0]
    post = []
    for r in frame:
        orow = []
        for px in r:
            nv = 0
            for c in range(cfg.ch):
                b = max(0, chan(px, c, cfg.bits) - cfg.blc[c])
                sums[c] += b
                # float gain application, then the documented integer
                # quantization (RNE + clamp) shared with the RTL contract.
                nv |= min(mpx(cfg.bits),
                          int(b * cfg.wb[c] + 128) >> GAIN_FRAC) << (c * cfg.bits)
            orow.append(nv)
        post.append(orow)
    # DPC operates on the quantized WB domain in both models; gamma is the
    # only stage where the float reference deviates (real pow vs PWL LUT).
    dpc = dpc_frame(post, cfg.dpc_thr, cfg.bits, cfg.ch)
    e = {0: None, 1: 1.0 / 2.2, 2: 2.2}[cfg.gamma_sel]
    out = []
    for r in dpc:
        orow = []
        for px in r:
            nv = 0
            for c in range(cfg.ch):
                v = chan(px, c, cfg.bits)
                if e is None:
                    fv = float(v)
                else:
                    fv = mpx(cfg.bits) * ((v / mpx(cfg.bits)) ** e)
                nv |= min(mpx(cfg.bits), int(fv + 0.5)) << (c * cfg.bits)
            orow.append(nv)
        out.append(orow)
    return out, sums


# --------------------------------------------------------------------------
# Vector packing (mirrors the tb_* port order)
# --------------------------------------------------------------------------

def pack_input(px, sof, eol, bits, ch):
    pw = ch * bits
    return (sof << (pw + 1)) | (eol << pw) | px


def pack_expected(px, sof, eol, bits, ch):
    """MSB->LSB: tuser, tlast, tdata."""
    return pack_input(px, sof, eol, bits, ch)


def pack_config(cfg):
    """MSB->LSB: img_w(CWX), img_h(CWY), blc2,blc1,blc0 (BITS each),
    wb2,wb1,wb0 (12 each), dpc_thr(BITS), gamma_sel(2)."""
    w = widths(cfg.bits, cfg.ch, cfg.width, cfg.height)
    wb_part = 0
    for c in range(3):
        wb_part |= (cfg.wb[c] & ((1 << GAIN_W) - 1)) << (c * GAIN_W)
    blc_part = 0
    for c in range(3):
        blc_part |= (cfg.blc[c] & mpx(cfg.bits)) << (c * cfg.bits)
    word = cfg.img_w
    word = (word << w['cwy']) | cfg.img_h
    word = (word << (3 * cfg.bits)) | blc_part
    word = (word << (3 * GAIN_W)) | wb_part
    word = (word << cfg.bits) | cfg.dpc_thr
    word = (word << 2) | (cfg.gamma_sel & 3)
    return word


def unpack_config(word, bits, width, height):
    w = widths(bits, 3, width, height)
    gsel = word & 3
    word >>= 2
    thr = word & mpx(bits)
    word >>= bits
    wb = [(word >> (c * GAIN_W)) & ((1 << GAIN_W) - 1) for c in range(3)]
    word >>= 3 * GAIN_W
    blc = [(word >> (c * bits)) & mpx(bits) for c in range(3)]
    word >>= 3 * bits
    ih = word & ((1 << w['cwy']) - 1)
    iw = (word >> w['cwy']) & ((1 << w['cwx']) - 1)
    return iw, ih, blc, wb, thr, gsel


def pack_awb(sums, sumw):
    """MSB->LSB: sum2, sum1, sum0."""
    return ((sums[2] << (2 * sumw)) | (sums[1] << sumw) | sums[0])


# --------------------------------------------------------------------------
# Generated RTL artifact: rtl/gamma_table.vh
# --------------------------------------------------------------------------

VH_HEADER = """// GENERATED by models/reference.py emit_gamma_vh(); do not edit.
// 33-node piecewise-linear gamma node tables, one function per BITS/curve.
// node[i] = round_half_up(MPX * (x/MPX)^e) at x = min(i*2^(BITS-5), MPX).
//   enc: e = 1/2.2 (display encode)   dec: e = 2.2 (display decode)
"""


def _emit_func(name, bits, sel):
    nodes = gamma_nodes(bits, sel)
    lines = ['function automatic [%d:0] %s(input [5:0] idx);' % (bits - 1, name),
             '  case (idx)']
    for i, v in enumerate(nodes):
        lines.append("    6'd%d: %s = %d'd%d;" % (i, name, bits, v))
    lines.append("    default: %s = %d'd%d;" % (name, bits, nodes[-1]))
    lines.append('  endcase')
    lines.append('endfunction')
    return '\n'.join(lines)


def emit_gamma_vh():
    """Return the canonical text of rtl/gamma_table.vh."""
    parts = [VH_HEADER]
    parts.append(_emit_func('gamma_node8_enc', 8, 1))
    parts.append('')
    parts.append(_emit_func('gamma_node8_dec', 8, 2))
    parts.append('')
    parts.append(_emit_func('gamma_node10_enc', 10, 1))
    parts.append('')
    parts.append(_emit_func('gamma_node10_dec', 10, 2))
    return '\n'.join(parts) + '\n'
