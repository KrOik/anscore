"""Generate the 64-phase x 6-tap Lanczos-3 coefficient table.

Outputs:
  scale_lanczos3.vh   - Verilog function returning a packed 72-bit row
                        (6 taps x 13-bit signed, tap t at bits [t*13 +: 13])
  scale_coeffs.json   - same table for the bit-exact golden model

Kernel: h(d) = sinc(d) * sinc(d/3) for |d| < 3 (Lanczos-3, 6 taps).
For output center cx = base + f (f in [0,1)), tap t multiplies the input
pixel at position base-2+t; its distance to the center is d = t-2-f.
Coefficients are Q1.11 signed (sum forced to exactly 2048).
"""
import json, math, pathlib

PHASES = 64
TAPS = 6
SCALE = 2048  # Q1.11

def lanczos3(d):
    if d == 0:
        return 1.0
    if abs(d) >= 3.0:
        return 0.0
    return (math.sin(math.pi * d) / (math.pi * d)) * \
           (math.sin(math.pi * d / 3.0) / (math.pi * d / 3.0))

def gen_table():
    table = []
    for k in range(PHASES):
        f = k / PHASES
        q = [int(round(lanczos3(t - 2 - f) * SCALE)) for t in range(TAPS)]
        # Force the quantized sum to exactly SCALE on the largest tap.
        err = SCALE - sum(q)
        if err:
            i = max(range(TAPS), key=lambda j: abs(q[j]))
            q[i] += err
        assert sum(q) == SCALE
        assert all(-4096 <= c <= 4095 for c in q)
        table.append(q)
    return table

def main():
    here = pathlib.Path(__file__).resolve().parent
    table = gen_table()
    lines = ["// Auto-generated by gen_scale_coeffs.py -- do not edit.",
             "// Lanczos-3, 64 phases x 6 taps, signed Q1.11 (13-bit container), sum=2048.",
             "// Tap t occupies bits [t*13 +: 13] of the returned row.",
             "function [77:0] scale_coef_row;",
             "    input [5:0] ph;",
             "    begin",
             "        case (ph)"]
    for k, row in enumerate(table):
        packed = 0
        for t, c in enumerate(row):
            packed |= (c & 0x1FFF) << (13 * t)
        lines.append(f"            6'd{k}: scale_coef_row = 78'h{packed:020X};")
    lines += ["            default: scale_coef_row = 78'h00000000000000000000;",
              "        endcase",
              "    end",
              "endfunction"]
    (here / 'scale_lanczos3.vh').write_text('\n'.join(lines) + '\n')
    (here / 'scale_coeffs.json').write_text(json.dumps(
        {"phases": PHASES, "taps": TAPS, "scale": SCALE, "table": table}))
    print(f"wrote {PHASES}x{TAPS} table; phase0={table[0]} phase32={table[32]}")

if __name__ == '__main__':
    main()
