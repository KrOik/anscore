"""Generate dsp_rate_harness_rom.vh - canned per-core configuration tables.

Single source of truth for the frozen RTL literals.  The board protocol
(protocol.py) recomputes the same tables directly from the independent
models, so a hand-edited ROM is caught as a board mismatch.

Layouts (low bits first):

  rs_cfg(sel) -> {coeffs[2304], taps[8], m[4], l[4]}         (2320 bits)
      coeffs[i*18 +: 18] = signed18 Q3.15 tap i (resampler polyphase order)
  hb_cfg(sel) -> {ucoeffs[162], taps[6]}                     (168 bits)
      ucoeffs[i*18 +: 18] = i-th unique halfband pair coeff
  dd_cfg(sel) -> {coeffs[288], taps[6], shift[6], rate[7],
                  init[32], inc[32]}                         (371 bits)
      coeffs[i*18 +: 18] = i-th unique symmetric FIR coeff (pack_coeffs)

Run:  python gen_rom.py   (writes dsp_rate_harness_rom.vh beside itself)
"""
import importlib.util, json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE.parents[1]


def load(name, rel):
    spec = importlib.util.spec_from_file_location(name, LIB / rel)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def _hex(v, bits):
    return "%d'h%0*x" % (bits, (bits + 3) // 4, v & ((1 << bits) - 1))


def pack18(coeffs, width):
    v = 0
    for i, c in enumerate(coeffs):
        assert -131072 <= c <= 131071, c
        v |= (c & 0x3FFFF) << (18 * i)
    assert v < (1 << width)
    return v


# ---------------------------------------------------------------- tables --
# index -> description kept in CANNED_JSON for the session log
def build_tables():
    rs_mod = load('rs_ref', 'dsp/resampler/models/reference.py')
    hb_mod = load('hb_ref', 'dsp/halfband/models/reference.py')
    dd_mod = load('dd_ref', 'dsp/ddcduc/models/model.py')

    resampler = []
    for l, m, taps in [(1, 2, 48), (2, 1, 48), (3, 2, 48),
                     (2, 3, 48), (1, 1, 16), (4, 1, 48)]:
        cfg, _h = rs_mod.design(l, m, taps=taps)
        assert len(cfg.coefficients) == taps
        resampler.append(dict(l=l, m=m, taps=taps,
                              coeffs=pack18(cfg.coefficients, 2304)))

    halfband = []
    for taps in (7, 15, 23, 31):
        uc, _h, hq = hb_mod.design_halfband(taps)
        assert sum(hq) == 32768
        halfband.append(dict(taps=taps, ucoeffs=pack18(uc, 162)))

    def comp(order, rate, taps):
        if taps == 1:
            return 0
        uc, _g, _hq = dd_mod.design_comp(order, rate, taps)
        return pack18(uc, 288)

    ddc = [
        dict(inc=dd_mod.inc_for(0.10), init=0x00000000, rate=4, shift=6,
             taps=1, coeffs=comp(3, 4, 1)),
        dict(inc=dd_mod.inc_for(-0.0625), init=0x10000000, rate=8, shift=9,
             taps=1, coeffs=comp(3, 8, 1)),
        dict(inc=dd_mod.inc_for(0.125), init=0x00000000, rate=16, shift=12,
             taps=7, coeffs=comp(3, 16, 7)),
        dict(inc=dd_mod.inc_for(0.02), init=0x7FFF0000, rate=64, shift=18,
             taps=1, coeffs=comp(3, 64, 1)),
    ]
    duc = [
        dict(inc=dd_mod.inc_for(0.15), init=0x00000000, rate=2, shift=3,
             taps=1, coeffs=comp(3, 2, 1)),
        dict(inc=dd_mod.inc_for(-0.075), init=0x22222222, rate=4, shift=6,
             taps=1, coeffs=comp(3, 4, 1)),
        dict(inc=dd_mod.inc_for(0.25), init=0x00000000, rate=8, shift=9,
             taps=1, coeffs=comp(3, 8, 1)),
        dict(inc=dd_mod.inc_for(0.30), init=0x00000000, rate=4, shift=6,
             taps=5, coeffs=comp(3, 4, 5)),
    ]
    return resampler, halfband, ddc, duc


def emit(resampler, halfband, ddc, duc):
    lines = [
        '// AUTO-GENERATED by gen_rom.py - do not hand-edit.',
        '// Canned rate-change configuration tables for dsp_rate_harness.',
        '// protocol.py recomputes every entry from the independent models.',
        '',
        'function [2319:0] rs_cfg(input [3:0] sel);',
        ' begin case(sel)']
    for i, e in enumerate(resampler):
        lines.append("  4'd%d: rs_cfg={%s,8'd%d,4'd%d,4'd%d};"
                     % (i, _hex(e['coeffs'], 2304), e['taps'], e['m'],
                        e['l']))
    lines += ["  default: rs_cfg=2320'd0;",
              '  endcase end',
              'endfunction', '',
              'function [167:0] hb_cfg(input [3:0] sel);',
              ' begin case(sel)']
    for i, e in enumerate(halfband):
        lines.append("  4'd%d: hb_cfg={%s,6'd%d};"
                     % (i, _hex(e['ucoeffs'], 162), e['taps']))
    lines += ["  default: hb_cfg=168'd0;",
              '  endcase end',
              'endfunction', '']

    for name, table in (('dd_cfg', ddc), ('du_cfg', duc)):
        lines += ['function [370:0] %s(input [3:0] sel);' % name,
                  ' begin case(sel)']
        for i, e in enumerate(table):
            lines.append("  4'd%d: %s={%s,6'd%d,6'd%d,7'd%d,32'h%08x,32'h%08x};"
                         % (i, name, _hex(e['coeffs'], 288), e['taps'],
                            e['shift'], e['rate'], e['init'], e['inc']))
        lines += ["  default: %s=371'd0;" % name,
                  '  endcase end',
                  'endfunction', '']
    return '\n'.join(lines)


def main():
    rs, hb, ddc, duc = build_tables()
    out = emit(rs, hb, ddc, duc)
    (HERE / 'dsp_rate_harness_rom.vh').write_text(out)
    (HERE / 'canned_configs.json').write_text(json.dumps(dict(
        resampler=rs, halfband=hb, ddc=ddc, duc=duc), indent=2))
    print('wrote', HERE / 'dsp_rate_harness_rom.vh')


if __name__ == '__main__':
    main()
