"""BLK2/RES2 rate-change block protocol for dsp_rate_harness.

Transport shape adapter: unlike BLK1/RES1 (1:1 beat mapping), a BLK2 packet
declares in_count input words plus the host-computed out_expect output count.
The DUT may emit 0..128 result words; the harness terminates on the core's
flush/drain condition, the 128-word capture bound, or the 65535-cycle
watchdog, and self-reports a count mismatch in flags[5].

Packet:  'BLK2' tag(4LE) config(4LE) in_count(1) stall(1) out_expect(1)
         rsvd(1, must be 0) + in_count * 32-bit words
Report:  'RES2' tag(4) config(4) in_count(1) flags(1) inc(1) outc(1)
         cycles(4LE) + outc * 32-bit words

flags: bit0 malformed packet, bit1 rx framing error, bit2 rx outside LOAD,
       bit3 config rejected, bit4 watchdog, bit5 outc != out_expect,
       bit6 output-RAM overflow / core capacity error, bit7 sticky clip.

CORE map: 0 polyphase_resampler, 1 halfband_decim, 2 halfband_interp,
          3 ddc_stream, 4 duc_stream, 5 median_stream (ISP),
          6 pfb_stream (M=8, P=8), 7 framediff_stream (ISP, 4x4, 4 frames).
          config_word[3:0]
          selects a canned configuration generated by gen_rom.py into
          dsp_rate_harness_rom.vh; the same tables are recomputed here from the
          independent models (no DUT-derived golden).  CORE 5 has no
          coefficients: config_word[0] selects the padding variant
          (0 = ZERO, 1 = REPLICATE) and the block must carry exactly
          MEDIAN_PIXELS words, one 8x8 frame.  CORE 6 has one static geometry
          (M/P are elaboration parameters), so it accepts config 0 only and its
          block length must be a whole number of M-sample frames.

Word packing:
  cores 0..2 : {15'b0, clip, y[15:0]}   (clip = m_tuser)
  cores 3..4 : {q[15:0], i[15:0]}       (per-beat clip folded to flags[7])
  core 5     : {21'b0, marker_error, eol, sof, pixel[7:0]}
  core 6     : {im[15:0], re[15:0]}     (the core's own channel beat)
  core 7     : {20'b0, scene_change, marker_error, eol, sof, pixel[7:0]}
  core 8     : {6'b0, eol, sof, pixel[23:0]}   (ISP-14 RGB pixel, BITS=8)
"""
import importlib.util
import json, random, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE.parents[1] if (HERE.parents[1] / 'dsp').is_dir() else HERE.parent

IN_CAP = 64
OUT_CAP = 128
MEDIAN_W = 8                   # CORE 5 frame geometry: 8 x 8 unsigned pixels
MEDIAN_H = 8
MEDIAN_PIXELS = MEDIAN_W * MEDIAN_H
CORE_NAMES = {0: 'resampler', 1: 'hb_decim', 2: 'hb_interp',
              3: 'ddc', 4: 'duc', 5: 'median', 6: 'pfb', 7: 'framediff',
              8: 'ccm'}
# CORE 6 is one static geometry: pfb_stream takes M and P as elaboration
# parameters, so a board image verifies one channelizer shape, not a sweep.
PFB_M = 8                      # channels per frame (critically sampled)
PFB_P = 8                      # taps per polyphase branch
# CORE 7 is isp/framediff (ISP-17), a core whose whole job is to remember the
# previous frame.  Its reference lives in an internal RAM, so the transport only
# has to keep the core alive across frames -- at a 4x4 geometry FOUR whole
# frames fit in the 64 words one block already carries (FD_PIXELS = 4*4*4), the
# same word count CORE 5 spends on one 8x8 frame.  That covers seeding, all
# three modes, and a scene change followed by its RESET or FAST_ADAPT recovery
# inside a single block, so no second request shape is needed to verify them.
# What a block still cannot show is a geometry change, because the harness
# commits one bundle per block; that needs cross-block persistence.
FD_W = 4
FD_H = 4
FD_FRAMES = 4
FD_PIXELS = FD_W * FD_H * FD_FRAMES


def _variant():
    for base in (HERE, Path.cwd()):
        v = base / 'variant.json'
        if v.exists():
            return json.loads(v.read_text())
    return {}


_LAST_CORE = [0]


def _core():
    v = _variant().get('core')
    return _LAST_CORE[0] if v is None else v


def _load(name, rel):
    frozen = HERE / (name + '.py')
    src = frozen if frozen.exists() else LIB / rel
    spec = importlib.util.spec_from_file_location(name, src)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


