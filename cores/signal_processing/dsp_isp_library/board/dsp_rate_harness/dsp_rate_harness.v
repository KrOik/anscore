// Rate-change / variable-output-count board harness for dsp_isp_library.
// Same proven plumbing as dsp_stream_harness (BLK-family packet -> bounded
// synchronous RAM -> DUT -> RAM -> UART report) but WITHOUT the 1:1
// input/output assumption:
//
//   packet 'BLK2': tag(4) config(4) in_count(1) stall(1) out_expect(1)
//                  rsvd(1) then in_count * 32-bit words.
//   report 'RES2': tag(4) config(4) in_count(1) flags(1) inc(1) outc(1)
//                  cycles(4) then outc * 32-bit words.
//
// RUN feeds in_count words (0 < in_count <= 64), then terminates on the
// per-core done condition:
//   * flush cores (0..2): flush_valid handshake after last input, then
//     flush_done; the final cycle waits for the last pending output beat.
//   * drain cores (3..4): 4095 consecutive quiet cycles after the last
//     input/output (no explicit flush port exists on the DDC/DUC chain).
// Output capture RAM is 128 words; an output present while the store is
// full sets flags[6] and ends the run (never wraps the write address).
// Watchdog flags[4] at 65535 cycles.  At every RUN exit a mismatch between
// the captured outc and the packet's declared out_expect sets flags[5].
//
// flags: [0] malformed packet  [1] UART rx error  [2] rx outside LOAD
//        [3] config rejected   [4] watchdog      [5] outc != out_expect
//        [6] output RAM overflow / core capacity_error / fifo_overflow
//        [7] sticky output clip (ddc/duc m_clip; resampler/halfband tuser)
//
// CORE map:
//   0 polyphase_resampler  (DSP-01)  word={15'b0,clip,y16}
//   1 halfband_decim       (DSP-10)  word={15'b0,clip,y16}
//   2 halfband_interp      (DSP-10)  word={15'b0,clip,y16}
//   3 ddc_stream CIC_STAGES=3 (DSP-03) word={q16,i16}, clip->flags[7]
//   4 duc_stream CIC_STAGES=3 (DSP-03) word={q16,i16}, clip->flags[7]
//
// config_word[3:0] selects a canned config from dsp_rate_harness_rom.vh
// (generated by gen_rom.py from the independent models); all higher bits
// must be zero.  Out-of-range index or reserved bits -> flags[3] reject.
module dsp_rate_harness #(parameter CORE=0)(
 input wire clk,uart_rx_pin,output wire uart_tx,dbg_uart);
 localparam integer IN_CAP=64;
 localparam integer OUT_CAP=128;
 localparam integer QUIET_MAX=4095;
 localparam HAS_FLUSH=(CORE<=2);
 reg [12:0] por=0;
 always @(posedge clk) if(!por[12]) por<=por+1'b1;
 wire rst_n=por[12];
 localparam LOAD=0,RESET=1,CONFIG=2,CHECK=3,PREFETCH=4,RUN=5,HEADER=6,READ=7,DATA=8;
 reg [3:0] state=LOAD;
 reg [7:0] index,byte_index,count,stall,flags,out_expect,rsvd_b;
 reg [31:0] tag,config_word,assembly,cycles;
 reg [6:0] input_count;
 reg [7:0] output_count,read_index;
 reg [2:0] phase;
 reg [11:0] quiet;
 reg flush_sent,drained;
 wire [31:0] input_q,output_q;
 wire [7:0] rx_data;
 wire rx_valid,rx_error;
 uart_rx rx(.clk(clk),.rst_n(rst_n),.clk_en(1'b1),.rx_pin(uart_rx_pin),.rx_data(rx_data),.rx_valid(rx_valid),.rx_ack(rx_valid),.framing_err(rx_error));
 wire in_ready,out_valid,cfg_ready,cfg_error,clip_w,cap_err,flush_rdy,flush_done;
 wire [31:0] result;
 wire in_valid=state==RUN && input_count<count;
 wire out_ready=state==RUN && phase>=stall[2:0];
 wire input_fire=in_valid && in_ready;
 wire output_fire=out_valid && out_ready;
 wire core_reset=rst_n && state!=RESET;
 wire inputs_done=input_count==count;
 wire flush_req=HAS_FLUSH && state==RUN && inputs_done && !flush_sent && !drained;

 `include "dsp_rate_harness_rom.vh"

 generate
 if(CORE==0) begin: g_rs
  wire [2319:0] e=rs_cfg(config_word[3:0]);
  reg seen_done,seen_err;wire c_done,c_err;
  always @(posedge clk) begin
   if(!core_reset) begin seen_done<=0;seen_err<=0;end
   else begin if(c_done)seen_done<=1;if(c_err)seen_err<=1;end
  end
  wire bad=(|config_word[31:4]) || (config_word[3:0]>5);
  wire signed [15:0] core_y;
  assign cfg_ready=seen_done | bad;
  assign cfg_error=seen_err | bad;
  assign result={15'b0,clip_w,core_y};
  polyphase_resampler #(.MAX_TAPS(128),.MAX_INPUTS(65535)) core(
   .clk(clk),.rst_n(core_reset),
   .s_tdata(input_q[15:0]),.s_tvalid(in_valid),.s_tready(in_ready),
   .m_tdata(core_y),.m_tuser(clip_w),.m_tvalid(out_valid),.m_tready(out_ready),
   .cfg_valid(state==CONFIG && !bad),.cfg_ready(),
   .cfg_l(e[3:0]),.cfg_m(e[7:4]),.cfg_taps(e[15:8]),.cfg_coeffs(e[2319:16]),
   .cfg_done(c_done),.cfg_error(c_err),
   .flush_valid(flush_req),.flush_ready(flush_rdy),.flush_done(flush_done),
   .input_count(),.output_count(),.capacity_error(cap_err));
 end else if(CORE==1 || CORE==2) begin: g_hb
  wire [167:0] e=hb_cfg(config_word[3:0]);
  reg seen_done,seen_err;wire c_done,c_err;
  always @(posedge clk) begin
   if(!core_reset) begin seen_done<=0;seen_err<=0;end
   else begin if(c_done)seen_done<=1;if(c_err)seen_err<=1;end
  end
  wire bad=(|config_word[31:4]) || (config_word[3:0]>3);
  wire signed [15:0] core_y;
  assign cfg_ready=seen_done | bad;
  assign cfg_error=seen_err | bad;
  assign result={15'b0,clip_w,core_y};
  // LANES=1 keeps the Tang DSP-class count at 4 total (1 MAC + 3 small
  // index multipliers); bit-exact outputs are LANES-invariant, only the
  // per-output round count grows (documented throughput bound).
  if(CORE==1) begin: b_decim
   halfband_decim #(.LANES(1)) core(.clk(clk),.rst_n(core_reset),
    .s_tdata(input_q[15:0]),.s_tvalid(in_valid),.s_tready(in_ready),
    .m_tdata(core_y),.m_tuser(clip_w),.m_tvalid(out_valid),.m_tready(out_ready),
    .cfg_valid(state==CONFIG && !bad),.cfg_ready(),
    .cfg_taps(e[5:0]),.cfg_coeffs(e[167:6]),
    .cfg_done(c_done),.cfg_error(c_err),
    .flush_valid(flush_req),.flush_ready(flush_rdy),.flush_done(flush_done),
    .input_count(),.output_count(),.capacity_error(cap_err));
  end else begin: b_interp
   halfband_interp #(.LANES(1)) core(.clk(clk),.rst_n(core_reset),
    .s_tdata(input_q[15:0]),.s_tvalid(in_valid),.s_tready(in_ready),
    .m_tdata(core_y),.m_tuser(clip_w),.m_tvalid(out_valid),.m_tready(out_ready),
    .cfg_valid(state==CONFIG && !bad),.cfg_ready(),
    .cfg_taps(e[5:0]),.cfg_coeffs(e[167:6]),
    .cfg_done(c_done),.cfg_error(c_err),
    .flush_valid(flush_req),.flush_ready(flush_rdy),.flush_done(flush_done),
    .input_count(),.output_count(),.capacity_error(cap_err));
  end
 end else if(CORE==3 || CORE==4) begin: g_dd
  wire [370:0] e=(CORE==3) ? dd_cfg(config_word[3:0]) : du_cfg(config_word[3:0]);
  reg seen_done,seen_err;wire c_done,c_err;
  always @(posedge clk) begin
   if(!core_reset) begin seen_done<=0;seen_err<=0;end
   else begin if(c_done)seen_done<=1;if(c_err)seen_err<=1;end
  end
  wire bad=(|config_word[31:4]) || (config_word[3:0]>3);
  assign cfg_ready=seen_done | bad;
  assign cfg_error=seen_err | bad;
  wire signed [15:0] oi,oq;
  assign result={oq[15:0],oi[15:0]};
  assign flush_rdy=1'b0;assign flush_done=1'b0;
  if(CORE==3) begin: b_ddc
   // FIFO_REGS=1: skid FIFO on fabric regs (GW2A CE-gated BSRAM read
   // divergence observed for this DPX9B pattern; see session notes).
   ddc_stream #(.CIC_STAGES(3),.FIFO_REGS(1)) core(.clk(clk),.rst_n(core_reset),
    .s_i_tdata(input_q[15:0]),.s_q_tdata(input_q[31:16]),
    .s_tvalid(in_valid),.s_tready(in_ready),
    .m_i_tdata(oi),.m_q_tdata(oq),.m_clip(clip_w),
    .m_tvalid(out_valid),.m_tready(out_ready),
    .cfg_valid(state==CONFIG && !bad),.cfg_ready(),
    .cfg_phase_inc(e[31:0]),.cfg_phase_init(e[63:32]),
    .cfg_rate(e[70:64]),.cfg_shift(e[76:71]),.cfg_taps(e[82:77]),
    .cfg_coeffs(e[370:83]),
    .cfg_done(c_done),.cfg_error(c_err),
    .input_count(),.output_count(),.sat_count(),.fifo_overflow(cap_err));
  end else begin: b_duc
   duc_stream #(.CIC_STAGES(3)) core(.clk(clk),.rst_n(core_reset),
    .s_i_tdata(input_q[15:0]),.s_q_tdata(input_q[31:16]),
    .s_tvalid(in_valid),.s_tready(in_ready),
    .m_i_tdata(oi),.m_q_tdata(oq),.m_clip(clip_w),
    .m_tvalid(out_valid),.m_tready(out_ready),
    .cfg_valid(state==CONFIG && !bad),.cfg_ready(),
    .cfg_phase_inc(e[31:0]),.cfg_phase_init(e[63:32]),
    .cfg_rate(e[70:64]),.cfg_shift(e[76:71]),.cfg_taps(e[82:77]),
    .cfg_coeffs(e[370:83]),
    .cfg_done(c_done),.cfg_error(c_err),
    .input_count(),.output_count(),.sat_count());
   assign cap_err=1'b0;
  end
 end else begin: bad
  assign in_ready=1'b0;assign out_valid=1'b0;assign cfg_ready=1'b1;
  assign cfg_error=1'b1;assign clip_w=1'b0;assign cap_err=1'b0;
  assign flush_rdy=1'b0;assign flush_done=1'b0;assign result=32'b0;
 end
 endgenerate

 // Dedicated synchronous RAM processes: never reset storage.
 // Input store: 64 words, same lookahead pattern as dsp_stream_harness.
 wire input_read=state==PREFETCH || in_valid;
 wire [5:0] input_address=state==PREFETCH ? 6'd0 :
     (input_fire ? input_count[5:0]+6'd1 : input_count[5:0]);
 wire input_write=rst_n && state==LOAD && rx_valid && !rx_error && index>=16 && byte_index[1:0]==3;
 block_ram #(.MEM_IMPL(1)) input_store(.clk(clk),.we(input_write),.waddr(byte_index[7:2]),.wdata({rx_data,assembly[23:0]}),.re(input_read),.raddr(input_address),.q(input_q));
 // Output store: 128 words = two proven 64x32 banks, MSB-selected.
 wire owe=output_fire && !output_count[7];
 wire [31:0] oq_lo,oq_hi;
 wire ore=state==READ;
 block_ram #(.MEM_IMPL(1)) output_lo(.clk(clk),.we(owe && !output_count[6]),.waddr(output_count[5:0]),.wdata(result),.re(ore),.raddr(read_index[5:0]),.q(oq_lo));
 block_ram #(.MEM_IMPL(1)) output_hi(.clk(clk),.we(owe && output_count[6]),.waddr(output_count[5:0]),.wdata(result),.re(ore),.raddr(read_index[5:0]),.q(oq_hi));
 assign output_q=read_index[6] ? oq_hi : oq_lo;
 reg [7:0] tx_data;
 wire tx_ready;
 wire tx_valid=state==HEADER || state==DATA;
 uart_tx tx(.clk(clk),.rst_n(rst_n),.tx_data(tx_data),.tx_data_valid(tx_valid),.tx_data_ready(tx_ready),.tx_pin(uart_tx),.tx_busy());
 assign dbg_uart=uart_tx;
 always @* begin
 tx_data=0;
 if(state==DATA) tx_data=output_q>>(8*byte_index[1:0]);
 else case(index)
 0:tx_data="R";1:tx_data="E";2:tx_data="S";3:tx_data="2";
 4,5,6,7:tx_data=tag>>(8*(index-4));
 8,9,10,11:tx_data=config_word>>(8*(index-8));
 12:tx_data=count;13:tx_data=flags;14:tx_data={1'b0,input_count};15:tx_data=output_count;
 16,17,18,19:tx_data=cycles>>(8*(index-16));
 endcase
 end
 wire run_done = (HAS_FLUSH ? (drained && !out_valid && !output_fire)
                            : (inputs_done && quiet==QUIET_MAX && !out_valid))
              || (output_count[7] && out_valid);
 always @(posedge clk) begin
 if(!rst_n) begin state<=LOAD;index<=0;byte_index<=0;count<=0;stall<=0;flags<=0;out_expect<=0;rsvd_b<=0;tag<=0;config_word<=0;assembly<=0;cycles<=0;input_count<=0;output_count<=0;read_index<=0;phase<=0;quiet<=0;flush_sent<=0;drained<=0;end
 else begin
 if(rx_error) flags[1]<=1;
 if(rx_valid && state!=LOAD) flags[2]<=1;
 case(state)
 LOAD: if(rx_valid && !rx_error) begin
 case(index)
 0: if(rx_data=="B") begin index<=1;flags<={5'd0,flags[2],2'd0};input_count<=0;output_count<=0;cycles<=0;end
 1: if(rx_data=="L") index<=2;else index<=0;
 2: if(rx_data=="K") index<=3;else index<=0;
 3: if(rx_data=="2") index<=4;else index<=0;
 4,5,6,7: begin tag<={rx_data,tag[31:8]};index<=index+1'b1;end
 8,9,10,11: begin config_word<={rx_data,config_word[31:8]};index<=index+1'b1;end
 12:begin count<=rx_data;index<=13;end
 13:begin stall<=rx_data;index<=14;end
 14:begin out_expect<=rx_data;index<=15;end
 15:begin rsvd_b<=rx_data;index<=16;byte_index<=0;
 if(count==0 || count>IN_CAP || stall>7 || out_expect>OUT_CAP || rx_data!=0) begin flags[0]<=1;count<=0;output_count<=0;index<=0;state<=HEADER;end
 end
 default:begin
 byte_index<=byte_index+1'b1;
 if(byte_index[1:0]==0) assembly[7:0]<=rx_data;
 if(byte_index[1:0]==1) assembly[15:8]<=rx_data;
 if(byte_index[1:0]==2) assembly[23:16]<=rx_data;
 if(byte_index=={count[5:0],2'b00}-1'b1) state<=RESET;
 end
 endcase
 end
 RESET:begin input_count<=0;output_count<=0;cycles<=0;phase<=0;quiet<=0;flush_sent<=0;drained<=0;state<=CONFIG;end
 CONFIG:if(cfg_ready) state<=CHECK;
 CHECK:if(cfg_error) begin flags[3]<=1;count<=0;output_count<=0;index<=0;state<=HEADER;end else state<=PREFETCH;
 PREFETCH:state<=RUN;
 RUN:begin
 cycles<=cycles+1'b1;phase<=phase+1'b1;
 if(input_fire) input_count<=input_count+1'b1;
 if(!inputs_done || out_valid || output_fire || input_fire) quiet<=0;
 else quiet<=quiet+1'b1;
 if(flush_req && flush_rdy) flush_sent<=1;
 if(flush_done) drained<=1;
 if(output_fire) begin
  if(!output_count[7]) output_count<=output_count+1'b1;
  else flags[6]<=1;
 end
 if(output_fire && clip_w) flags[7]<=1;
 if(cap_err) flags[6]<=1;
 if(run_done || cycles==32'd65535) begin
  if(cycles==32'd65535) flags[4]<=1;
  if(output_count+(output_fire && !output_count[7] ? 8'd1:8'd0)!=out_expect) flags[5]<=1;
  index<=0;state<=HEADER;
 end
 end
 HEADER:if(tx_ready) begin if(index==19) begin read_index<=0;byte_index<=0;if(output_count==0) begin state<=LOAD;index<=0;end else state<=READ;end else index<=index+1'b1;end
 READ:state<=DATA;
 DATA:if(tx_ready) begin
 if(byte_index[1:0]==3) begin byte_index<=0;read_index<=read_index+1'b1;
 if(read_index+1==output_count) begin state<=LOAD;index<=0;end else state<=READ;
 end else byte_index<=byte_index+1'b1;
 end
 default:state<=LOAD;
 endcase
 end
 end
endmodule
