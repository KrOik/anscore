"""Build and simulate the 25K dock ROM-stimulus board harness for one core.

    python build_rom_25k.py --family dstream --core biquad [--build]

The dock's USB-UART bridge cannot drive the FPGA RX pad, so instead of the 20K
flow (host injects a BLK1/IMG1 packet, reads the report) the case ROM in
stim_25k.v emits the same packets inside the fabric and the report stream is read
over the working TX direction.  Everything that decides pass or fail stays the
frozen family protocol.py: the descriptors come from protocol.cases(), the golden
answers from protocol.oracle()/verify(), and the RTL byte stream is compared
byte-for-byte against rom_stim_25k.py before the reports are graded.

Evidence lands in board/tang25k/harness/evidence/<core>_<stamp>/ as a frozen
build dir that board/remote/run_25k.py --mode rom stages onto the rig.
"""
import argparse, datetime, hashlib, importlib.util, json, re, shutil, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent            # board/tang25k/harness


def _up(path, n):
    """parents[n] that cannot raise: a rig staging dir is shallower than the repo.

    The board round imports this file for split_reports()/grade(), and importing it
    must not depend on living inside the repository tree.
    """
    for _ in range(n):
        path = path.parent
    return path


BOARD = _up(HERE, 2)                              # board
LIB = _up(HERE, 3)                                # dsp_isp_library
ROOT = _up(HERE, 5)                               # repository root
sys.path.insert(0, str(HERE.parent))              # board/tang25k
sys.path.insert(0, str(HERE))
import device_flow                                # noqa: E402

FAMS = {
    'dstream': dict(dir='dsp_stream_harness', dut='dsp_stream_harness', family=0,
                    magic=b'BLK1', rmagic=b'RES1', bad_config=True,
                    image='dstream_25k.fs', sim_rate=2000),
    'isp': dict(dir='isp_stream_harness', dut='isp_stream_harness', family=1,
                magic=b'IMG1', rmagic=b'IMR1', bad_config=False,
                image='isp_25k.fs', sim_rate=6000),
    # A delivery bundle rather than a single core: the CSC -> morphology chain
    # harness, whose framing is the ISP one (IMG1 in, fixed 276-byte IMR1 out).
    'chain_isp': dict(dir='image_harness', dut='image_harness', family=3,
                      magic=b'IMG1', rmagic=b'IMR1', bad_config=False,
                      image='chain_isp_25k.fs', sim_rate=6000,
                      spec='chain25k_spec.py', needs=('CLK_FRE',)),
    # The second delivery bundle: DC -> statistics.  Its packet geometry differs
    # from every other family -- one signed16 sample per case word, so 2 stimulus
    # bytes and a 17-byte DST1 report entry per result.
    'chain_dsp': dict(dir='dsp_chain_harness', dut='dsp_chain_harness', family=4,
                      magic=b'DSC1', rmagic=b'DST1', bad_config=False,
                      image='chain_dsp_25k.fs', sim_rate=3000,
                      spec='chaindsp25k_spec.py', needs=('CLK_FRE',),
                      synth_timeout=3600, pnr_timeout=3600),
}
HEADER = struct.Struct('<IIBBBBI')


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def module_params(text, mod):
    """Parameter names the harness module declares, read from its own header.

    chparam on a name the module does not have is a hard yosys error, and the three
    harness families declare different parameters, so the set is discovered rather
    than assumed.
    """
    m = re.search(r'module\s+%s\s*#\s*\((.*?)\)\s*\(' % re.escape(mod), text,
                  re.S)
    return re.findall(r'parameter\s+(?:integer\s+)?(\w+)\s*=', m.group(1)) if m else []


def write_desc(dest, descs):
    lines = ['// Generated by build_rom_25k.py from the frozen case list.',
             'always @* begin',
             ' d_tag=32\'h0; d_cfg=32\'h0; d_count=8\'d0; d_stall=8\'d0;',
             ' d_mask=32\'h0; d_shift=5\'d0; d_shape=2\'d0; d_imp=1\'b0;',
             ' case (case_idx)']
    for d in descs:
        lines.append('  8\'d%d: begin d_tag=32\'h%08x; d_cfg=32\'h%08x;'
                     ' d_count=8\'d%d; d_stall=8\'d%d; d_mask=32\'h%08x;'
                     ' d_shift=5\'d%d; d_shape=2\'d%d; d_imp=1\'b%d; end'
                     % (d['index'], d['tag'] & 0xFFFFFFFF, d['config'] & 0xFFFFFFFF,
                        d['count'], d['stall'], d['mask'], d['shift'],
                        d['shape'], d['imp']))
    lines += ['  default: begin d_tag=32\'h0; d_cfg=32\'h0; d_count=8\'d0;',
              '    d_stall=8\'d0; d_mask=32\'h0; d_shift=5\'d0;',
              '    d_shape=2\'d0; d_imp=1\'b0; end', ' endcase', 'end']
    (dest / 'rom_desc.vh').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def write_cfg_top(dest, cfg):
    """Emit the literal configuration top.

    yosys ``chparam`` only re-elaborates the module it names: with the parameters
    set on ``rom_harness_25k`` the generate block inside ``dsp_stream_harness``
    kept its CORE=0 branch and synthesis died on the missing farrow module
    (measured, not assumed).  Selecting logic therefore lives in this file as
    literals, which elaboration does honour, and nothing is overridden later.
    """
    (dest / 'rom_cfg_25k.v').write_text("""// Generated by build_rom_25k.py for one core; do not hand-edit.
// All values are literals on purpose -- see write_cfg_top() in build_rom_25k.py.
module rom_cfg_25k(input wire clk, input wire uart_rx_pin,
                   output wire uart_tx, output wire dbg_uart);
rom_harness_25k #(.FAMILY(%(family)d), .CORE(%(core)d), .BITS(%(bits)d),
                  .PAD_MODE(%(padding)d), .CLK_FRE(%(clk)d), .NCASE(%(ncase)d),
                  .MEM_IMPL(%(mem)d), .SEED(32'h%(seed)08x)) impl(
    .clk(clk), .uart_rx_pin(uart_rx_pin), .uart_tx(uart_tx),
    .dbg_uart(dbg_uart));
endmodule
""" % cfg, encoding='utf-8')


def sim_timeout(descs, stim_bytes, rate=2000):
    """Host seconds for the vvp round, from the bytes the round itself moves.

    A ROM round is 115200-baud traffic driven by a 50 MHz clock, so simulation
    cost is design time, not case count: measured 1.2-1.5 ks of host time per
    second of UART byte time on this box (biquad ~3 min, median 81 % of its
    bytes at the old flat 900 s cap).  The rate is per family because the
    simulated logic, not the clock, dominates: conv (ISP) ran at 754 s/s while
    the DSP stream cores sit near 1500 s/s, and the ISP sorting/matrix cones are
    allowed four times that before the guard fires.
    """
    byte_s = 10.0 / 115200.0
    out_bytes = sum(20 + (d.get('report_bpe', 4) * d['count']
                          if d['kind'] == 'case' else 0) for d in descs)
    design_s = (len(stim_bytes) + out_bytes) * byte_s + len(descs) * 0.005
    return int(design_s * rate + 240)


def split_reports(raw, descs, rmagic):
    """Pull the declared-length reports out of the byte stream, resyncing on magic."""
    out, pos, skipped = [], 0, 0
    for d in descs:
        bpe = d.get('report_bpe', 4)
        while pos + 20 <= len(raw):
            if raw[pos:pos + 4] == rmagic:
                rt, rc, n, flags, inc, outc, cyc = HEADER.unpack(raw[pos + 4:pos + 20])
                if rt == d['tag'] and rc == d['config']:
                    size = 20 + bpe * outc
                    if len(raw) >= pos + size:
                        out.append(raw[pos:pos + size])
                        pos += size
                        break
            pos += 1
            skipped += 1
        else:
            out.append(b'')
        if len(out) == len(descs):
            break
    return out, skipped, raw[pos:]


def grade(fam, pr, descs, all_words, reports, bits, padding, core_id):
    rows = []
    # The chain harnesses have one core set and no CORE parameter, so their frozen
    # verify() takes no core index; the other two families do.
    kw = {} if fam.startswith('chain') else {'core': core_id}
    for d, wl, rep in zip(descs, all_words, reports):
        rec = dict(index=d['index'], kind=d['kind'], tag='%08x' % d['tag'],
                   config=d['config'], count=d['count'], stall=d['stall'],
                   ok=False)
        want = 20 + (d.get('report_bpe', 4) * d['count']
                     if d['kind'] == 'case' else 0)
        if len(rep) != want:
            rec['error'] = 'report length %d want %d' % (len(rep), want)
            rows.append(rec)
            continue
        # verify()'s own positional tail is per family: a 32-bit-word family puts
        # the sample count after the words, the DC chain puts the pipeline stage
        # counts after the stall.  Assembling it once keeps the corruption check
        # below on exactly the same argument list as the real report.
        args = (d['tag'], d['config'], wl)
        if fam in ('dstream', 'chain_dsp'):
            args += (d['stall'],) + tuple(d.get('latencies') or ())
        else:
            args += (bits, d['stall'], padding)
        try:
            if d['kind'] == 'case':
                res = pr.verify(rep, *args, **kw)
                # a flipped payload bit must be rejected by the checker
                mut = bytearray(rep)
                mut[20 if len(rep) > 21 else 19] ^= 0x01
                try:
                    pr.verify(bytes(mut), *args, **kw)
                except AssertionError:
                    rec['negative_check'] = 'PASS'
                else:
                    raise AssertionError('checker accepted a corrupted reply')
                rec.update(ok=True, **{k: v for k, v in res.items()
                                       if k != 'status'})
            else:
                rt, rc, n, flags, inc, outc, cyc = HEADER.unpack(rep[4:20])
                if (rt, rc, n, flags, inc, outc, cyc) != (d['tag'], d['config'],
                                                          0, d['flags'], 0, 0, 0):
                    raise AssertionError(('negative header', rt, rc, n, flags,
                                          inc, outc, cyc))
                rec.update(ok=True, flags=flags)
        except AssertionError as exc:
            rec['error'] = 'verify: %r' % (exc.args,)
        rows.append(rec)
    return rows


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--family', choices=sorted(FAMS), required=True)
    p.add_argument('--core', required=True)
    p.add_argument('--bits', type=int, default=8)
    p.add_argument('--padding', type=int, default=1)
    p.add_argument('--seed', type=int, default=0xA5A51234)
    p.add_argument('--build', action='store_true')
    p.add_argument('--reuse-sim', action='store_true',
                   help='carry over a simulation_summary.json that already passed '
                        'in --dest instead of re-running vvp (synthesis iterating)')
    p.add_argument('--dest', type=Path)
    a = p.parse_args()

    fam = FAMS[a.family]
    hdir = BOARD / fam['dir']
    # A family whose 20K runner keeps its source list inside main() supplies the
    # same table here instead, so the 20K file stays untouched.
    runner = load_module(HERE / fam['spec'] if 'spec' in fam
                         else hdir / 'run.py', 'harness_run')
    sel = runner.CORES[a.core]
    core_id = sel['core']
    pr = load_module(hdir / 'protocol.py', 'frozen_protocol')
    sys.path.insert(0, str(hdir))

    import rom_stim_25k
    if a.family == 'dstream':
        work = pr.cases(core=core_id)
    elif a.family == 'isp':
        work = pr.cases(a.bits, core=core_id)
    elif a.family == 'chain_dsp':
        work = pr.cases()
    else:
        work = pr.cases(a.bits)
    descs = rom_stim_25k.descriptors(a.family, core_id, work, bits=a.bits,
                                     seed=a.seed, bad_config=fam['bad_config'])
    # Report geometry travels on the descriptor: the board round splits and grades
    # with the same code, and it cannot know that a family emits 17 report bytes
    # per result instead of 4 unless the case list says so.  ``latencies`` are the
    # pipeline depths the frozen verify() replays for the DC chain.
    for d in descs:
        d['report_bpe'] = getattr(runner, 'REPORT_BYTES_PER_WORD', 4)
        if hasattr(runner, 'latencies'):
            d['latencies'] = list(runner.latencies(LIB))
    stim_bytes, all_words = rom_stim_25k.byte_stream(descs, magic=fam['magic'],
                                                     seed=a.seed)

    dest = a.dest or (HERE / 'evidence' / ('%s_%s' % (
        a.core, datetime.datetime.now().strftime('%Y%m%d_%H%M%S_%f'))))
    dest.mkdir(parents=True, exist_ok=True)
    write_desc(dest, descs)
    write_cfg_top(dest, dict(family=fam['family'], core=core_id, bits=a.bits,
                             padding=a.padding, clk=device_flow.CLK_MHZ,
                             ncase=len(descs), mem=0, seed=a.seed & 0xFFFFFFFF))

    harness_rtl = ['%s.v' % fam['dir']]
    core_rtl = [Path(s).name for s in sel['rtl']]
    extra = [Path(s).name for s in sel.get('extra', [])]
    shared = [Path(s).name for s in getattr(runner, 'SHARED_RTL', [])]
    copies = ([hdir / s for s in harness_rtl]
              # the Verilog preprocessor resolves `include` before elaboration, so
              # an include table living inside another core's generate branch is
              # still required for every core of that harness
              + sorted(hdir.glob('*.vh'))
              + [LIB / s for s in sel.get('extra', [])]
              + [LIB / s for s in sel['rtl']]
              + [LIB / s for s in getattr(runner, 'SHARED_RTL', [])]
              + [ROOT / 'cores/communication/primitives/src/uart_rx.v',
                 ROOT / 'cores/communication/primitives/src/uart_tx.v',
                 ROOT / 'cores/image_processing/window/sim/gowin_bsram_sim.v',
                 hdir / 'protocol.py',
                 HERE / 'stim_25k.v', HERE / 'rom_harness_25k.v',
                 HERE / 'tb_rom_harness_25k.sv', HERE / 'build_rom_25k.py',
                 HERE / 'rom_stim_25k.py',
                 # the board round imports this module's split_reports()/grade(),
                 # and importing it pulls in device_flow, so the rig needs it too
                 HERE.parent / 'device_flow.py'])
    for f in copies:
        shutil.copy2(f, dest / f.name)
    for src, alias in sel['models'].items():
        shutil.copy2(LIB / src, dest / alias)
    staged = sorted(set([f.name for f in copies]
                        + [alias for alias in sel['models'].values()]
                        + ['rom_desc.vh', 'rom_cfg_25k.v']))
    (dest / 'hashes.json').write_text(json.dumps({
        n: hashlib.sha256((dest / n).read_bytes()).hexdigest()
        for n in staged if not n.endswith('.py') or n == 'protocol.py'}, indent=2))
    (dest / 'variant.json').write_text(json.dumps(dict(
        family=a.family, core=core_id, core_name=a.core, bits=a.bits,
        padding=a.padding, seed=a.seed, stimulus='rom',
        note='pad B3 undrivable on the dock; cases emitted from on-chip ROM'),
        indent=2) + '\n')
    (dest / 'rom_cases_25k.json').write_text(json.dumps(dict(
        family=a.family, core=core_id, core_name=a.core, bits=a.bits,
        padding=a.padding, seed=a.seed, magic=fam['magic'].decode(),
        report_magic=fam['rmagic'].decode(), cases=descs,
        words=all_words), indent=2) + '\n')

    def run(cmd, log, timeout=900):
        return device_flow.run_capture(dest, cmd, log, timeout=timeout)

    sim_rtl = [n for n in dict.fromkeys(staged)
               if Path(n).suffix in ('.v', '.sv')
               and n not in ('tb_rom_harness_25k.sv', 'gowin_bsram_sim.v')]
    # Synthesis iterating should not re-pay for a simulation that already proved
    # this exact staged tree, so a finished PASS can be carried over by name.
    prior = None
    if a.reuse_sim and (dest / 'simulation_summary.json').exists():
        prior = json.loads((dest / 'simulation_summary.json').read_text())
        if prior.get('status') != 'PASS':
            raise AssertionError('--reuse-sim but %s did not pass' % dest)
    if prior:
        sim_budget = prior.get('sim_budget_seconds', 0)
        sim_wall = prior.get('sim_wall_seconds', 0)
        print('ROM SIM REUSED %s (%ds of vvp not re-run)' % (dest, sim_wall),
              flush=True)
    else:
        run(['iverilog', '-g2012', '-Wall', '-I.', '-s', 'tb_rom_harness_25k',
             '-o', 'sim.vvp', 'tb_rom_harness_25k.sv', 'gowin_bsram_sim.v',
             *sim_rtl], 'compile.log')
        sim_budget = sim_timeout(descs, stim_bytes, fam['sim_rate'])
        t_sim = datetime.datetime.now()
        out = run(['vvp', 'sim.vvp'], 'simulation.log', timeout=sim_budget)
        sim_wall = int((datetime.datetime.now() - t_sim).total_seconds())
        assert 'ROM SIM DECODE OK' in out, out[-600:]

    got_stim = bytes(int(x, 16) for x in (dest / 'stim.bin').read_text().split())
    if got_stim != stim_bytes:
        i = next((k for k in range(min(len(got_stim), len(stim_bytes)))
                  if got_stim[k] != stim_bytes[k]), min(len(got_stim),
                                                        len(stim_bytes)))
        raise AssertionError('stimulus mirror drift at byte %d: rtl %02x python %02x'
                             % (i, got_stim[i], stim_bytes[i]))
    raw = bytes(int(x, 16) for x in (dest / 'raw.bin').read_text().split())
    (dest / 'raw_all.bin').write_bytes(raw)
    reports, skipped, tail = split_reports(raw, descs, fam['rmagic'])
    rows = grade(a.family, pr, descs, all_words, reports, a.bits, a.padding,
                 core_id)
    passed = sum(1 for r in rows if r['ok'])
    summary = dict(status='PASS' if passed == len(rows) and not skipped
                   else 'FAIL', family=a.family, core=core_id, core_name=a.core,
                   stimulus='rom', blocks=len(rows), passed=passed,
                   resync_skipped=skipped, trailing_bytes=len(tail),
                 report_bytes=len(raw), stim_bytes=len(got_stim),
                 sim_wall_seconds=sim_wall, sim_budget_seconds=sim_budget,
                 cases=rows)
    (dest / 'simulation_summary.json').write_text(json.dumps(summary, indent=2)
                                                  + '\n')
    if summary['status'] != 'PASS':
        print(json.dumps(summary, indent=2))
        raise AssertionError('ROM stimulus simulation failed; %s' % dest)
    print('ROM SIM PASS', dest, 'cases=%d stim=%dB report=%dB'
          % (len(rows), len(got_stim), len(raw)), flush=True)

    if not a.build:
        return
    # The selecting values are literals in rom_cfg_25k.v, and the harness child is
    # also chparam'd so its *default* elaboration cannot point at a core that this
    # build does not include (see device_flow.build).
    child_want = dict(CORE=core_id, CLK_FRE=device_flow.CLK_MHZ, BITS=a.bits,
                      PAD_MODE=a.padding, MEM_IMPL=0)
    declared = module_params((dest / ('%s.v' % fam['dir'])).read_text(encoding='utf-8'),
                             fam['dut'])
    missing = [k for k in fam.get('needs', ('CORE', 'CLK_FRE')) if k not in declared]
    if missing:
        raise AssertionError('%s declares no %s; the wrapper cannot configure it'
                             % (fam['dut'], missing))
    child = {k: v for k, v in child_want.items() if k in declared}
    # The wrapper needs its defaults matched too, for the same reason as the child:
    # read_verilog also elaborates a *default* rom_harness_25k, and with FAMILY
    # still 0 that orphan takes the dsp branch, so an ISP build died on
    # "Module \dsp_stream_harness is not part of the design" (measured on conv).
    wrapper = dict(FAMILY=fam['family'], CORE=core_id, BITS=a.bits,
                   PAD_MODE=a.padding, CLK_FRE=device_flow.CLK_MHZ,
                   NCASE=len(descs), MEM_IMPL=0, SEED=a.seed & 0xFFFFFFFF)
    s = device_flow.build(dest, top='rom_cfg_25k', rtl=sim_rtl, params=None,
                          chparams={fam['dut']: child,
                                    'rom_harness_25k': wrapper},
                          image=fam['image'], json_name='rom25k.json',
                          synth_timeout=fam.get('synth_timeout', 900),
                          pnr_timeout=fam.get('pnr_timeout', 900))
    # Prove the netlist holds the core that was simulated, and only that core.
    text = (dest / 'rom25k.json').read_text()
    names = {Path(m).stem for spec in runner.CORES.values() for m in spec['rtl']}
    want = {Path(m).stem for m in sel['rtl']}
    absent = sorted(n for n in names - want if n in text)
    if absent or not all(n in text for n in want):
        raise AssertionError('netlist core set mismatch: extra=%s missing=%s'
                             % (absent, [n for n in want if n not in text]))
    s['cores_in_netlist'] = sorted(want)
    s['harness_chparams'] = child
    s['wrapper_chparams'] = wrapper
    s['harness_declared_params'] = declared
    s['sim_and_netlist_cores_match'] = True
    (dest / 'build_25k_summary.json').write_text(json.dumps(s, indent=2) + '\n')
    print(json.dumps(s, indent=2))


if __name__ == '__main__':
    main()
