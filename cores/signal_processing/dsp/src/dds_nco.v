// ============================================================================
// dds_nco.v -- 32-bit phase accumulator + 256x16 sine LUT NCO, zero DSP.
//
//   phase_acc += tuning_word  once per clk_en beat while run=1.
//   sine_out   <= lut[phase_acc[31:24]]  (registered BSRAM read, 1-beat lag:
//               emits the value addressed by the phase BEFORE this beat's
//               accumulate -- see golden model for exact cycle semantics).
//   square_out  = phase_acc[31]          (combinational MSB, 50% duty)
//   phase_out   = phase_acc              (for test/diagnostic taps)
//
// LUT: sine256.mem, 256 hex words, signed Q1.15 two's complement,
//   v[i] = round(32767 * sin(2*pi*i/256)).  Generated by tools/golden_model.py.
// ============================================================================
module dds_nco #(
    parameter LUT_FILE = "sine256.mem"
) (
    input  wire               clk,
    input  wire               clk_en,
    input  wire               rst_n,
    input  wire               run,
    input  wire [31:0]        tuning_word,
    output reg  signed [15:0] sine_out,
    output wire               square_out,
    output wire [31:0]        phase_out
);

(* ram_style = "block" *) reg signed [15:0] lut [0:255];
initial $readmemh(LUT_FILE, lut);

reg [31:0] phase_acc;

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        phase_acc <= 32'd0;
    end else if (clk_en && run) begin
        phase_acc <= phase_acc + tuning_word;
    end
end

// Synchronous ROM read in a pure posedge block (keeps the LUT in BSRAM).
// Reads the pre-increment address: sine_out at beat k = lut[(k-1)*tw >> 24].
always @(posedge clk) begin
    if (clk_en) begin
        sine_out <= lut[phase_acc[31:24]];
    end
end

assign square_out = phase_acc[31];
assign phase_out  = phase_acc;

endmodule
