"""Offline static instruction allocation/bounds; never runs HDL or numeric fixtures."""
import json
from collections import Counter
from pathlib import Path
from instruction_spec import RAW, DEGREES, PROGRAM, OUTPUTS
ROOT=Path(__file__).resolve().parent
def build():
    uses=Counter(x for ins in PROGRAM for x in (ins['a'],ins['b']))
    uses.update(x for pair in OUTPUTS for x in pair)
    slots={n:k for k,n in enumerate(RAW)}; free=list(range(10,32)); peak=10
    bounds={n:(1,1,d) for n,d in zip(RAW,DEGREES)}
    out=[]
    for pc,ins in enumerate(PROGRAM):
        a,b=ins['a'],ins['b']; aa,bb=slots[a],slots[b]
        ac,ap,aq=bounds[a];bc,bp,bq=bounds[b]
        ac <<= ins['sa'];bc <<= ins['sb']
        if ins['op']=='MUL':bound=(ac*bc,ap+bp,aq+bq)
        else:
            assert (ap,aq)==(bp,bq),(pc,ins)
            bound=(ac+bc,ap,aq)
        for name in (a,b):
            uses[name]-=1
            if uses[name]==0:free.append(slots.pop(name))
        assert free,'scratch allocation exceeds32'
        slot=min(free);free.remove(slot);slots[ins['dst']]=slot
        bounds[ins['dst']]=tuple(ins['refine'] or bound)
        peak=max(peak,len(slots))
        out.append(dict(pc=pc,**ins,aa=aa,bb=bb,dd=slot,pre_bound=bound,bound=bounds[ins['dst']]))
    return dict(instructions=out,outputs=[(slots[a],slots[b]) for a,b in OUTPUTS],peak_live=peak,
                counts=dict(Counter(x['op'] for x in PROGRAM)))
def main():
    d=build();(ROOT/'INSTRUCTIONS.json').write_text(json.dumps(d,indent=2)+'\n',encoding='utf-8',newline='\n')
    lines=['// Generated by assemble.py from instruction_spec.py; production decode.']
    lines+=['always @* begin','    op=0; addr_a=0; addr_b=0; addr_d=0; shift_a=0; shift_b=0;','    case(pc)']
    for x in d['instructions']:
        op={'ADD':0,'SUB':1,'MUL':2}[x['op']]
        lines.append(f"        7'd{x['pc']}:begin op=2'd{op};addr_a=5'd{x['aa']};addr_b=5'd{x['bb']};addr_d=5'd{x['dd']};shift_a=2'd{x['sa']};shift_b=2'd{x['sb']};end")
    lines+=['        default:begin end','    endcase','    out_num_addr=0;out_den_addr=0;','    case(out_index)']
    for k,(a,b) in enumerate(d['outputs']):lines.append(f"        3'd{k}:begin out_num_addr=5'd{a};out_den_addr=5'd{b};end")
    lines+=['        default:begin end','    endcase','end']
    (ROOT/'rtl/instructions.vh').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    limits=[]
    for fname,key in [('instruction_bound','pre_bound'),('refined_bound','bound')]:
        limits += [f'function [511:0] {fname};','    input integer index;','    begin','        case(index)']
        for x in d['instructions']:
            c,p,q=x[key]
            limits.append(f"            {x['pc']}:{fname}=512'd{c}*(512'(N)**{p})*((512'd1<<L)**{q});")
        limits += [f'            default:{fname}=0;','        endcase','    end','endfunction']
    (ROOT/'sim/instruction_bounds.vh').write_text('\n'.join(limits)+'\n',encoding='utf-8',newline='\n')
    print('STATIC_ASSEMBLY',d['counts'],'instructions',len(d['instructions']),'peak_live',d['peak_live'])
if __name__=='__main__':main()
