"""Generate the signed Q15 twiddle ROM; --check never writes files."""
import argparse
import math
from pathlib import Path


def source():
    lines = ["// Generated by generate_fft_twiddle.py: exp(-j*2*pi*k/256), Q15.",
             "module cip_dsp_fft_twiddle(input wire [6:0] address,",
             "    output wire signed [16:0] re,im);",
             "reg [33:0] value;",
             "assign re=value[33:17]; assign im=value[16:0];",
             "always @* begin", "    case(address)"]
    for index in range(128):
        re=round(math.cos(2*math.pi*index/256)*32768)
        im=round(-math.sin(2*math.pi*index/256)*32768)
        value=((re & 0x1ffff)<<17)|(im & 0x1ffff)
        lines.append(f"        7'd{index}: value=34'h{value:09x};")
    lines += ["        default: value=34'd0;", "    endcase", "end", "endmodule", ""]
    return "\n".join(lines)


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=Path(__file__).resolve().parent/'rtl/cip_dsp_fft_twiddle.v'
    expected=source()
    if args.check:
        if path.read_text(encoding='ascii')!=expected:
            raise SystemExit('FFT twiddle ROM differs from generator')
        print('PASS FFT twiddle generator')
    else:
        path.write_text(expected,encoding='ascii')
