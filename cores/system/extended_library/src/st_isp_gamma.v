// ============================================================================
// st_isp_gamma -- selftest cell for isp_gamma (wave2 unit contract).
//   Phase LOAD: write the 256-entry gamma LUT (image in sim/gamma_lut.mem,
//   produced by tools/golden_isp.py) through the DUT's lut_we port.
//   Phase RUN : stim (w2_img_stim 32x32x1, `pix24`) -> isp_gamma -> FNV fold
//   of {LUT[R],LUT[G],LUT[B]} per output pixel.
// EXP comes ONLY from tools/golden_isp.py (T1).  Verdict uses === (T6).
// ============================================================================
module st_isp_gamma (
    input  wire        clk,
    input  wire        clk_en,
    input  wire        rst_n,
    input  wire        start,
    output reg         done,
    output reg         pass,
    output reg  [31:0] digest,
    output reg  [15:0] cycles
);
    localparam [31:0] EXP    = 32'h61B5D82E;   // golden_isp.py GAM DIGEST
    localparam        IMG_W  = 32;
    localparam        IMG_H  = 32;
    localparam [15:0] NPIX   = IMG_W * IMG_H;

    `include "w2_fnv.vh"

    // LUT image (gamma ~2.2 encode) -- generated by tools/golden_isp.py.
    reg [7:0] lutimg [0:255];
    initial $readmemh("sim/gamma_lut.mem", lutimg);

    // phases: 0 idle, 1 LUT load, 2 stream
    reg [1:0] phase = 2'd0;
    reg [8:0] li    = 9'd0;
    wire      lut_we   = (phase == 2'd1);
    wire [7:0] lut_addr = li[7:0];
    wire [7:0] lut_data = lutimg[li[7:0]];
    wire      cev_stim = (clk_en & (phase == 2'd2)) | ~rst_n;
    wire      cev_dut  = clk_en | ~rst_n;   // DUT needs clk_en for LUT writes

    wire [23:0] s_p24;
    wire        s_pv, s_nl, s_done;
    w2_img_stim #(.IMG_W(IMG_W), .IMG_H(IMG_H), .N_FRAMES(1)) u_stim (
        .clk(clk), .clk_en(cev_stim), .rst_n(rst_n),
        .pix(), .pix24(s_p24), .pix_valid(s_pv), .new_line(s_nl),
        .fidx(), .stim_done(s_done));

    wire [23:0] o_dat;
    wire        o_v, o_nl;
    isp_gamma u_dut (
        .clk(clk), .clk_en(cev_dut), .rst_n(rst_n),
        .lut_we(lut_we), .lut_addr(lut_addr), .lut_data(lut_data),
        .pix24(s_p24), .pix_valid(s_pv), .new_line(s_nl),
        .pix24_out(o_dat), .out_valid(o_v), .nl_out(o_nl));

    reg [3:0]  tail;
    reg [15:0] ocnt;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            phase  <= 2'd0;
            li     <= 9'd0;
            done   <= 1'b0;
            pass   <= 1'b0;
            digest <= 32'h811C9DC5;
            cycles <= 16'd0;
            tail   <= 4'd0;
            ocnt   <= 16'd0;
        end else if (clk_en) begin
            case (phase)
                2'd0: if (start) phase <= 2'd1;
                2'd1: begin
                    cycles <= cycles + 16'd1;
                    if (li == 9'd255) phase <= 2'd2;
                    li <= li + 9'd1;
                end
                default: begin
                    if (!done) begin
                        cycles <= cycles + 16'd1;
                        if (o_v) begin
                            digest <= fnv(fnv(fnv(digest, o_dat[23:16]),
                                              o_dat[15:8]), o_dat[7:0]);
                            ocnt   <= ocnt + 16'd1;
                        end
                        if (s_done) begin
                            if (tail == 4'd8) begin
                                done <= 1'b1;
                                pass <= (digest === EXP) && (ocnt === NPIX);
                            end else begin
                                tail <= tail + 4'd1;
                            end
                        end
                    end
                end
            endcase
        end
    end
endmodule
