"""Generate AES S-box logic using GF(16)[y]/(y^2+y+8).

GF(16) uses x^4+x+1. Find a root of the AES polynomial in this field,
derive the two binary basis maps, and exhaustively verify all 256 values
against inversion in the original AES field followed by its affine map.
No RTL output or copied S-box table is used as the oracle.
"""
import argparse
from pathlib import Path


def mul(a, b, poly, bits):
    out = 0
    for _ in range(bits):
        if b & 1:
            out ^= a
        b >>= 1
        a <<= 1
        if a & (1 << bits):
            a ^= poly
    return out


def m16(a, b):
    return mul(a, b, 0x13, 4)


def extension_mul(x, z):
    a, b, c, d = x & 15, x >> 4, z & 15, z >> 4
    bd = m16(b, d)
    return (m16(a, c) ^ m16(8, bd)) | ((m16(a, d) ^ m16(b, c) ^ bd) << 4)


def power(x, n, multiply):
    out = 1
    while n:
        if n & 1:
            out = multiply(out, x)
        x = multiply(x, x)
        n >>= 1
    return out


def linear(x, basis):
    out = 0
    for i, col in enumerate(basis):
        if (x >> i) & 1:
            out ^= col
    return out


def affine(x):
    return x ^ ((x << 1 | x >> 7) & 255) ^ ((x << 2 | x >> 6) & 255) ^ ((x << 3 | x >> 5) & 255) ^ ((x << 4 | x >> 4) & 255) ^ 0x63


def emit_linear(dest, source, basis, width):
    return [f"        {dest}[{j}] = " + ' ^ '.join(f'{source}[{i}]' for i, col in enumerate(basis) if col >> j & 1) + ';'
            for j in range(width)]


def generate():
    root = next(r for r in range(2, 256) if
                power(r, 8, extension_mul) ^ power(r, 4, extension_mul) ^
                power(r, 3, extension_mul) ^ r ^ 1 == 0)
    forward = [power(root, i, extension_mul) for i in range(8)]
    inverse_map = {linear(i, forward): i for i in range(256)}
    assert len(inverse_map) == 256
    backward = [inverse_map[1 << i] for i in range(8)]
    inv16 = [0] + [power(i, 14, m16) for i in range(1, 16)]
    # Fold the AES affine linear part into the inverse basis map.
    output_basis = [affine(col) ^ 0x63 for col in backward]
    for x in range(256):
        mapped = linear(x, forward)
        a, b = mapped & 15, mapped >> 4
        norm = m16(a, a ^ b) ^ m16(8, m16(b, b))
        reciprocal = m16(a ^ b, inv16[norm]) | (m16(b, inv16[norm]) << 4)
        expected = affine(power(x, 254, lambda u, v: mul(u, v, 0x11b, 8)))
        assert linear(reciprocal, output_basis) ^ 0x63 == expected

    lines = [
        '// Generated by tools/gen_aes_composite_sbox.py; all 256 values verified.',
        '// Unmasked combinational implementation; no side-channel protection claim.',
        'function [3:0] aes_mul16;', '    input [3:0] a, b;', '    begin']
    for j in range(4):
        terms = [f'(a[{i}] & b[{k}])' for i in range(4) for k in range(4)
                 if m16(1 << i, 1 << k) >> j & 1]
        lines.append(f"        aes_mul16[{j}] = " + ' ^ '.join(terms) + ';')
    lines += ['    end', 'endfunction', '', 'function [7:0] sbox;',
              '    input [7:0] x;', '    reg [7:0] mapped, reciprocal, transformed;',
              '    reg [3:0] a, b, lambda_square, norm, norm_inv;', '    begin']
    lines += emit_linear('mapped', 'x', forward, 8)
    lines += ['        a = mapped[3:0];', '        b = mapped[7:4];']
    lines += emit_linear('lambda_square', 'b', [m16(8, m16(1 << i, 1 << i)) for i in range(4)], 4)
    lines += ['        norm = aes_mul16(a, a ^ b) ^ lambda_square;', '        case (norm)']
    lines += [f"            4'h{i:x}: norm_inv = 4'h{v:x};" for i, v in enumerate(inv16)]
    lines += ["            default: norm_inv = 4'hx;", '        endcase',
              '        reciprocal = {aes_mul16(b, norm_inv), aes_mul16(a ^ b, norm_inv)};']
    lines += emit_linear('transformed', 'reciprocal', output_basis, 8)
    lines += ["        sbox = transformed ^ 8'h63;", '    end', 'endfunction']
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(), encoding='ascii')
    print('PASS composite-field bijection and all 256 AES S-box values')
