def m_cordic(a, b, c, state):
    """Statement-for-statement mirror of the generated CORDIC kernel."""
    if (a >> 14) or (b >> 16) or ((b >> 14) & 1):
        return 0, 0, 1, state
    csres, csck = c >> 31, (c >> 30) & 1
    csro, cshd = (c >> 29) & 1, (c >> 28) & 1
    csload = to_signed(a & 0x3FFF, 14)
    csstep, csdir = b & 0x3FFF, (b >> 15) & 1
    cslim = (c >> 14) & 0x3FFF
    csacc0 = to_signed(state & 0x3FFF, 14)
    if csck and csstep > cslim:
        return 0, 0, 1, state
    if csres:
        csacc, cswrap = csload, 0
    elif cshd:
        csacc, cswrap = csacc0, 0
    else:
        csst = to_signed(-csstep if csdir else csstep, 16)
        csum = to_signed(csacc0 + csst, 16)
        cswrap = 1 if (csum > 8191 or csum < -8192) else 0
        if csum > 8191:
            csum2 = csum - 16384
        elif csum < -8192:
            csum2 = csum + 16384
        else:
            csum2 = csum
        csacc = to_signed(csum2, 14)
    csx16 = to_signed(csacc, 16)
    csq = 1 if (csx16 > 4095 or csx16 < -4096) else 0
    if not csq:
        csf1 = csx16
    elif csx16 < 0:
        csf1 = csx16 + 8192
    else:
        csf1 = csx16 - 8192
    csp, csm = 1 if csf1 > 2048 else 0, 1 if csf1 < -2048 else 0
    if csp:
        czw = to_signed(csf1 - 4096, 16)
    elif csm:
        czw = to_signed(csf1 + 4096, 16)
    else:
        czw = csf1
    csfold = 1 if (csq or csp or csm) else 0
    cxw, cyw = {(0, 0, 0): (1024, 0), (0, 0, 1): (0, -1024),
                (0, 1, 0): (0, 1024), (1, 0, 0): (-1024, 0),
                (1, 0, 1): (0, 1024), (1, 1, 0): (0, -1024)}.get(
                    (csq, csp, csm), (1024, 0))
    csd = czw >= 0
    for index, arc in enumerate(CORDIC_ARCW):
        csxs = to_signed(cxw if index == 0 else round_shift(cxw, index), 16)
        csys = to_signed(cyw if index == 0 else round_shift(cyw, index), 16)
        if csd:
            cxw = to_signed(cxw - csys, 16)
            cyw = to_signed(cyw + csxs, 16)
            czw = to_signed(czw - arc, 16)
        else:
            cxw = to_signed(cxw + csys, 16)
            cyw = to_signed(cyw - csxs, 16)
            czw = to_signed(czw + arc, 16)
        csd = czw >= 0
    csxpr = to_signed(sum(sign * (cxw << pos)
                          for pos, sign in CORDIC_INVK_TERMS), 32)
    csypr = to_signed(sum(sign * (cyw << pos)
                          for pos, sign in CORDIC_INVK_TERMS), 32)
    csscos = to_signed(round_shift(csxpr, 15), 12)
    csssin = to_signed(round_shift(csypr, 15), 12)
    csoc = umask(cxw, 12) if csro else umask(csscos, 12)
    csos = umask(cyw, 12) if csro else umask(csssin, 12)
    r = (((czw >> 15) & 1) << 31) | (csfold << 30) | (((csacc >> 13) & 1) << 29) | \
        (cswrap << 28) | (csck << 27) | (csro << 26) | (cshd << 25) | \
        (csres << 24) | (csos << 12) | csoc
    x = (cswrap << 31) | (csm << 30) | (csp << 29) | (csq << 28) | \
        (umask(czw, 14) << 14) | umask(csacc, 14)
    return r, x, 0, umask(csacc, 14)


_MODELS['cordic_sincos'] = m_cordic


def h_cordic():
    """Board set: sixteen hand-picked angles, then free-running accumulator."""
    def cw(res=0, ck=0, ro=0, hd=0, lim=16383):
        return (res << 31) | (ck << 30) | (ro << 29) | (hd << 28) | \
               ((lim & 0x3FFF) << 14)

    def word(deg):
        return round(8192.0 * deg / 180.0) & 0x3FFF

    rows = []
    for deg in (0, 45, 90, 135, -180, -135, -90, -45,
                30, 60, 120, 150, -30, -60, -120, -150):
        rows.append((word(deg), 0, cw(res=1)))                      # 16 angles
    steps = [1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2048,
             4095, 4096, 8191, 8192, 3, 5, 17, 257, 16383, 11, 13, 7]
    for index, step in enumerate(steps):          # free-running, state threaded
        rows.append((0, step, cw(res=1) if index == 0 else 0))
    for index, step in enumerate(steps):          # backwards, raw-gain output
        rows.append((0, step | (1 << 15), cw(ro=1, res=1) if index == 0 else cw(ro=1)))
    for deg in (15, 75, 105, 165, 195, 255, 285, 345):
        rows.append((word(deg), 0, cw(res=1)))                      # sector edges
    for index in range(10):                       # restart then hold, alternating
        rows.append((word(64 * index), 0,
                     cw(res=1) if index % 2 == 0 else cw(hd=1)))
    for index in range(8):                        # slew check on, never tripped
        rows.append((0, 100 + 9 * index,
                     cw(ck=1, lim=1000, res=1) if index == 0 else cw(ck=1, lim=1000)))
    for index in range(8):                        # wrap through +-180 repeatedly
        rows.append((8000, 300 + 17 * index, cw(res=1) if index == 0 else 0))
    for index in range(6):                        # raw-gain free run
        rows.append((0, 1000 + 137 * index,
                     cw(ro=1, res=1) if index == 0 else cw(ro=1)))
    for index in range(4):                        # slew check tripped
        rows.append((0, 1001 + index, cw(ck=1, lim=1000)))
    rows.append((1 << 14, 0, 0))                  # malformed a
    rows.append((1 << 20, 0, 0))                  # malformed a (high bit)
    rows.append((0, 1 << 16, 0))                  # malformed b (high bit)
    rows.append((0, 1 << 14, 0))                  # malformed b (reserved bit)
    for index in range(16):                       # dithered electrical-angle sweep
        rows.append((0, 41 + ((index * 991) % 373), cw(res=1) if index == 0 else 0))
    return rows


