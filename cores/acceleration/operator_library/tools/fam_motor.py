# ==========================================================================
# Independent integer model.
#
# Every function below mirrors one generated Verilog kernel statement by
# statement, including the register width it is stored in: an RTL assignment
# truncates to the left-hand side, so the model applies to_signed(value, bits)
# with exactly that width instead of letting Python grow the number.  Values are
# never copied from the RTL; they are recomputed from the same derived
# constants this module builds (CL_K, SINCOS_IMAGE, RECIP, SVM_*).
# ==========================================================================
def to_signed(value, bits):
    """Mirror an assignment into a `bits`-wide two's-complement register."""
    value &= (1 << bits) - 1
    return value - (1 << bits) if value >> (bits - 1) else value


def umask(value, bits):
    return value & ((1 << bits) - 1)


def clamp(value, low, high):
    return low if value < low else (high if value > high else value)


def fld(state, low, bits):
    """One unsigned field of the 256-bit RTL state register."""
    return (state >> low) & ((1 << bits) - 1)


def sfld(state, low, bits):
    """One signed field of the state register, as $signed() would read it."""
    return to_signed(fld(state, low, bits), bits)


def setf(state, low, bits, value):
    """Write one field, exactly as `state_n[low+:bits] = value` does."""
    mask = ((1 << bits) - 1) << low
    return (state & ~mask) | (umask(value, bits) << low)


def m_clarke(a, b, c, state):
    if (a >> 20) or (b >> 10) or (c & 0x7FFFFF00):
        return 0, 0, 1, state
    ia = to_signed(a & 0x3FF, 10)
    ib = to_signed((a >> 10) & 0x3FF, 10)
    ic = to_signed(b & 0x3FF, 10)
    s1v = to_signed(ia + ib + ib, 14)
    s2v = to_signed(ib - ic, 14)
    # MULT12X12 is signed 12x12 -> 24-bit; the operands are the 12-bit slices.
    clp1 = to_signed(to_signed(umask(s1v, 12), 12) * CL_K, 24)
    clp2 = to_signed(to_signed(umask(s2v, 12), 12) * CL_K, 24)
    b1v = to_signed((clp1 + 1024) >> 11, 14)
    b2v = to_signed((clp2 + 1024) >> 11, 14)
    dlt = to_signed(b1v - b2v, 14)
    adv = umask(to_signed(-dlt, 14), 14) if dlt < 0 else umask(dlt, 14)
    enchk = 1 if (c >> 31) else 0
    tol = c & 0xFF
    viol = 1 if (enchk and adv > to_signed(tol, 14)) else 0
    r = (umask(b1v, 12) << 12) | umask(ia, 12)
    x = (viol << 25) | (enchk << 24) | (umask(adv, 12) << 12) | umask(b2v, 12)
    return r, x, viol, state


def m_park(a, b, c, state, inverse=False):
    if c & 0x7FFFFF00:
        return 0, 0, 1, state
    av = to_signed(a & 0xFFF, 12)
    bv = to_signed(b & 0xFFF, 12)
    pth = c & 0xFF
    word = SINCOS_IMAGE[pth]
    ccs = to_signed((word >> 12) & 0xFFF, 12)
    snx = to_signed(word & 0xFFF, 12)
    ai = clamp(av, -1024, 1023)
    bi = clamp(bv, -1024, 1023)
    pfl = [1 if ai != av else 0, 1 if bi != bv else 0, 0, 0]
    nsx = snx if inverse else -snx
    abv = to_signed(ai + bi, 14)
    csd = to_signed(ccs + snx if inverse else ccs - snx, 14)
    pk1 = to_signed(to_signed(umask(ai, 12), 12) * to_signed(umask(ccs, 12), 12), 24)
    pk2 = to_signed(to_signed(umask(bi, 12), 12) * to_signed(umask(nsx, 12), 12), 24)
    pk3 = to_signed(to_signed(umask(abv, 12), 12) * to_signed(umask(csd, 12), 12), 24)
    o1v = to_signed((pk1 - pk2 + 512) >> 10, 14)
    o2v = to_signed((pk3 - pk1 - pk2 + 512) >> 10, 14)
    m1v = to_signed(-o1v, 14) if o1v < 0 else umask(o1v, 14)
    m2v = to_signed(-o2v, 14) if o2v < 0 else umask(o2v, 14)
    pfl[2] = 1 if m1v > 1023 else 0
    pfl[3] = 1 if m2v > 1023 else 0
    r = (umask(o2v, 12) << 12) | umask(o1v, 12)
    x = (pfl[3] << 11) | (pfl[2] << 10) | (pfl[1] << 9) | (pfl[0] << 8) | pth
    return r, x, 0, state


def m_svpwm(a, b, c, state):
    if (a >> 22) or (b >> 11) or (c & 0x7FFFF000):
        return 0, 0, 1, state
    uv = to_signed(a & 0x7FF, 11)
    vv = to_signed((a >> 11) & 0x7FF, 11)
    wv = to_signed(b & 0x7FF, 11)
    proj = {'X': to_signed(vv - wv, 13), 'Y': to_signed(wv - uv, 13),
            'Z': to_signed(uv - vv, 13)}
    key = ((1 if proj['Z'] > 0 else 0) << 2) | ((1 if proj['Y'] > 0 else 0) << 1) | \
        (1 if proj['X'] > 0 else 0)

    def picked(table):
        name = table[key] if key in (1, 2, 3, 4, 5, 6) else None
        if name is None:
            return 0
        return to_signed(-proj[name[1:]] if name[0] == '-' else proj[name[0]], 13)

    sector = SVM_SECTOR[key] if key in (1, 2, 3, 4, 5, 6) else 0
    t1v = picked(SVM_T1)
    t2v = picked(SVM_T2)
    va = SVM_STATES[(sector - 1) % 6] if sector else 0
    vb = SVM_STATES[sector % 6] if sector else 0
    limv = c & 0xFFF
    sumv = to_signed(t1v + t2v, 14)
    enchk = 1 if (c >> 31) else 0
    ovr = 1 if (enchk and sumv > to_signed(limv, 13)) else 0
    dgen = 1 if key == 0 else 0
    r = (ovr << 31) | (dgen << 30) | (vb << 27) | (va << 24) | \
        (umask(t2v, 12) << 12) | umask(t1v, 12)
    x = (enchk << 18) | (key << 15) | (sector << 12) | limv
    return r, x, ovr or dgen, state


