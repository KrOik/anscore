# ==========================================================================
# Board vector sets.
#
# Rows 0..127 are the set the board runs, so the structured part is written
# first and deliberately: every flag, saturation, restart and malformed-beat
# case gets its own slot there instead of being left to the random tail.
# ==========================================================================
def s(v):
    """Pack one signed count into its low bits (the field width is checked by
    the model's own slicing, which reads the same bits back as signed)."""
    return v & MASK


def bits2(*pairs):
    value = 0
    for position, width, field in pairs:
        value |= (field & ((1 << width) - 1)) << position
    return value


def _cyc(cycle, index):
    return cycle[index % len(cycle)]


def h_clarke():
    rows = []
    ias = [0, 1, -1, 511, -512, 255, -256, 127, -128, 63, -64, 31, -32, 500, -500, 2]
    ibs = [0, 511, -512, 127, -128, 255, -256, 4]
    for i in range(120):
        ia, ib = _cyc(ias, i), _cyc(ibs, i // 16)
        ic = clamp(-ia - ib, -512, 511)
        control = 0x80000000 | 8 if i % 20 == 0 else 0
        rows.append((bits2((0, 10, ia), (10, 10, ib)), bits2((0, 10, ic)), control))
    rows.append((s(1 << 20), 0, 0))                            # malformed a
    rows.append((0, s(1 << 10), 0))                            # malformed b
    rows.append((0, 0, 1 << 15))                               # malformed c
    rows.append((bits2((0, 10, 0), (10, 10, 511)), bits2((0, 10, 0)), 0x80000000))
    rows.append((bits2((0, 10, 511), (10, 10, 0)), bits2((0, 10, 0)), 0x80000001))
    rows.append((bits2((0, 10, -512), (10, 10, 511)), bits2((0, 10, -512)), 0x800000ff))
    rows.append((bits2((0, 10, 511), (10, 10, 511)), bits2((0, 10, -512)), 0x800000ff))
    rows.append((bits2((0, 10, -1), (10, 10, -1)), bits2((0, 10, 2)), 0x80000000))
    return rows


