# --- cordic_sincos derived constants --------------------------------------
# The angle word is pi/8192, so an iteration step is atan(2^-i) expressed in
# that unit.  K is the accumulated CORDIC gain, and the output stage divides it
# out by multiplying with round(32768/K) through the shift-add term list.
CORDIC_ARCW = [round(atan(2.0 ** -i) * 8192.0 / pi) for i in range(12)]
CORDIC_K = CORDIC_GAIN[11]
CORDIC_INVK = round(32768.0 / CORDIC_K)


def naf_terms(value):
    """Non-adjacent form of a positive constant: signed shift-add terms.

    Returns [(shift, +1|-1), ...] whose weighted sum is exactly `value`.  NAF
    needs fewer addends than the plain bit list, which is what keeps the output
    requantiser a pure shift-add tree instead of a multiplier.
    """
    terms, pos = [], 0
    while value:
        if value & 1:
            if (value & 3) == 3 and value > 3:
                terms.append((pos, -1))
                value = (value + 1) >> 1
            else:
                terms.append((pos, 1))
                value >>= 1
        else:
            value >>= 1
        pos += 1
    return terms


CORDIC_INVK_TERMS = naf_terms(CORDIC_INVK)


def cordic_iterations():
    """The twelve unrolled vectoring steps, as one statement group per step.

    Unrolled rather than looped because the arc constant would otherwise be a
    memory read, and an asynchronous ROM read in a combinational kernel maps to
    logic the synthesiser does not treat like a BSRAM cell.  csxs is the shifted
    x (it drives the y update), csys the shifted y (it drives the x update), and
    csd is re-decided from the residual at the end of every step so the next
    step uses its own sign.
    """
    out = []
    for index, arc in enumerate(CORDIC_ARCW):
        if index == 0:
            shx, shy = 'csxw', 'csyw'
        else:
            half = 1 << (index - 1)
            shx = f"((csxw + 16'sd{half}) >>> {index})"
            shy = f"((csyw + 16'sd{half}) >>> {index})"
        out.append(
            f'csxs = {shx};\n'
            f'csys = {shy};\n'
            'if (csd) begin\n'
            f"    csxw = csxw - csys; csyw = csyw + csxs; czw = czw - 16'sd{arc};\n"
            'end else begin\n'
            f"    csxw = csxw + csys; csyw = csyw - csxs; czw = czw + 16'sd{arc};\n"
            "end\n"
            "csd = (czw >= 16'sd0);")
    return '\n'.join(out)


def _naf_expr(word):
    """The NAF shift-add sum applied to one sign-extended 32-bit register."""
    parts = []
    for shift, sign in CORDIC_INVK_TERMS:
        term = f'{word} <<< {shift}'
        parts.append(f'({term})' if sign > 0 else f'-({term})')
    return ' + '.join(parts)


def cordic_gain_scale():
    """Remove the accumulated CORDIC gain from both working registers.

    The 16-bit signed working register widens into the 32-bit signed product
    register by sign extension, so the only arithmetic left is the NAF shift-add
    sum of that one variable.
    """
    out = []
    for name in ('csx', 'csy'):
        out.append(f'{name}se = {name}w;')
        out.append(f'{name}pr = {_naf_expr(name + "se")};')
    return '\n'.join(out)


