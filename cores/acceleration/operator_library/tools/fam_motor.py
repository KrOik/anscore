"""Motor-control and power-electronics accelerator cores: FOC, SVM, loops, gates.

Family theme.  A servo/FOC cycle must close inside one enabled beat: the
Clarke/Park pair, the SVM sector decoder, the current-loop compensator, the
back-EMF observer and the complementary-pair dead band all retire per enabled
clock with II=1, which is exactly what a 20 kHz PWM ISR on a CPU cannot do
without jitter.  Every core here is a template kernel (combinational body, one
registered response), so the arithmetic cone is the whole story: hard
MULT12X12 slices where a multiply is unavoidable (Clarke's 1/sqrt3, Park's
three-multiplier Gauss rotation, the PID gains, the observer gain, the
divider-free speed reciprocal), pure shift-add where a multiply would be
affordable but is not needed (CORDIC, the sinc decimator, the dead-band
counters, the SVM projections).

Fixed-point conventions used throughout this family:
  * signal buses are 11- or 12-bit two's complement counts (Q10 at 11 bit:
    +/-1.0 = +/-1024; Q12 at 12 bit: +/-2.0 max);
  * trig tables are generated by tables(), Q10 (unity = 1024), 256 angles;
  * every requantise is a round-half-up arithmetic shift written as
    (p + (1 << (k-1))) >>> k, mirrored exactly by round_shift() below;
  * a saturating clamp always admits the whole signed bus range
    [-2^(w-1), 2^(w-1)-1], so a clamped variable can be stored in w bits.

Why the ranges are what they are: the three-multiplier Gauss rotation needs
(a+b) and (cos-sin) to fit a 12-bit signed multiplier input, so Park's inputs
are the 11-bit full-scale bus and the table is Q10, never Q15.  That is a
property of the trick, not a sloppiness, and selftest() proves the trick is
bit-exact against the four-product definition over the whole table.

Body vocabulary (declared by the template, reset each evaluation):
    r x                       result/aux registers, 32 bit
    f                         fault flag
    temp mask pa pb pc ph pl  32-bit unsigned temporaries
    ext                       33-bit unsigned (carry capture)
    wide wide2                64-bit unsigned
    swide swide2              64-bit signed
    sa sb sc                  $signed(a), $signed(b), $signed(c)
    data                      {a,b,c} as one 96-bit word
    i j idx lane sh           integers
    state_r state_n           256-bit state; only accepted beats commit it
Anything else comes from `decl`, which is module scope and may hold instances
and generated ROM images.  Because that vocabulary is already taken, no core in
this family names a register r, x, f, swide, idx, lane or sh.
"""
from math import atan, cos, degrees, pi, sin, sqrt
