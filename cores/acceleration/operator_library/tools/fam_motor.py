def _svpwm_case(table, target):
    """One case arm per live sign triple, from the geometrically derived table."""
    expr = {'X': 'Xv', 'Y': 'Yv', 'Z': 'Zv', '-X': '-Xv', '-Y': '-Yv', '-Z': '-Zv'}
    arms = [f'                3\'d{idx}: {target} = {expr[table[idx]]};'
            for idx in range(1, 7)]
    arms.append(f'                default: {target} = 13\'sd0;')
    return '\n'.join(arms)


def _svpwm_sector_case():
    arms = [f'                3\'d{idx}: svp_sec = 3\'d{SVM_SECTOR[idx]};'
            for idx in range(1, 7)]
    arms.append('                default: svp_sec = 3\'d0;')
    return '\n'.join(arms)


def _svpwm_vector_case(which, offset):
    arms = [f'                3\'d{sec}: svp_{which} = 3\'b{SVM_STATES[(sec - 1 + offset) % 6]:03b};'
            for sec in range(1, 7)]
    arms.append(f'                default: svp_{which} = 3\'b000;')
    return '\n'.join(arms)


