def m_deadband(a, b, c, state):
    dv, pr = a & 0xFFF, (a >> 12) & 0xFFF
    nb, th = b & 0xFF, (b >> 8) & 0xFF
    if (a >> 24) or pr == 0 or (b >> 16) or (c & 0x1FFFFF00):
        return 0, 0, 1, state
    restart, ctr, gate = c >> 31, (c >> 30) & 1, (c >> 29) & 1
    if restart:
        phi = dirn_prev = run = reqp = hip = lop = 0
        beat = edge = supp = seen = 0
    else:
        phi = fld(state, 0, 12)
        dirn_prev = fld(state, 12, 1)
        run = fld(state, 13, 16)
        reqp = fld(state, 29, 1)
        hip = fld(state, 30, 1)
        lop = fld(state, 31, 1)
        beat = fld(state, 32, 12)
        edge = fld(state, 44, 4)
        supp = fld(state, 48, 4)
        seen = fld(state, 52, 1)
    ph0 = (phi + 1) & 0xFFF
    ph1 = (phi - 1) & 0xFFF
    pem1 = (pr - 1) & 0xFFF
    dev = to_signed(2 * phi - (pr - 1), 14)
    mag = to_signed(-dev, 14) if dev < 0 else umask(dev, 14)
    req = (1 if mag < dv else 0) if ctr else (1 if phi < dv else 0)
    same = req == reqp
    runn = min(run + 1, 65535) if same else 1
    allowed = bool(gate) and runn > nb
    hi = 1 if (allowed and req) else 0
    lo = 1 if (allowed and not req) else 0
    short = (not same) and run != 0 and run <= nb
    toggle = (hi != hip) or (lo != lop)
    beatn = min(beat + 1, 4095)
    seen_n = 1 if (seen or hi or lo) else 0
    edgen = min(edge + 1, 15) if toggle else edge
    suppn = min(supp + 1, 15) if short else supp
    if ctr:
        if not dirn_prev:
            phi_n, dir_n = (pem1, 1) if phi >= pem1 else (ph0, 0)
        else:
            phi_n, dir_n = (0, 0) if phi == 0 else (ph1, 1)
    else:
        phi_n, dir_n = (0 if ph0 >= pr else ph0), dirn_prev
    dutybad = 1 if dv > pr else 0
    nbad = 1 if nb > pr else 0
    ovl = 1 if (hi and lo) else 0
    alarm = 1 if (th != 0 and beatn > th and not seen_n) else 0
    run12 = 4095 if runn > 4095 else runn
    new_state = 0
    for low, width, value in ((0, 12, phi_n), (12, 1, dir_n), (13, 16, runn),
                              (29, 1, req), (30, 1, hi), (31, 1, lo),
                              (32, 12, beatn), (44, 4, edgen), (48, 4, suppn),
                              (52, 1, seen_n)):
        new_state = setf(new_state, low, width, value)
    r = (suppn << 28) | (edgen << 24) | (int(toggle) << 23) | (int(short) << 22) | \
        (ovl << 21) | (alarm << 20) | (nbad << 19) | (dutybad << 18) | \
        (restart << 17) | (ctr << 16) | (gate << 15) | (req << 14) | (hi << 13) | \
        (lo << 12) | run12
    x = (hi << 31) | (lo << 30) | (dir_n << 29) | (req << 28) | (runn << 12) | phi_n
    return r, x, dutybad or nbad or ovl or alarm, new_state


def h_deadband():
    rows = []
    for i in range(48):                      # edge aligned, dead band of 3 beats
        rows.append((bits2((12, 12, 64), (0, 12, 3 + (i % 58))), 3,
                     0x20000000 | (0x80000000 if i == 0 else 0)))
    for i in range(24):                      # centre aligned, dead band swept
        rows.append((bits2((12, 12, 48), (0, 12, i * 2)), 1 << (i % 5),
                     0x60000000 | (0x80000000 if i == 0 else 0)))
    for i in range(16):                      # toggling faster than the dead band
        rows.append((bits2((12, 12, 40), (0, 12, 0 if i % 2 else 40)), 6,
                     0x20000000))
    for i in range(16):                      # duty beyond the period, band beyond it
        rows.append((bits2((12, 12, 20 + i), (0, 12, 20)), 200 + i,
                     0x20000000 | (0x80000000 if i == 0 else 0)))
    for i in range(12):                      # gate dropped: the no-output alarm runs
        rows.append((bits2((12, 12, 30), (0, 12, 15)), 8,
                     (0x20000000 if i >= 6 else 0) | (0x80000000 if i == 0 else 0)))
    rows.append((s(1 << 24), 3, 0x20000000))                    # malformed a
    rows.append((bits2((12, 12, 0), (0, 12, 0)), 3, 0x20000000))   # period zero
    rows.append((bits2((12, 12, 30), (0, 12, 15)), s(1 << 16), 0x20000000))
    rows.append((bits2((12, 12, 30), (0, 12, 15)), 3, 1 << 20))   # malformed c
    for i in range(8):                        # full-on / full-off with a long band
        rows.append((bits2((12, 12, 96), (0, 12, 0 if i % 4 == 0 else 96)), 9,
                     0x20000000))
    return rows


