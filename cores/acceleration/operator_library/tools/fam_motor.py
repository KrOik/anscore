def selftest():
    """Independent verification of every core in this family.

    The rule this file follows is that selftest() must attack the kernel from
    outside: it never calls the `m_*` model routines as an oracle (that would be
    a replay of the very code under test).  Every expected value below comes
    from one of five external sources:

      * published geometry and closed-form constants (sqrt(3), pi, sin/cos of
        30/45/60 degree angles, the CORDIC gain),
      * Python's own integer arithmetic applied to the arithmetic rule the core
        *specification* declares (integer division, round-half-up, clamps),
      * an algebraic invariant that must hold whatever the datapath does
        (ia+ib+ic = 0 <=> beta == beta2, rotation preserves |v|, the three SVM
        projections sum to zero, a comb decimator has DC gain R**3),
      * exhaustive enumeration of a small domain,
      * a cross-core identity (the CORDIC angle generator versus the Park
        sin/cos image, Park versus inverse Park).

    Returns a positive integer: the number of independent assertions passed.
    """
    tally = {'n': 0}

    def chk(cond, what):
        if not cond:
            raise AssertionError(what)
        tally['n'] += 1

    def zmask(lo, hi):
        """A must-zero bit range [lo, hi] written as a mask."""
        return ((1 << (hi - lo + 1)) - 1) << lo

    names = [entry['name'] for entry in CORES]

    # --- 1. family registry ------------------------------------------------
    chk(len(CORES) == 10, 'family must register ten cores')
    chk(len(set(names)) == len(names), 'core names must be unique')
    for entry in CORES:
        nm = entry['name']
        chk(nm in HEADS, f'{nm}: no board vector head')
        chk(nm in _MODELS, f'{nm}: no family model')
        chk(isinstance(entry['spec'], str) and len(entry['spec']) > 120,
            f'{nm}: operand spec too short to be a contract')
        chk(isinstance(entry['advantage'], str) and len(entry['advantage']) > 120,
            f'{nm}: advantage text missing')
        chk(entry['family'] == FAMILY and entry['lanes'] == 1,
            f'{nm}: family/lane registration wrong')
        # Fabric $mul is unsigned: a `*` anywhere in a kernel body or its
        # declaration would silently corrupt an operand with bit 11 set.
        chk('*' not in entry['body'], f'{nm}: kernel body contains a `*` operand')
        chk('*' not in entry['decl'], f'{nm}: kernel decl contains a `*` operand')

    # --- 2. derived tables are self-consistent geometry --------------------
    chk(SVM_SECTOR[0] is None, 'the degenerate sign triple must carry no sector')
    chk(sorted(v for v in SVM_SECTOR if v is not None) == [1, 2, 3, 4, 5, 6],
        'the sector table must cover 1..6 exactly once')
    chk(len(SVM_T1) == 8 and len(SVM_T2) == 8, 'projection tables must be indexed by idx')
    for idx in range(1, 7):
        chk(SVM_T1[idx] != SVM_T2[idx], f'idx {idx}: T1 and T2 are the same projection')
    chk(CL_K * CL_K * 3 < (1 << 22) and CL_K * CL_K * 3 > (1 << 22) - 4096,
        'the 1/sqrt3 slice must square to 1/3 at Q11')
    chk(SIN_Q[0] == 0 and COS_Q[0] == 1024, 'trig image at 0 degrees')
    chk(SIN_Q[64] == 1024 and COS_Q[64] == 0, 'trig image at 90 degrees')
    chk(SIN_Q[128] == 0 and COS_Q[128] == -1024, 'trig image at 180 degrees')
    chk(SIN_Q[192] == -1024 and COS_Q[192] == 0, 'trig image at 270 degrees')
    for k in range(256):
        # quarter-wave symmetry of the generated image, checked as integers.
        chk(SINCOS_IMAGE[k] >> 24 == 0, f'image word {k} exceeds 24 bits')
    for k in (32, 96, 160, 224):
        chk(abs(SIN_Q[k]) == 724 and abs(COS_Q[k]) == 724,
            f'the 45-degree table entries must be round(1024/sqrt2)=724, got {k}')
    chk(RECIP[0] == round((1 << 17) / 128) and RECIP[-1] == round((1 << 17) / 255),
        'reciprocal image endpoints')
    chk(all(RECIP[i] >= RECIP[i + 1] for i in range(len(RECIP) - 1)),
        'the reciprocal image must be non-increasing in the mantissa')
    chk(CORDIC_ARC[0] == round(8192.0 * pi / 4.0), 'first CORDIC arc is 45 degrees')
    chk(all(CORDIC_ARC[i] > CORDIC_ARC[i + 1] for i in range(11)),
        'CORDIC arcs must strictly decrease')
    chk(abs(CORDIC_K - 1.64676) < 1e-4, 'accumulated CORDIC gain must be 1.64676')
    chk(abs(sum((1 << sh) * sgn for sh, sgn in CORDIC_INVK_TERMS) - CORDIC_INVK) == 0,
        'the non-adjacent form must re-sum to its constant exactly')
    chk(len(CORDIC_INVK_TERMS) <= 8, 'NAF must be sparser than the bit list')

    # --- 3. every board vector set is well formed and deterministic --------
    for nm in names:
        head = HEADS[nm]()
        chk(len(head) == BOARD_ROWS, f'{nm}: head is not {BOARD_ROWS} rows')
        first = vectors(nm)
        second = vectors(nm)
        chk(len(first) == 320, f'{nm}: vector set is not 320 rows')
        chk(first == second, f'{nm}: vector set must be deterministic')
        chk(first[:BOARD_ROWS] == head, f'{nm}: head rows must survive into the set')
        for row in first:
            chk(len(row) == 3 and all(isinstance(v, int) and 0 <= v <= MASK
                                      for v in row), f'{nm}: bad row {row}')
        entry = next(e for e in CORES if e['name'] == nm)
        model = _MODELS[nm]
        threads_state = entry['stateful']
        seen_new_state = 0
        for a, b, c in first:
            r, x, f, st = step(nm, a, b, c, 0)
            chk(isinstance(r, int) and isinstance(x, int) and
                0 <= r <= MASK and 0 <= x <= MASK and f in (0, 1),
                f'{nm}: step out of contract {a:08x} {b:08x} {c:08x}')
            if not threads_state:
                chk(st == 0, f'{nm}: stateless core moved the state register')
            elif st != 0:
                seen_new_state = 1
            # the dispatcher masks its operands, so a negative word must behave
            # exactly like its 32-bit two's complement.
            r2, x2, f2, _ = step(nm, a | ~MASK, b | ~MASK, c | ~MASK, 0)
            chk((r2, x2, f2) == (r, x, f), f'{nm}: operand masking is not idempotent')
        if threads_state:
            chk(seen_new_state, f'{nm}: stateful core never threaded its 256-bit state')
            # a stateful core must answer differently once it carries history:
            # run the set as a real chain, then re-evaluate every beat as if the
            # pipeline were empty.  A core whose output ignores its registers
            # would pass the per-beat checks above and fail here.
            st, distinct = 0, 0
            for a, b, c in first:
                r, x, f, nxt = step(nm, a, b, c, st)
                r0, x0, f0, _ = step(nm, a, b, c, 0)
                if (r, x, f) != (r0, x0, f0):
                    distinct += 1
                st = nxt
            chk(distinct >= 16, f'{nm}: carried state has no effect on the answer')

    # --- 4. malformed-beat supervision, exhaustive over every reserved bit --
    # Each spec declares bit ranges of a, b or c that "must be zero".  Setting
    # one of them makes the beat malformed, and every core documents the same
    # reaction: fault=1 and the state register left exactly as it was.  This is
    # checked bit by bit, so a mask that lost a bit on the way into the RTL is
    # caught rather than silently accepted.
    reserved = {
        'clarke_s12': ((0, 20, 31), (1, 10, 31), (2, 8, 30)),
        'park_s12': ((2, 8, 30),),
        'inv_park_s12': ((2, 8, 30),),
        'svpwm_sector': ((0, 22, 31), (1, 11, 31), (2, 12, 30)),
        'ipi_pid_s12': ((0, 24, 31), (2, 4, 28)),
        'backemf_obs_s12': ((0, 24, 31), (1, 12, 31), (2, 12, 29)),
        'mt_speed': ((0, 11, 31), (1, 12, 31), (2, 0, 3), (2, 12, 30)),
        'pwm_deadband': ((0, 24, 31), (1, 16, 31), (2, 8, 28)),
        'cordic_sincos': ((0, 14, 31), (1, 14, 14), (1, 16, 31)),
        'sinc3_decim': ((0, 12, 31), (1, 8, 31), (2, 6, 27)),
    }
    clean_row = {
        'clarke_s12': (bits2((0, 10, 100), (10, 10, -50)), bits2((0, 10, -50)), 0),
        'park_s12': (bits2((0, 12, 300)), bits2((0, 12, -200)), 37),
        'inv_park_s12': (bits2((0, 12, 300)), bits2((0, 12, -200)), 37),
        'svpwm_sector': (bits2((0, 11, 100), (11, 11, -50)), bits2((0, 11, -50)), 0),
        'ipi_pid_s12': (bits2((0, 12, 100), (12, 12, 50)),
                        bits2((0, 12, 300), (12, 12, 200), (24, 8, 10)), 5),
        'backemf_obs_s12': (bits2((0, 12, 900), (12, 12, 100)), bits2((0, 12, 200)),
                            4 | (4 << 4) | (2 << 8)),
        'mt_speed': (bits2((0, 11, 100)), 300, 4 << 4),
        'pwm_deadband': (bits2((0, 12, 10), (12, 12, 64)), bits2((0, 8, 2), (8, 8, 0)),
                         1 << 29),
        'cordic_sincos': (bits2((0, 14, 1000)), 5, 1 << 31),
        'sinc3_decim': (bits2((0, 12, 300)), 7, 1 << 29),
    }
    keeper = 0x0BADF00D
    for nm in names:
        base = list(clean_row[nm])
        r0, x0, f0, _ = step(nm, base[0], base[1], base[2], 0)
        chk(f0 == 0 and (r0 | x0) != 0,
            f'{nm}: the clean reference beat is not an accepting beat')
        full = [0, 0, 0]
        for word, lo, hi in reserved[nm]:
            full[word] |= zmask(lo, hi)
        for word, lo, hi in reserved[nm]:
            for bit in range(lo, hi + 1):
                probe = list(base)
                probe[word] |= (1 << bit)
                r, x, f, st = step(nm, probe[0], probe[1], probe[2], keeper)
                chk(f == 1, f'{nm}: reserved bit {word}d{bit} accepted without a fault')
                chk(st == keeper,
                    f'{nm}: reserved bit {word}d{bit} overwrote the state register')
                if nm != 'sinc3_decim':
                    chk(r == 0 and x == 0,
                        f'{nm}: bit {word}d{bit} faulted but still drove the buses')
        for word in range(3):
            if not full[word]:
                continue
            probe = list(base)
            probe[word] |= full[word]
            r, x, f, st = step(nm, probe[0], probe[1], probe[2], keeper)
            chk(f == 1 and st == keeper,
                f'{nm}: the whole reserved word {word} was not rejected')

    # --- 5. declared output widths ----------------------------------------
    # Every spec closes a beat with "result[31:24]=0" or "aux[31:19]=0": those
    # lanes must stay clean on every accepting beat, including the random tail of
    # the board set, so an over-wide field cannot smuggle a value into a flag.
    zero_fields = {
        'clarke_s12': (zmask(24, 31), zmask(26, 31)),
        'park_s12': (zmask(24, 31), zmask(12, 31)),
        'inv_park_s12': (zmask(24, 31), zmask(12, 31)),
        'svpwm_sector': (0, zmask(19, 31)),
        'ipi_pid_s12': (zmask(24, 31), zmask(26, 31)),
        'backemf_obs_s12': (zmask(24, 31), 0),
        'mt_speed': (zmask(17, 31), 0),
        'pwm_deadband': (0, 0),
        'cordic_sincos': (0, 0),
        'sinc3_decim': (0, 0),
    }
    for nm in names:
        rmask, xmask = zero_fields[nm]
        accepted, st = 0, 0
        for a, b, c in vectors(nm):
            r, x, f, st = step(nm, a, b, c, st)
            # A fault lane is only raised for a malformed beat by the bus
            # zeroing rule; a clamp or a supervision trip faults with valid
            # outputs, so the width rule has to hold on both kinds of beat.
            chk((r & rmask) == 0 and (x & xmask) == 0,
                f'{nm}: a beat polluted a declared zero field')
            if not f:
                accepted += 1
        # The board sets are deliberately hard to satisfy (the observer set is
        # mostly rails), but a core that never accepts a beat at all would make
        # the width rule above vacuous.
        chk(accepted >= 4, f'{nm}: no accepting beat in its own board set')

    # --- 6. clarke_s12: amplitude-invariant Clarke -------------------------
    # beta is defined as (ia + 2*ib)/sqrt(3).  The expected value is computed
    # here twice: as exact Python integer arithmetic on the Q11 slice the spec
    # declares, and as a float from 1/sqrt(3), and the two must bracket the
    # core's answer.  The zero-sequence invariant |beta - beta2| = |ia+ib+ic|/
    # sqrt(3) is checked as plain integer algebra.
    def clarke_pack(ia, ib, ic, control=0):
        return (umask(ia, 10) | (umask(ib, 10) << 10), umask(ic, 10), control)

    for ia in list(range(-16, 17)) + [-512, -511, -256, 255, 511, 0]:
        for ib in [-512, -256, -7, 0, 5, 255, 511]:
            ic = -ia - ib
            if not -512 <= ic <= 511:
                continue
            r, x, f, _ = step('clarke_s12', *clarke_pack(ia, ib, ic))
            chk(f == 0, f'clarke: balanced set {ia} {ib} {ic} faulted')
            alpha, beta = sfld(r, 0, 12), sfld(r, 12, 12)
            beta2 = sfld(x, 0, 12)
            chk(alpha == ia, f'clarke: alpha must be ia verbatim, got {alpha} vs {ia}')
            exact = round_shift((ia + 2 * ib) * CL_K, 11)
            chk(beta == exact,
                f'clarke: beta {beta} != integer closed form {exact} for {ia} {ib}')
            chk(abs(beta - (ia + 2 * ib) / sqrt(3.0)) < 1.6,
                f'clarke: beta {beta} off the analytic 1/sqrt3 value for {ia} {ib}')
            chk(beta2 == round_shift((ib - ic) * CL_K, 11),
                f'clarke: beta2 wrong for {ia} {ib} {ic}')
            gap = umask(fld(x, 12, 12), 12)
            chk(gap == abs(beta - beta2),
                f'clarke: reported |beta-beta2| {gap} != {abs(beta - beta2)}')
            chk(abs(abs(beta - beta2) - abs(ia + ib + ic) / sqrt(3.0)) < 2.2,
                f'clarke: zero-sequence invariant broken on {ia} {ib} {ic}')
    # Known instants of a balanced three-phase set, checked against the exact
    # sine/cosine values (ia = m cos t, ib = m cos(t-120) => beta = m sin t).
    for m in (500, 250, 511, 100):
        for deg in (0, 30, 45, 60, 90, 135, 180, 270):
            th = pi * deg / 180.0
            ia = round(m * cos(th))
            ib = round(m * cos(th - 2.0 * pi / 3.0))
            ic = round(m * cos(th + 2.0 * pi / 3.0))
            r, x, f, _ = step('clarke_s12', *clarke_pack(ia, ib, ic))
            chk(f == 0, 'clarke: a physical three-phase set must not fault')
            chk(sfld(r, 0, 12) == ia, 'clarke: alpha of a balanced set')
            err = abs(sfld(r, 12, 12) - m * sin(th))
            chk(err <= 2.0 + m * 0.002,
                f'clarke: beta at {deg} deg is off by {err}, expected m*sin(t)')
    # Sensor-plausibility supervision: c[31] arms it, c[7:0] is the tolerance.
    # The expected verdict comes from the zero-sequence current alone: the two
    # beta estimates differ by (ia+ib+ic)/sqrt(3), so a set whose zero sequence
    # is well inside / well outside the tolerance fixes the answer without any
    # reference to how the core computes.
    for ia, ib, ic, tol, want_viol in ((300, -150, -150, 4, 0),      # sum 0
                                       (300, -150, -140, 64, 0),     # sum 10
                                       (300, -150, -100, 0, 1),      # sum 50
                                       (-512, 511, 1, 0, 0),         # sum 0
                                       (0, 500, 0, 255, 1),          # sum 500
                                       (0, 500, 490, 64, 1),         # sum 990
                                       (0, 0, -1, 4, 0),             # sum 1
                                       (0, 0, -1, 0, 1)):            # sum 1
        r, x, f, _ = step('clarke_s12', *clarke_pack(ia, ib, ic, 0x80000000 | tol))
        chk(fld(x, 24, 1) == 1, 'clarke: c[31] must echo the armed check')
        chk(fld(x, 25, 1) == want_viol,
            f'clarke: tolerance {tol} on sum {ia + ib + ic} should report {want_viol}')
        chk(f == want_viol, 'clarke: the plausibility verdict must drive the fault')
        # an armed check leaves both output buses valid, it does not zero them.
        chk(sfld(r, 0, 12) == ia and sfld(x, 0, 12) == round_shift((ib - ic) * CL_K, 11),
            'clarke: an armed check lost the outputs')
    r, x, f, _ = step('clarke_s12', *clarke_pack(0, 500, 0, 0))
    chk(f == 0 and fld(x, 24, 1) == 0 and fld(x, 25, 1) == 0,
        'clarke: a disarmed check must never raise')

    # --- 7. park_s12 / inv_park_s12: Gauss rotation -------------------------
    # The four quadrant angles have exact table entries (+-1024 / 0), so the
    # rotation collapses to a permutation with signs that is checked as integer
    # identities.  Away from the quadrants the same vectors must round-trip
    # through the inverse and preserve |v|.
    for k in range(256):
        r, x, f, _ = step('park_s12', 0, 0, k)
        chk(f == 0 and r == 0 and x & 0xFFFFF000 == 0,
            'park: a zero-magnitude input must rotate to zero at every angle')
    for alpha, beta in ((1023, 0), (-1024, 0), (0, 1023), (0, -1024), (600, -400),
                        (-512, 511), (1, 1), (-1, -1), (1000, 1000)):
        pairs = []
        for k, expect in ((0, (alpha, beta)), (64, (beta, -alpha)),
                          (128, (-alpha, -beta)), (192, (-beta, alpha))):
            r, x, f, _ = step('park_s12', umask(alpha, 12), umask(beta, 12), k)
            chk(f == 0, 'park: in-range rotation faulted')
            d, q = sfld(r, 0, 12), sfld(r, 12, 12)
            chk((d, q) == expect,
                f'park: at {k * 90 / 64:.0f} deg expected {expect}, got {(d, q)}')
            chk(fld(x, 8, 2) == 0, 'park: in-domain inputs must not report saturation')
            # aux[10]/aux[11] advertise that a rotation output left the 11-bit
            # regulator range: the flag must be exactly the magnitude test.
            chk(fld(x, 10, 1) == (1 if abs(d) > 1023 else 0),
                f'park: |d|={abs(d)} regulator flag wrong at {k}')
            chk(fld(x, 11, 1) == (1 if abs(q) > 1023 else 0),
                f'park: |q|={abs(q)} regulator flag wrong at {k}')
            chk(fld(x, 0, 8) == k, 'park: theta must echo the table index')
            pairs.append((k, (d, q)))
        # |v| is invariant under a rotation: compare the squared magnitudes.
        # The band is one part in a hundred of |v|^2 (a Q10 table can tilt the
        # vector by up to half an LSB of angle) plus the two requantise steps.
        band = (alpha * alpha + beta * beta) // 100 + \
            4 * (abs(alpha) + abs(beta)) + 256
        for index, (d, q) in pairs:
            chk(abs(d * d + q * q - (alpha * alpha + beta * beta)) <= band,
                f'park: rotation changed |v| for {(alpha, beta)} -> {(d, q)}')
            ir, ix, if_, _ = step('inv_park_s12', umask(d, 12), umask(q, 12), index)
            chk(if_ == 0, 'inv_park: in-range rotation faulted')
            ra, rb = sfld(ir, 0, 12), sfld(ir, 12, 12)
            tol = 3 + (abs(alpha) + abs(beta)) * 0.004
            chk(abs(ra - alpha) <= tol and abs(rb - beta) <= tol,
                f'park round trip at {index}: {(alpha, beta)} -> {(ra, rb)}')
            chk(fld(ix, 0, 8) == index, 'inv_park: theta must echo the table index')
        # the two kernels are transposes of one another, so the same table index
        # used by both on the same vector must land on the same radius band, and
        # a 180-degree index shift must negate both outputs within one LSB of
        # the Q10 requantise.
        for k in (17, 51, 99, 200):
            pr, _, _, _ = step('park_s12', umask(alpha, 12), umask(beta, 12), k)
            jr, jx, jf, _ = step('inv_park_s12', umask(alpha, 12), umask(beta, 12), k)
            chk(jf == 0, 'inv_park: malformed-free beat flagged')
            da, qa = sfld(pr, 0, 12), sfld(pr, 12, 12)
            ai, bi = sfld(jr, 0, 12), sfld(jr, 12, 12)
            chk(abs((da * da + qa * qa) - (ai * ai + bi * bi)) <= 2 * band,
                f'park/inv_park disagree on the radius at index {k}')
            chk(fld(jx, 8, 2) == 0, f'inv_park: {alpha},{beta} must not saturate')
            pr2, _, _, _ = step('park_s12', umask(alpha, 12), umask(beta, 12),
                                (k + 128) & 0xFF)
            chk(max(abs(sfld(pr2, 0, 12) + da), abs(sfld(pr2, 12, 12) + qa)) <= 1,
                f'park: index +128 must negate the vector at {k}')
            jr2, _, _, _ = step('inv_park_s12', umask(alpha, 12), umask(beta, 12),
                                (k + 128) & 0xFF)
            chk(max(abs(sfld(jr2, 0, 12) + ai), abs(sfld(jr2, 12, 12) + bi)) <= 1,
                f'inv_park: index +128 must negate the vector at {k}')

    # Saturation is reported, never faulted, and it clips into the rotation
    # domain before any product: the 0-degree identity exposes the clipped value.
    for value in (2047, 1024, -2048, 0, 1023, -1024):
        want = 1 if (value > 1023 or value < -1024) else 0
        r, x, f, _ = step('park_s12', umask(value, 12), 0, 0)
        chk(f == 0, 'park: an out-of-range amplitude is not a malformed beat')
        chk(fld(x, 8, 1) == want, f'park: alpha saturation flag wrong for {value}')
        chk(sfld(r, 0, 12) == clamp(value, -1024, 1023),
            f'park: alpha must clip to [-1024,1023], got {sfld(r, 0, 12)} for {value}')
    for value in (2047, -2048, 1500):
        r, x, f, _ = step('park_s12', 0, umask(value, 12), 0)
        chk(f == 0 and fld(x, 9, 1) == 1 and sfld(r, 12, 12) == clamp(value, -1024, 1023),
            f'park: beta clip/flag wrong for {value}')
        r, x, f, _ = step('inv_park_s12', umask(value, 12), 0, 0)
        chk(f == 0 and fld(x, 8, 1) == 1 and sfld(r, 0, 12) == clamp(value, -1024, 1023),
            f'inv_park: first input clip/flag wrong for {value}')

    # --- 8. svpwm_sector: projections, sector and working times ------------
    # X = V-W, Y = W-U, Z = U-V sum to zero, so their strict-positive sign
    # triple has six live values and the two volt-second working times are two
    # of the three projections.  Both facts are checked with plain integer
    # arithmetic on the operands, and the sector is re-derived from the analytic
    # angle of the reference vector (alpha = U, beta = (U+2V)/sqrt(3)).
    def svm_row(u, v, w, control=0):
        return (umask(u, 11) | (umask(v, 11) << 11), umask(w, 11), control)

    def svm_decode(r, x):
        return dict(t1=sfld(r, 0, 12), t2=sfld(r, 12, 12), va=fld(r, 24, 3),
                    vb=fld(r, 27, 3), degenerate=fld(r, 30, 1),
                    overmod=fld(r, 31, 1), limit=fld(x, 0, 12),
                    sector=fld(x, 12, 3), idx=fld(x, 15, 3), enabled=fld(x, 18, 1))

    def svm_case(u, v, w, control=0):
        r, x, f, _ = step('svpwm_sector', *svm_row(u, v, w, control))
        d = svm_decode(r, x)
        px, py, pz = v - w, w - u, u - v
        idx = (1 if px > 0 else 0) + 2 * (1 if py > 0 else 0) + 4 * (1 if pz > 0 else 0)
        chk(d['idx'] == idx, f'svpwm: sign triple {idx} reported as {d["idx"]}')
        chk(d['enabled'] == (1 if control >> 31 else 0), 'svpwm: check enable echo')
        chk(d['limit'] == (control & 0xFFF),
            'svpwm: the supervision limit lane must echo c[11:0]')
        chk(px + py + pz == 0, 'svpwm: the three projections must sum to zero')
        if idx != 0:
            chk(sorted([d['t1'], d['t2'], d['t1'] + d['t2']]) ==
                sorted([abs(px), abs(py), abs(pz)]),
                f'svpwm: working times {d["t1"]},{d["t2"]} are not two of the '
                f'projections {px},{py},{pz}')
            chk(d['t1'] >= 0 and d['t2'] >= 0, 'svpwm: a working time went negative')
            chk(d['degenerate'] == 0, 'svpwm: a live reference is not degenerate')
            chk(d['va'] not in (0, 7) and d['vb'] not in (0, 7) and d['va'] != d['vb'],
                f'svpwm: switching pair {d["va"]:03b}/{d["vb"]:03b} is not two real vectors')
            chk(bin(d['va'] ^ d['vb']).count('1') == 1,
                'svpwm: adjacent sector vectors must differ in one phase leg')
        # T1+T2 is the longest of the three projections, so the over-modulation
        # verdict is decided by a plain integer compare against the armed limit.
        longest = max(abs(px), abs(py), abs(pz))
        over = 1 if (control >> 31 and longest > (control & 0xFFF)) else 0
        want = 1 if (over or (idx == 0)) else 0
        chk(d['overmod'] == over,
            f'svpwm: over-modulation flag vs longest projection {longest}')
        chk(f == want, f'svpwm: fault {f} for sum {px + py + pz} and limit {control & 0xFFF}')
        return d, (px, py, pz)

    def wedge_set(alpha, beta):
        """Sectors whose 60-degree wedge contains the reference (rays: both)."""
        live = []
        for k in range(6):
            ax, ay = cos(2.0 * pi * k / 6.0), sin(2.0 * pi * k / 6.0)
            bx, by = cos(2.0 * pi * (k + 1) / 6.0), sin(2.0 * pi * (k + 1) / 6.0)
            if (ax * beta - ay * alpha >= -1e-9 and
                    alpha * by - beta * bx >= -1e-9):
                live.append(k + 1)
        return live

    vertex = {}
    for leg in range(8):
        sa, sb, sc = (leg >> 2) & 1, (leg >> 1) & 1, leg & 1
        vertex[leg] = ((2.0 / 3.0) * (sa - (sb + sc) / 2.0),
                       (sqrt(3.0) / 3.0) * (sb - sc))

    def state_at(deg):
        """The switching state whose vector points along `deg`."""
        tx, ty = cos(pi * deg / 180.0), sin(pi * deg / 180.0)
        pick, best = None, None
        for leg in range(8):
            dot = vertex[leg][0] * tx + vertex[leg][1] * ty
            if best is None or dot > best + 1e-12:
                pick, best = leg, dot
        return pick

    pair_by_sector = {}
    for deg in range(0, 360, 7):
        m = 400
        th = pi * deg / 180.0
        u = round(m * cos(th))
        v = round(m * cos(th - 2.0 * pi / 3.0))
        w = round(m * cos(th + 2.0 * pi / 3.0))
        d, proj = svm_case(u, v, w)
        alpha, beta = float(u), (u + 2 * v) / sqrt(3.0)
        live = wedge_set(alpha, beta)
        chk(d['sector'] in live,
            f'svpwm: sector {d["sector"]} is not a wedge of {deg} deg {live}')
        chk(SVM_SECTOR[d['idx']] in live,
            f'svpwm: the sign-triple table says {SVM_SECTOR[d["idx"]]} at {deg} deg')
        if len(live) == 1:                       # strict interior of a wedge
            sec = live[0]
            ax, ay = (2.0 / 3.0) * cos(pi * (sec - 1) * 60.0 / 180.0), \
                (2.0 / 3.0) * sin(pi * (sec - 1) * 60.0 / 180.0)
            bx, by = (2.0 / 3.0) * cos(pi * sec * 60.0 / 180.0), \
                (2.0 / 3.0) * sin(pi * sec * 60.0 / 180.0)
            det = ax * by - ay * bx
            e1 = (alpha * by - beta * bx) / det
            e2 = (ax * beta - ay * alpha) / det
            chk(abs(d['t1'] - e1) < 2.0 and abs(d['t2'] - e2) < 2.0,
                f'svpwm: volt-second solve at {deg} deg says '
                f'{e1:.1f},{e2:.1f}, core says {d["t1"]},{d["t2"]}')
            chk(d['va'] == state_at((sec - 1) * 60.0) and
                d['vb'] == state_at(sec * 60.0),
                f'svpwm: sector {sec} pairs {d["va"]:03b}/{d["vb"]:03b} with the '
                f'wrong geometry vectors')
            chk(abs(sum(proj)) == 0, 'svpwm: projections must cancel exactly')
            pair_by_sector.setdefault(sec, (d['va'], d['vb']))
    chk(sorted(pair_by_sector) == [1, 2, 3, 4, 5, 6],
        'svpwm: the sweep did not visit all six sectors')
    for sec in range(1, 7):
        va, vb = pair_by_sector[sec]
        nxt_va, nxt_vb = pair_by_sector[sec % 6 + 1]
        chk(vb == nxt_va, f'svpwm: sector {sec} ends on a different vector than '
                          f'sector {sec % 6 + 1} starts on')
    used = set()
    for va, vb in pair_by_sector.values():
        used.update((va, vb))
    chk(len(used) == 6, 'svpwm: the six sectors must walk over six distinct vectors')
    # The +alpha axis is the one direction whose vector is fixed by the Clarke
    # definition alone: the state with the largest alpha is the one the core
    # must name as the vector sitting on that ray.
    best = max(range(8), key=lambda s: vertex[s][0])
    d, _ = svm_case(400, -200, -200)
    chk(d['vb'] == best,
        f'svpwm: the +alpha ray must land on state {best:03b}, got {d["vb"]:03b}')
    chk(d['va'] == state_at(300.0), 'svpwm: the sector behind the +alpha ray')
    # Six boundary rays: the reference sits on a vertex, so exactly one working
    # time is zero and the other is the longest projection.
    for index in range(6):
        th = pi * index / 3.0
        u = round(400 * cos(th))
        v = round(400 * cos(th - 2.0 * pi / 3.0))
        w = round(400 * cos(th + 2.0 * pi / 3.0))
        d, proj = svm_case(u, v, w)
        chk(d['sector'] in wedge_set(float(u), (u + 2 * v) / sqrt(3.0)),
            f'svpwm: ray {index * 60} deg landed outside its wedges')
        chk(min(d['t1'], d['t2']) == 0,
            f'svpwm: ray {index * 60} deg has no zero working time: {d["t1"]},{d["t2"]}')
        chk(max(d['t1'], d['t2']) == max(abs(p) for p in proj),
            f'svpwm: ray {index * 60} deg working time is not the longest projection')
    # Degenerate reference: U=V=W gives idx 0, no sector, and a fault that is
    # independent of the supervision enable.
    for control in (0, 0x80000000 | 4000):
        r, x, f, _ = step('svpwm_sector', *svm_row(300, 300, 300, control))
        d = svm_decode(r, x)
        chk(f == 1 and d['degenerate'] == 1 and d['idx'] == 0 and d['t1'] == 0 and
            d['t2'] == 0, 'svpwm: a zero-sequence reference must be flagged degenerate')
    # Supervision boundary: T1+T2 is the longest projection, so arming with the
    # limit one count above / below it must flip the verdict and nothing else.
    for limit, want in ((150, 0), (149, 1), (0, 1), (4095, 0)):
        d, _ = svm_case(100, -50, -50, 0x80000000 | limit)
        chk(d['overmod'] == want, f'svpwm: limit {limit} on T1+T2=150 must flag {want}')

    # --- 9. ipi_pid_s12: integration, windup and clamping ------------------
    def pid_row(e, ff, kp, ki, kd, control):
        return (bits2((0, 12, e), (12, 12, ff)),
                bits2((0, 12, kp), (12, 12, ki), (24, 8, kd)), control)

    def pid_read(r, x):
        return dict(out=sfld(r, 0, 12), high=fld(r, 12, 1), low=fld(r, 13, 1),
                    railed=fld(r, 14, 1), dclip=fld(r, 15, 1), hold=fld(r, 16, 1),
                    freeze=fld(r, 17, 1), restart=fld(r, 18, 1),
                    select=fld(r, 19, 1), shift=fld(r, 20, 4),
                    unclamped=sfld(x, 0, 14), integral=sfld(x, 14, 12))

    # Pure integration: ki = 2^s makes the I term the integral register verbatim,
    # so a constant error must step the output by exactly E per beat until the
    # declared 12-bit anti-windup bound is reached, and never past it.
    #
    # "Never past it" is the signed 12-bit window [-2048, 2047].  That window is
    # not symmetric, so abs(x) <= 2047 is the wrong predicate: it rejects the
    # very value (-2048) the core is required to saturate to, and it disagrees
    # with the rail lane, the fault and the state field checked below.  The
    # window is also matched against the core's own spec sentence, so this check
    # and the published contract cannot drift apart silently.
    pid_spec = next(entry for entry in CORES
                    if entry['name'] == 'ipi_pid_s12')['spec']
    pid_ihi, pid_ilo = 2047, -2048
    chk(f'[{pid_ilo},{pid_ihi}]' in pid_spec,
        'pid: the integral window checked here is no longer the window the '
        'core spec declares')
    railed_ramps = []
    for shift, e0 in ((10, 200), (9, 300), (8, 60), (10, -200), (9, -300)):
        ki = 1 << shift
        st, expect, bound = 0, 0, (pid_ilo if e0 < 0 else pid_ihi)
        raw = 0
        for beat in range(1, 24):
            control = shift | (1 << 31 if beat == 1 else 0)
            r, x, f, st = step('ipi_pid_s12',
                               *pid_row(e0, 0, 0, ki, 0, control), st)
            d = pid_read(r, x)
            # raw is the unbounded mathematical integral of the constant error
            # (closed form: beat * E), expect the step-wise saturation the
            # register must perform.  Saturating every beat and saturating the
            # whole sum once must agree, and the result must be in the window.
            raw += e0
            expect = clamp(expect + e0, pid_ilo, pid_ihi)
            chk(d['out'] == expect,
                f'pid: beat {beat} of a {e0} ramp expected {expect} got {d["out"]}')
            chk(d['integral'] == expect, 'pid: committed integral must follow the ramp')
            chk(pid_ilo <= d['integral'] <= pid_ihi,
                f'pid: the integral left its declared bound [{pid_ilo},{pid_ihi}]: '
                f'{d["integral"]} at beat {beat}')
            chk(d['integral'] == clamp(raw, pid_ilo, pid_ihi),
                f'pid: beat {beat} of a {e0} ramp: per-beat anti-windup commits '
                f'{d["integral"]} but saturating the closed-form sum {raw} gives '
                f'{clamp(raw, pid_ilo, pid_ihi)}')
            chk(d['shift'] == shift, 'pid: the requantise shift must echo c[3:0]')
            chk(d['restart'] == (1 if beat == 1 else 0), 'pid: restart echo')
            # The output sum here *is* the integral (ki = 2^s, no P, D or ff), so
            # the only rail the core can hit is the integral one: the output
            # clamp lanes must stay low and the railed lane must not.
            railed = raw != clamp(raw, pid_ilo, pid_ihi)
            chk(d['railed'] == (1 if railed else 0),
                f'pid: integral rail lane wrong at beat {beat}')
            chk(d['high'] == 0 and d['low'] == 0,
                f'pid: an output clamp at beat {beat} with the sum inside the bus')
            chk(f == (1 if railed else 0),
                f'pid: fault must follow the rail, got {f} at beat {beat}')
        # A ramp whose closed-form sum stays inside the window must never claim
        # a rail; one that leaves it must sit exactly on its own signed rail.
        chk((expect == bound) == railed,
            f'pid: a {e0} ramp ended at {expect} with rail lane {int(railed)}')
        railed_ramps.append(railed)
    # Most of those ramps exist to sit on the rail: if none of them reached it,
    # the window above would be untested and an unclamped accumulator would
    # still pass every beat check.
    chk(sum(1 for v in railed_ramps if v) >= 4,
        'pid: none of the integration ramps reached its declared rail, so the '
        'anti-windup window went untested')
    # The half-scale select clamps the OUTPUT to [-1024,1023] while the integral
    # register keeps its own [-2048,2047] window: the two limits must not be
    # confused.  A bare +200 error cannot demonstrate that, because the output
    # clamp fires first and the conditional-integration law then holds the
    # register - it never even reaches half-scale, let alone 2047.  So the same
    # ramp is swept twice, once with a compensating feedforward ('walk') that
    # keeps the output sum inside half-scale so the register is free to walk past
    # 1023 up to its own rail, and once without it ('hold'), where the clamp must
    # freeze the register.  Every expectation is hand-derived from the beat count.
    half_hi, half_lo = 1023, -1024
    for offset, label in ((-1200, 'walk'), (0, 'hold')):
        # The largest integral whose committed sum still fits half-scale; below
        # it the register moves freely, at and above it anti-windup freezes it.
        free_top = 200 * ((half_hi - offset) // 200)
        st, seen = 0, []
        for beat in range(1, 17):
            control = 10 | (1 << 29) | (1 << 31 if beat == 1 else 0)
            r, x, f, st = step('ipi_pid_s12',
                               *pid_row(200, offset, 0, 1024, 0, control), st)
            d = pid_read(r, x)
            # Hand-applied recursion, one beat at a time, straight from the spec
            # law: irv = previous committed integral + e, itv = irv saturated
            # into the register window, the output sum is built from itv, and a
            # railed-high output with e > 0 puts the previous value back.
            prev = 0 if beat == 1 else want_prev
            irv = prev + 200
            trial = clamp(irv, pid_ilo, pid_ihi)
            raw_sum = trial + offset
            want_out = clamp(raw_sum, half_lo, half_hi)
            want_high = 1 if raw_sum > half_hi else 0
            want_low = 1 if raw_sum < half_lo else 0
            want_int = prev if want_high else trial
            want_rail = 1 if trial != irv else 0
            want_prev = want_int
            # For a ramp the register is free to follow, step-wise saturation and
            # one-shot saturation of the closed-form sum 200*beat must agree.
            free_sum = clamp(200 * beat, pid_ilo, pid_ihi) if want_high == 0 else None
            seen.append(d['integral'])
            chk(d['select'] == 1, 'pid: clamp select must echo c[29]')
            chk(d['shift'] == 10, 'pid: shift echo under the half-scale select')
            chk(d['integral'] == want_int,
                f'pid: {label}: half-scale integral at beat {beat} gave '
                f'{d["integral"]} want {want_int}')
            chk(pid_ilo <= d['integral'] <= pid_ihi,
                f'pid: {label}: the integral left its own window at beat {beat}')
            if free_sum is not None:
                chk(d['integral'] == free_sum,
                    f'pid: {label}: beat {beat}: the free register ramp should be '
                    f'the saturated closed-form sum {free_sum}, saw {d["integral"]}')
            chk(d['out'] == want_out,
                f'pid: {label}: half-scale output at beat {beat} gave {d["out"]} '
                f'want {want_out}')
            chk(half_lo <= d['out'] <= half_hi,
                f'pid: {label}: the output left the half-scale window at beat {beat}')
            chk(d['high'] == want_high and d['low'] == want_low,
                f'pid: {label}: output clamp lanes at beat {beat}')
            chk(d['railed'] == want_rail,
                f'pid: {label}: integral rail lane at beat {beat} must follow '
                f'the register window, not the output window')
            chk(d['hold'] == want_high,
                f'pid: {label}: the anti-windup hold lane must fire exactly while '
                f'the railed output pushes against a positive error')
            chk(f == (want_high or want_low or want_rail),
                f'pid: {label}: fault lane at beat {beat}')
        if label == 'walk':
            chk(max(seen) > half_hi and seen[-1] == pid_ihi,
                f'pid: walk: the integral stopped at {max(seen)}, so the '
                'half-scale output window and the register window were never '
                'distinguished')
        else:
            chk(max(seen) == free_top < half_hi,
                f'pid: hold: the register should freeze at the last free sum '
                f'{free_top}, saw {max(seen)}')
    # Zero gains must give a zero output whatever the error does.
    st = 0
    for beat in range(30):
        e = 2000 if beat % 2 else -2000
        r, x, f, st = step('ipi_pid_s12', *pid_row(e, 0, 0, 0, 0, beat % 16), st)
        d = pid_read(r, x)
        chk(d['out'] == 0, f'pid: zero gains produced {d["out"]} at beat {beat}')
        chk(f == 0, 'pid: a zeroed controller must not claim a clamp')
    # Proportional term only: the output is the declared product/requantise, and
    # Python's own integer arithmetic is the oracle.
    for kp in (1, 31, 512, 1024, 2047, -700, -2048, 0):
        for shift in (0, 4, 10, 15):
            for e in (2047, -2048, 1000, -999, 7, 0, 1):
                want = clamp(round_shift(e * kp, shift), -2048, 2047)
                r, x, f, _ = step('ipi_pid_s12',
                                  *pid_row(e, 0, kp, 0, 0, shift))
                d = pid_read(r, x)
                chk(d['out'] == want,
                    f'pid: P term e={e} kp={kp} s={shift} gave {d["out"]} want {want}')
                chk(d['high'] == (1 if want == 2047 and round_shift(e * kp, shift) != want
                                  else 0), 'pid: P-only high flag')
                chk(f == (want != round_shift(e * kp, shift)),
                    'pid: P-only clamp must drive the fault')
    # Anti-windup law read straight off the state register: while the output is
    # railed high the integral must not grow, and while it is railed low it must
    # not shrink.
    st, prev_integral = 0, None
    rails = set()
    for beat in range(40):
        e = 1800 if beat < 20 else -1800
        control = 10 | (1 << 31 if beat == 0 else 0)
        r, x, f, nxt = step('ipi_pid_s12', *pid_row(e, 0, 0, 1024, 0, control), st)
        d = pid_read(r, x)
        integral_now = sfld(st, 0, 12)
        integral_after = sfld(nxt, 0, 12)
        if prev_integral is not None:
            chk(integral_now == prev_integral,
                'pid: the state register and the committed integral disagree')
        if d['high'] and e > 0:
            chk(integral_after == integral_now,
                f'pid: windup at beat {beat}: integral grew while railed high')
        if d['low'] and e < 0:
            chk(integral_after == integral_now,
                f'pid: unwindup at beat {beat}: integral shrank while railed low')
        # The window is the signed 12-bit interval [-2048, 2047]: its negative
        # rail is one count deeper than its positive rail, so abs() is the wrong
        # predicate here too -- it would reject the very rail the law saturates
        # to.  The second check is the stronger form: the committed integral must
        # be either the held value or the previous value stepped by e and
        # saturated, so a 12-bit wrap that landed back inside the window would
        # still be caught.
        chk(pid_ilo <= integral_after <= pid_ihi,
            f'pid: the integral left its declared bound [{pid_ilo},{pid_ihi}]: '
            f'{integral_after} at beat {beat}')
        chk(integral_after in (integral_now,
                               clamp(integral_now + e, pid_ilo, pid_ihi)),
            f'pid: beat {beat}: the committed integral is neither the held value '
            f'nor the saturated step of {integral_now} by {e}: {integral_after}')
        if integral_after in (pid_ilo, pid_ihi):
            rails.add(integral_after)
        prev_integral = integral_after
        st = nxt
    # Both rails must actually have been reached, or this sweep would never have
    # exercised the asymmetric corner it is checking.
    chk(rails == {pid_ilo, pid_ihi},
        f'pid: the windup sweep only reached the rails {sorted(rails)}')
    # Freeze holds the integrator exactly, and restart clears it back to zero:
    # both are visible as the state register, not as arithmetic.
    st = 0
    for beat in range(6):
        r, x, f, st = step('ipi_pid_s12', *pid_row(500, 0, 0, 1024, 0, 10), st)
    held = sfld(st, 0, 12)
    chk(held != 0, 'pid: the warm-up ramp left no integral at all')
    for beat in range(5):
        r, x, f, nxt = step('ipi_pid_s12', *pid_row(2047, 2047, 2047, 1024, 255,
                                                   10 | (1 << 30)), st)
        d = pid_read(r, x)
        chk(sfld(nxt, 0, 12) == held, 'pid: c[30] must hold the integral register exactly')
        chk(d['freeze'] == 1, 'pid: freeze echo')
        chk(d['integral'] == held, 'pid: the frozen integral lane must report the hold')
        st = nxt
    r, x, f, nxt = step('ipi_pid_s12', *pid_row(123, 0, 0, 1024, 0, 10 | (1 << 31)), st)
    d = pid_read(r, x)
    chk(d['out'] == 123,
        f'pid: after a restart the output must be one beat of integration, got {d["out"]}')
    chk(sfld(nxt, 0, 12) != held, 'pid: restart must clear the wound-up integrator')

    # --- 10. backemf_obs_s12: IR drop, clipping and convergence -------------
    def obs_row(v, i, res, control):
        return (bits2((0, 12, v), (12, 12, i)), bits2((0, 12, res)), control)

    def obs_read(r, x):
        return dict(speed=sfld(r, 0, 12), rail=fld(r, 12, 1), clip=fld(r, 13, 1),
                    freeze=fld(r, 14, 1), restart=fld(r, 15, 1),
                    lam=fld(r, 16, 4), sR=fld(r, 20, 4),
                    emf=sfld(x, 0, 12), acc=sfld(x, 12, 12), beats=fld(x, 24, 8))

    # The IR drop is one signed product through the fabric multiplier, exactly
    # the path the no-`*` rule protects: compare it against Python's own
    # integer multiply, shift and clamp over a grid that covers both signs.
    # The swept shift must actually reach the control word: c[3:0] is the IR
    # shift, so a fixed 4 here would silently reduce this grid to one shift.
    for sR in (0, 2, 4, 11):
        for i in (-2000, -511, -1, 0, 1, 300, 2047):
            for res in (-2048, -1024, -1, 0, 5, 512, 2047):
                v = 400
                drop = round_shift(i * res, sR)
                want = clamp(v - drop, -2048, 2047)
                r, x, f, _ = step('backemf_obs_s12', *obs_row(v, i, res,
                                                               sR | (4 << 4)))
                d = obs_read(r, x)
                chk(d['emf'] == want,
                    f'observer: emf {d["emf"]} != v-iR {want} for {v},{i},{res},s{sR}')
                chk(d['clip'] == (1 if want != v - drop else 0),
                    'observer: the clip lane must follow the 12-bit domain')
                chk(f == (1 if want != v - drop else 0),
                    'observer: a clipped emf must raise the fault')
                chk(d['sR'] == sR, 'observer: the IR shift must echo c[3:0]')
    # Zero resistance makes the emf the measured voltage, so a constant voltage
    # is a constant emf E and the leaky integrator obeys the documented
    # recurrence acc_next = acc + E - (acc >>> lambda).  Its absorbing fixed point
    # is the first acc with floor(acc / 2^lambda) == E, and the speed word is
    # that register requantised by sF: for a negative fixed point that rounding
    # gives E + 1, not E, so convergence has to be watched in the register.
    #
    # Two defects in the old sweep, both on the checking side: lambda was written
    # into c[3:0], the IR-shift slot, so lambda stayed 0, the register merely
    # tracked one beat of emf and nothing ever converged; and the convergence
    # beat was bounded by a magic 60 that the lambda=4 case cannot satisfy.
    # Neither is a kernel fault.  With q = 2^lambda the deficit right after the
    # restart beat is |E|*q - |E| and it obeys d_next = d - ceil(d / q), a
    # contraction that predicts the fixed-point beat in closed form, so that
    # prediction is what gets asserted.
    def obs_beats(lam_, level):
        q = 1 << lam_
        deficit = abs(level) * q - abs(level)
        count = 1
        while deficit > 0:
            deficit -= max(1, (deficit + q - 1) // q)
            count += 1
        return count

    for lam, sF, e_level in ((2, 2, 100), (3, 3, 250), (4, 4, 60), (1, 1, 500),
                             (2, 2, -140), (0, 0, 77)):
        st = 0
        previous = None
        reached = None
        want_beats = obs_beats(lam, e_level)
        for beat in range(1, 90):
            r, x, f, st = step('backemf_obs_s12',
                               *obs_row(e_level, 0, 0, (sF << 4) | (lam << 8) |
                                        (1 << 31 if beat == 1 else 0)), st)
            d = obs_read(r, x)
            acc = sfld(st, 0, 12)
            chk(d['emf'] == e_level, 'observer: with R=0 the emf is the voltage')
            chk(d['clip'] == 0 and d['rail'] == 0,
                f'observer: a steady inside-range input claimed a rail at beat {beat}')
            chk(d['beats'] == min(beat, 255), 'observer: the beat counter must count')
            chk(f == 0, f'observer: a steady inside-range input faulted at beat {beat}')
            chk(d['lam'] == lam and d['sR'] == 0,
                'observer: lambda must live in c[11:8] and be echoed from there')
            chk(-2048 <= acc <= 2047,
                f'observer: the integrator left the signed window at beat {beat}')
            chk(d['speed'] == round_shift(acc, sF),
                f'observer: beat {beat}: the speed word must be the register '
                f'requantised by sF')
            if previous is not None:
                moving = acc - previous
                if e_level > 0:
                    chk(moving >= 0, 'observer: the estimate must rise monotonically')
                else:
                    chk(moving <= 0, 'observer: the estimate must fall monotonically')
            previous = acc
            at_fixed = (acc >> lam) == e_level
            if at_fixed and reached is None:
                reached = beat
            if reached is not None and beat > reached:
                chk(at_fixed,
                    f'observer: the fixed point washed out at beat {beat}')
        chk(reached == want_beats,
            f'observer: lambda={lam} emf={e_level}: the contraction law predicts '
            f'the fixed point at beat {want_beats}, the register arrived at '
            f'{reached}')
        chk((acc >> lam) == e_level,
            'observer: the fixed point must be floor(acc/2^lambda) = emf exactly')
        chk(abs(d['speed'] - e_level) <= 1,
            'observer: the reported speed must stay within one quantisation of '
            'the emf')
    # The observer integrator has its own anti-windup, and the convergence sweep
    # above never touches it: every level there has a fixed point |E|*2^lambda
    # inside the window.  Here the closed-form fixed point sits far outside the
    # signed 12-bit window, so the register must pin on the window edge, the rail
    # lane must fire on every pinned beat, the fault must follow it, and the speed
    # word must stay the requantised register rather than the runaway sum.  The
    # expectation is the spec recurrence acc_next = acc + E - (acc >>> lambda)
    # hand-applied one beat at a time, then saturated into [-2048, 2047].
    for e_rail, lam_w, sF_w in ((2047, 4, 4), (-1400, 3, 3), (700, 5, 0)):
        st, acc, rails = 0, 0, 0
        for beat in range(1, 25):
            r, x, f, st = step('backemf_obs_s12',
                               *obs_row(e_rail, 0, 0, (sF_w << 4) | (lam_w << 8) |
                                        (1 << 31 if beat == 1 else 0)), st)
            d = obs_read(r, x)
            trial = acc + e_rail - (acc >> lam_w)
            acc = clamp(trial, -2048, 2047)
            want_rail = 1 if trial != acc else 0
            rails += want_rail
            chk(d['emf'] == e_rail, 'observer: with R=0 the rail sweep emf is the voltage')
            chk(d['beats'] == min(beat, 255),
                'observer: the beat counter must count while railed')
            chk(sfld(st, 0, 12) == acc,
                f'observer: railed integrator at beat {beat}: state says '
                f'{sfld(st, 0, 12)} want {acc}')
            chk(-2048 <= acc <= 2047,
                f'observer: the railed integrator left its window at beat {beat}')
            chk(d['rail'] == want_rail,
                f'observer: beat {beat}: the rail lane must fire exactly when the '
                f'sum {trial} left the window')
            chk(f == want_rail,
                f'observer: beat {beat}: a railed integrator must raise the fault')
            chk(d['speed'] == round_shift(acc, sF_w),
                f'observer: beat {beat}: the speed word must be the pinned '
                f'register requantised by sF')
        chk(acc in (-2048, 2047) and rails >= 20,
            f'observer: emf={e_rail} lambda={lam_w}: the integrator never pinned '
            f'to its window (ended at {acc} after {rails} rail beats)')
    # The freeze lane holds the integrator register exactly.
    st = 0
    for beat in range(10):
        r, x, f, st = step('backemf_obs_s12', *obs_row(600, 100, 300, 3 | (3 << 4)), st)
    held = sfld(st, 0, 12)
    for beat in range(4):
        r, x, f, nxt = step('backemf_obs_s12',
                            *obs_row(-2000, 2000, -2000, 3 | (3 << 4) | (1 << 30)), st)
        d = obs_read(r, x)
        chk(sfld(nxt, 0, 12) == held, 'observer: c[30] must freeze the integrator')
        chk(d['freeze'] == 1, 'observer: freeze echo')
        chk(d['acc'] == held, 'observer: the acc lane must report the frozen value')
        st = nxt
    # A restart seeds the beat counter and empties the integrator.
    r, x, f, nxt = step('backemf_obs_s12', *obs_row(500, 0, 0, 2 | (2 << 4) | (1 << 31)),
                        st)
    d = obs_read(r, x)
    chk(d['restart'] == 1 and d['beats'] == 1, 'observer: restart must reset the beat count')
    chk(sfld(nxt, 0, 12) == clamp(500, -2048, 2047) or sfld(nxt, 0, 12) != held,
        'observer: restart must clear the wound-up integrator')

    return tally['n']






