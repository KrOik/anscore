# --------------------------------------------------------------------------
# Derived constants.  Nothing below is typed from memory: each one is computed
# from sqrt(3), pi or atan(2^-i) here, and selftest() re-derives it from
# published geometry as an independent check.
# --------------------------------------------------------------------------
def round_shift(value, shift):
    """Round-half-up arithmetic shift, the exact mirror of the RTL expression."""
    return value if shift == 0 else (value + (1 << (shift - 1))) >> shift


CL_K = round((1 << 11) / sqrt(3.0))            # 1/sqrt3 as a 12-bit signed slice
CL_SHIFT = 11

SIN_Q = [round(1024.0 * sin(2.0 * pi * k / 256.0)) for k in range(256)]
COS_Q = [round(1024.0 * cos(2.0 * pi * k / 256.0)) for k in range(256)]
SINCOS_IMAGE = [((COS_Q[k] & 0xfff) << 12) | (SIN_Q[k] & 0xfff)
                for k in range(256)]

# Divider-free speed: 1/p normalised to an 8-bit mantissa u in [128,255],
# r = round(2^17/u) so that p ~= u*2^(msb-7) gives 1024*2^msb/p exactly.
RECIP = [round((1 << 17) / u) for u in range(128, 256)]

CORDIC_ARC = [round(8192.0 * atan(2.0 ** -i)) for i in range(12)]
CORDIC_GAIN = []
_g = 1.0
for _i in range(12):
    _g *= sqrt(1.0 + 4.0 ** -_i)
    CORDIC_GAIN.append(_g)
PI_WORD = round(8192.0 * pi)                   # +/-180 deg bound of the angle word
HALF_PI_WORD = round(4096.0 * pi)              # the pre-fold threshold
CORDIC_UNIT = 1024                             # Q10 unit vector at restart


def _uvw(theta, mag):
    """Phase voltages of a reference vector, amplitude-invariant Clarke.

    alpha = U, beta = (U + 2V)/sqrt3, W = -U-V, so U+V+W = 0 exactly and the
    vector magnitude is mag in the same counts as U.
    """
    u = mag * cos(theta)
    beta = mag * sin(theta)
    v = (sqrt(3.0) * beta - u) / 2.0
    return u, v, -u - v


def _hex_vertex(index):
    """alpha,beta of switching state index in {0..5} -> V1..V6 at 0,60,...,300 deg."""
    states = (0b100, 0b110, 0b010, 0b011, 0b001, 0b101)
    sa, sb, sc = (states[index] >> 2) & 1, (states[index] >> 1) & 1, states[index] & 1
    return (2.0 / 3.0) * (sa - (sb + sc) / 2.0), (sqrt(3.0) / 3.0) * (sb - sc)


def _volt_seconds(theta):
    """Exact adjacent-vector working times for the sector holding theta."""
    sec = int((degrees(theta) % 360.0) // 60)
    a1, b1 = _hex_vertex(sec)
    a2, b2 = _hex_vertex((sec + 1) % 6)
    det = a1 * b2 - a2 * b1
    al, be = cos(theta), sin(theta)
    return sec + 1, (al * b2 - be * a2) / det, (a1 * be - b1 * al) / det


def _derive_svpwm():
    """Recover the sector table and the T1/T2 projection sources from geometry.

    The three projections X=V-W, Y=W-U, Z=U-V sum to zero, so their signs form
    exactly six non-degenerate triples.  For each triple the volt-second solve
    above identifies one sector and expresses T1 and T2 as two of the six
    signed projections; intersecting the candidates over every angle inside the
    wedge leaves a unique answer.  Returns (sector, t1, t2) indexed by
    idx = signX + 2*signY + 4*signZ, with None for the degenerate triples.
    """
    names = ('X', 'Y', 'Z')
    sector_of, t1_of, t2_of = [None] * 8, [None] * 8, [None] * 8
    for idx in range(1, 7):
        secs, set1, set2 = set(), None, None
        for step in range(0, 1440):
            theta = 2.0 * pi * step / 1440.0
            u, v, w = _uvw(theta, 1.0)
            px, py, pz = v - w, w - u, u - v
            if (1 if px > 0 else 0) + 2 * (1 if py > 0 else 0) + 4 * (1 if pz > 0 else 0) != idx:
                continue
            sec, t1, t2 = _volt_seconds(theta)
            if min(t1, t2) < 1e-3:                     # wedge boundary: ambiguous
                continue
            secs.add(sec)
            hit1, hit2 = set(), set()
            for nm, val in zip(names, (px, py, pz)):
                if abs(val - t1) < 1e-9:
                    hit1.add(nm)
                if abs(val + t1) < 1e-9:
                    hit1.add('-' + nm)
                if abs(val - t2) < 1e-9:
                    hit2.add(nm)
                if abs(val + t2) < 1e-9:
                    hit2.add('-' + nm)
            set1 = hit1 if set1 is None else (set1 & hit1)
            set2 = hit2 if set2 is None else (set2 & hit2)
        assert len(secs) == 1 and len(set1) == 1 and len(set2) == 1, (idx, secs, set1, set2)
        sector_of[idx] = secs.pop()
        t1_of[idx] = set1.pop()
        t2_of[idx] = set2.pop()
    return sector_of, t1_of, t2_of


SVM_SECTOR, SVM_T1, SVM_T2 = _derive_svpwm()
