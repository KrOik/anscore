# 2/3. park_s12 and inv_park_s12  (three-multiplier Gauss rotation pair)
# ==========================================================================
# One template, two sign conventions: the forward transform subtracts the
# sine cross term and uses (cos-sin) as the third factor, the inverse adds it
# and uses (cos+sin).  Everything else -- widths, saturation, rounding, the
# aux layout -- is byte-identical, so the pair cannot drift apart.
PARK_TEMPLATE = """
av = $signed(a[11:0]);
bv = $signed(b[11:0]);
pth = c[7:0];
pw = sincos[pth];
ccs = $signed(pw[23:12]);
snx = $signed(pw[11:0]);
if(av > 14'sd1023)      begin ai = 14'sd1023;  pfl[0] = 1'b1; end
else if(av < -14'sd1024) begin ai = -14'sd1024; pfl[0] = 1'b1; end
else                    begin ai = av;         pfl[0] = 1'b0; end
if(bv > 14'sd1023)      begin bi = 14'sd1023;  pfl[1] = 1'b1; end
else if(bv < -14'sd1024) begin bi = -14'sd1024; pfl[1] = 1'b1; end
else                    begin bi = bv;         pfl[1] = 1'b0; end
nsx = __SECOND__;
abv = ai + bi;
csd = __THIRD__;
pk1a = ai[11:0];
pk1b = ccs[11:0];
pk2a = bi[11:0];
pk2b = nsx[11:0];
pk3a = abv[11:0];
pk3b = csd[11:0];
swide = pk1 - pk2 + 24'sd512;
o1v = swide >>> 10;
swide = pk3 - pk1 - pk2 + 24'sd512;
o2v = swide >>> 10;
m1v = o1v < 14'sd0 ? -o1v : o1v;
m2v = o2v < 14'sd0 ? -o2v : o2v;
pfl[2] = m1v > 14'sd1023;
pfl[3] = m2v > 14'sd1023;
if(c[30:8]!=0) f=1'b1;
else begin
    r = {8'd0, o2v[11:0], o1v[11:0]};
    x = {20'd0, pfl[3], pfl[2], pfl[1], pfl[0], pth};
    f = 1'b0;
end"""


def park_body(second, third):
    return PARK_TEMPLATE.replace('__SECOND__', second).replace('__THIRD__', third)


