def slice_decl(out, xa, xb):
    return (f'wire [23:0] {out}_raw;\n'
            f'wire signed [23:0] {out} = $signed({out}_raw);\n'
            f'MULT12X12 u_{out} (.DOUT({out}_raw), .A({xa}), .B({xb}), '
            f".CLK(2'b00), .CE(2'b00), .RESET(2'b00));\n")


def operands(*names):
    return 'reg [11:0] ' + ', '.join(names) + ';\n'


