def m_ipi_pid(a, b, c, state):
    if (a >> 24) or (c & 0x1FFFFFF0):
        return 0, 0, 1, state
    ev = to_signed(a & 0xFFF, 12)
    ffv = to_signed((a >> 12) & 0xFFF, 12)
    sft = c & 0xF
    kp = to_signed(b & 0xFFF, 12)
    ki = to_signed((b >> 12) & 0xFFF, 12)
    kd = (b >> 24) & 0xFF
    if c >> 31:
        i0v = epv = 0
    else:
        i0v = sfld(state, 0, 12)
        epv = sfld(state, 12, 12)
    dev = to_signed(ev - epv, 14)
    dec = clamp(dev, -2048, 2047)
    pfl = [1 if dec != dev else 0, 0, 0, 0]
    irv = to_signed(i0v + ev, 14)
    if (c >> 30) & 1:
        itv, pfl[1] = i0v, 0
    else:
        itv = clamp(irv, -2048, 2047)
        pfl[1] = 1 if itv != irv else 0
    terms = []
    for left, right in ((ev, kp), (itv, ki), (dec, kd)):
        product = to_signed(to_signed(umask(left, 12), 12) *
                            to_signed(umask(right, 12), 12), 24)
        terms.append(to_signed(round_shift(product, sft), 32))
    hiv, lov = (1023, -1024) if ((c >> 29) & 1) else (2047, -2048)
    outv = to_signed(terms[0] + terms[1] + terms[2] + ffv, 32)
    if outv > hiv:
        outc, pfl[2], pfl[3] = hiv, 1, 0
    elif outv < lov:
        outc, pfl[2], pfl[3] = lov, 0, 1
    else:
        outc, pfl[2], pfl[3] = outv, 0, 0
    wind = 1 if (pfl[2] and ev > 0) or (pfl[3] and ev < 0) else 0
    icv = i0v if (wind and not ((c >> 30) & 1)) else itv
    new_state = setf(setf(state, 0, 12, icv), 12, 12, ev)
    r = (sft << 20) | (((c >> 29) & 1) << 19) | ((c >> 31) << 18) | \
        (((c >> 30) & 1) << 17) | (wind << 16) | (pfl[0] << 15) | (pfl[1] << 14) | \
        (pfl[3] << 13) | (pfl[2] << 12) | umask(outc, 12)
    x = (umask(icv, 12) << 14) | umask(outv, 14)
    return r, x, pfl[2] or pfl[3] or pfl[1], new_state


def m_backemf(a, b, c, state):
    if (a >> 24) or (b >> 12) or (c & 0x3FFFF000):
        return 0, 0, 1, state
    vv = to_signed(a & 0xFFF, 12)
    ivv = to_signed((a >> 12) & 0xFFF, 12)
    rv = to_signed(b & 0xFFF, 12)
    sr, sf, lam = c & 0xF, (c >> 4) & 0xF, (c >> 8) & 0xF
    product = to_signed(to_signed(umask(ivv, 12), 12) *
                        to_signed(umask(rv, 12), 12), 24)
    drop = to_signed(round_shift(product, sr), 32)
    emfr = to_signed(vv - drop, 32)
    ofl = [0, 0]
    emf = clamp(emfr, -2048, 2047)
    ofl[0] = 1 if emf != emfr else 0
    restart = c >> 31
    acc0 = 0 if restart else sfld(state, 0, 12)
    btr0 = 0 if restart else fld(state, 12, 8)
    lr = acc0 >> lam if lam else acc0
    accw = to_signed(acc0 + emf - lr, 32)
    if (c >> 30) & 1:
        accn, ofl[1] = acc0, 0
    else:
        accn = clamp(accw, -2048, 2047)
        ofl[1] = 1 if accn != accw else 0
    spd = to_signed(round_shift(accn, sf), 14)
    btr = 255 if btr0 == 255 else btr0 + 1
    new_state = setf(setf(state, 0, 12, accn), 12, 8, btr)
    r = (sr << 20) | (lam << 16) | (restart << 15) | (((c >> 30) & 1) << 14) | \
        (ofl[0] << 13) | (ofl[1] << 12) | umask(spd, 12)
    x = (btr << 24) | (umask(accn, 12) << 12) | umask(emf, 12)
    return r, x, ofl[0] or ofl[1], new_state


def m_mt_speed(a, b, c, state):
    if (a >> 11) or (b >> 12) or (c & 0x7FFFF00F):
        return 0, 0, 1, state
    nv = to_signed(a & 0x7FF, 11)
    pv = b & 0xFFF
    sv, tv = (c >> 4) & 0xF, (c >> 8) & 0xF
    if c >> 31:
        pp, to0 = 0, 0
    else:
        pp = fld(state, 0, 12)
        to0 = fld(state, 24, 12)
    an = to_signed(-nv, 14) if nv < 0 else umask(nv, 14)
    mb = 0
    for index in range(1, 12):
        if (pv >> index) & 1:
            mb = index
    un = umask(pv >> (mb - 7), 9) if mb > 7 else umask(pv << (7 - mb), 9)
    rni = un - 128 if 128 <= un <= 255 else 0
    rn = RECIP[rni]
    ms1 = to_signed(to_signed(umask(an, 12), 12) * to_signed(umask(rn, 12), 12), 24)
    sgn = to_signed(mb + 10 - sv, 7)
    if nv == 0 or pv == 0:
        mag = 0
    elif sgn >= 0:
        mag = to_signed(round_shift(ms1, sgn), 32)
    else:
        mag = to_signed(ms1 << (-sgn), 32)
    sp = to_signed(-mag, 32) if nv < 0 else mag
    ovr = 1 if (sp > 2047 or sp < -2048) else 0
    und = 1 if (nv != 0 and pv != 0 and mag == 0) else 0
    npr = 1 if (pv == 0 and nv != 0) else 0
    spc = clamp(sp, -2048, 2047)
    to = 0 if nv != 0 else (4095 if to0 == 4095 else to0 + 1)
    tf = 1 if (tv != 0 and to > tv) else 0
    new_state = setf(setf(setf(setf(state, 0, 12, pv), 12, 12, nv),
                          24, 12, to), 36, 12, spc)
    r = ((c >> 31) << 16) | (npr << 15) | (tf << 14) | (und << 13) | (ovr << 12) | \
        umask(spc, 12)
    x = (sv << 28) | (mb << 24) | (to << 12) | umask(pv - pp, 12)
    return r, x, ovr or und or npr or tf, new_state


