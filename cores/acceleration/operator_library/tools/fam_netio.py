"""Network-processing and table-lookup accelerators: one beat = a whole branchy loop.

Family theme. Software pays for a routing table, a Bloom filter, a sketch or a
VLAN parse with a loop that carries control dependence: one compare, one branch
and one cache-missing indirection per element. Every core here retires a whole
parallel block of that work in one enabled beat: 16 longest-prefix compares with
a longest-match priority pick, four one's-complement folds, a 32-term XOR-masked
Toeplitz product, three stacked VLAN slots classified at once, sixteen Bloom bit
sets, sixteen sketch read-modify-writes, a 256-bit register popcount, a rotating
find-first-set and a four-flow deficit round-robin round. No core contains a
multiply or a divide: table reads, shifts, adds, compares and conditional
subtracts only, and every table image is generated by tables() below so a table
cell has exactly one definition shared by the RTL and the Python model.

Body vocabulary (declared by the template, reset each evaluation):
    r x                       result/aux registers, 32 bit
    f                         fault flag
    temp mask pa pb pc ph pl  32-bit unsigned temporaries
    ext                       33-bit unsigned (carry capture)
    wide wide2                64-bit unsigned
    swide swide2              64-bit signed
    sa sb sc                  $signed(a), $signed(b), $signed(c)
    data                      {a,b,c} as one 96-bit word
    i j idx lane sh           integers
    state_r state_n           256-bit state; only accepted beats commit it

Restart convention: c[31]=1 discards the carried walk/sketch state and re-arms it
from that beat's own fields, so a new lookup or a new flow set needs no drain;
session counters that are declared persistent survive a restart. Bits a core
validates are listed in its spec with the exact malformed rule; on such a beat
result=aux=0, fault=1 and the state is kept untouched.
"""
from random import Random

FAMILY = 'netio'
MASK = (1 << 32) - 1
BOARD_ROWS = 128

CORES = []


def core(name, spec, body, advantage, lanes, **kwargs):
    CORES.append(dict(name=name, family=FAMILY, spec=spec, body=body,
                      advantage=advantage, lanes=lanes, **kwargs))


