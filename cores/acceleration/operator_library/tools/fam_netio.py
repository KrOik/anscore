def _m_toeplitz(a, b, c, state):
    key = tables('toeplitz_rss')['key'][0] | (tables('toeplitz_rss')['key'][1] << 32)
    ain = a
    stray = 0
    for i in range(4):
        if not (b >> i) & 1:
            if (ain >> (8 * i)) & 0xFF:
                stray = 1
            ain &= ~(0xFF << (8 * i)) & MASK
    if (c >> 31) & 1:
        ain = int(format(ain, '032b')[::-1], 2)
    out = drop = cnt = 0
    for i in range(32):
        if (ain >> i) & 1:
            out ^= (key >> i) & MASK
            drop ^= (key >> (i + 32)) & MASK
            cnt += 1
    if (b >> 4) & 0x0FFFFFFF:
        return 0, 0, 1, state
    x = ((cnt & 0x3F) | (((c >> 31) & 1) << 6) | ((b & 0xF) << 7)
         | (stray << 11) | ((((drop >> 16) ^ drop) & 0xFFFF) << 16))
    return out, x, 1 if stray else 0, state


