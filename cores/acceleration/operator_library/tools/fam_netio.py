        assert x & 0x1FF == occupancy == len(reference), (x, len(reference))
        assert (x >> 18) & 0x1FF == previous_occupancy
        assert (x >> 9) & 0x7F == occupancy - previous_occupancy
        assert (x >> 27) & 1 == 0 and (x >> 16) & 1 == 0
        previous_occupancy = occupancy
