    for lane, key in enumerate(qkeys):
        positions = _ref_bloom_indices(key, salt)
        fresh = any(not (work >> pos) & 1 for pos in positions)
        assert ((ri >> (4 + lane)) & 1) == (1 if fresh else 0), (lane, key, hex(ri))
        for pos in positions:
            if not (work >> pos) & 1:
                digest ^= pos
                work |= 1 << pos
    assert (ri >> 8) & 0xFF == digest, (hex(ri), digest)
    assert ins == work
    checks += 1
    # malformed field keeps the filter
    r, x, f, after = step('bloom4_update', 0, 0, salt | (1 << 20), before)
    assert (r, x, f, after) == (0, 0, 1, before)
    checks += 2
    # saturation path: fill the filter past the seven-eighths bound
    state = 0
    filler = 0
    faults = 0
    while bin(state).count('1') <= 225 and filler < 200:
        keys = [rngb.getrandbits(16) for _ in range(4)]
        r, x, f, state = step('bloom4_update', keys[0] | (keys[1] << 16),
                              keys[2] | (keys[3] << 16), 0, state)
        faults += 1 if f else 0
        assert (x >> 17) & 1 == (1 if f else 0)
        filler += 1
    assert faults >= 1 and bin(state).count('1') > 224, (faults, bin(state).count('1'))
    checks += 1
    # A seed beat clears the filter before its own lanes run, so a seed+query
    # beat leaves the register empty whatever it held: 0x8000_0100 with the
    # filter previously at 225+ bits must come out as state 0, after 0, set 0,
    # before 0 (the seeded filter is what the lanes were measured against) and
    # no lane may claim a hit.
    occupied = bin(state).count('1')
    assert occupied > 224, occupied
    r, x, f, state = step('bloom4_update', 0xFFFF_FFFF, 0xFFFF_FFFF, 0x8000_0100, state)
    assert state == 0 and (x & 0x1FF) == 0 and (x >> 9) & 0x7F == 0
    assert (x >> 18) & 0x1FF == 0 and (x >> 27) & 1 == 1 and (x >> 16) & 1 == 1
    assert f == 0 and r == 0, (hex(r), f)
    checks += 1
    # Seed plus insert on a degenerate tuple: a = b = 0xFFFF_FFFF puts the key
    # 0xFFFF on all four lanes, whose positions with salt 0 are h0 = 0,
    # h1 = ((0xF^0xF^0xF^0xF)&0xF | 1) = 1, i.e. bits 0,1,2,3. The seed cleared
    # the filter, so no lane may claim a hit, only lane 0 may claim new bits, and
    # the digest is 0^1^2^3 = 0.
    r, x, f, state = step('bloom4_update', 0xFFFF_FFFF, 0xFFFF_FFFF, 0x8000_0000, state)
    assert _bits(state, 0, 256) == 0xF and (x & 0x1FF) == 4 and (x >> 9) & 0x7F == 4
    assert (x >> 18) & 0x1FF == 0 and (x >> 27) & 1 == 1
    assert r == 0x10 and f == 0, (hex(r), f)
    checks += 1

    return checks
