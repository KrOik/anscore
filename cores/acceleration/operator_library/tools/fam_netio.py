    prevalid = _bits(new, 144, 1)
    rounds = _bits(new, 128, 8)
    deficit = [_bits(new, 16 * lane, 16) for lane in range(4)]
    served = [_bits(new, 64 + 8 * lane, 8) for lane in range(4)]
    age = [_bits(new, 96 + 8 * lane, 8) for lane in range(4)]
    servm = starvem = idlem = backm = 0
    satnow = starm = tie = 0
    have = best = win = 0
    havemax = maxage = maxflow = 0
    count = 0
    for lane in range(4):
        weight = (b >> (4 * lane)) & 0xF
        length = (a >> (4 * lane)) & 0xF
        blk = (a >> (16 + lane)) & 1
        total = deficit[lane] + weight * 64
        if total > 0xFFFF:
            total = 0xFFFF
            satnow = 1
        pay = length * 64
        ok = 1 if (blk and (total & 0xFFFF) >= pay) else 0
        if ok:
            nxt = (total & 0xFFFF) - pay
            servm |= 1 << lane
            count += 1
            age[lane] = 0
            if served[lane] != 255:
                served[lane] += 1
        else:
            nxt = total & 0xFFFF
            if blk:
                if age[lane] == 255:
                    satnow = 1
                else:
                    age[lane] += 1
                if thresh and age[lane] >= thresh:
                    starvem |= 1 << lane
                    starm = 1
            else:
                idlem |= 1 << lane
                age[lane] = 0
        deficit[lane] = nxt
        if blk:
            backm |= 1 << lane
            if not have or nxt < best:
                have, best, win = 1, nxt, lane
            elif nxt == best:
                tie = 1
            if not havemax or age[lane] > maxage:
                havemax, maxage, maxflow = 1, age[lane], lane
    ww = 0 if not have else (b >> (4 * win)) & 0xF
    agedm = backm & ~servm
    repeat = 1 if (have and prevalid and win == prevwin) else 0
    if rounds == 255:
        satnow = 1
    else:
        rounds += 1
    stkstarve = _bits(new, 136, 1) | starm
    stksat = _bits(new, 137, 1) | satnow
    r = ((win if have else 0) | (have << 2) | (servm << 3) | (starvem << 7)
         | (idlem << 11) | (tie << 15) | (ww << 16)
         | ((maxflow if havemax else 0) << 20) | (stkstarve << 22)
         | (stksat << 23) | (seed << 24) | ((1 if agedm else 0) << 25)
         | (count << 26) | (repeat << 29) | (prevwin << 30))
    x = (rounds | ((best if have else 0xFFFF) << 8) | (satnow << 24)
         | (starm << 25) | (tie << 26) | ((1 if (prevmask & backm) else 0) << 27)
         | (agedm << 28))
    for lane in range(4):
        new = _put(new, 16 * lane, 16, deficit[lane])
        new = _put(new, 64 + 8 * lane, 8, served[lane])
        new = _put(new, 96 + 8 * lane, 8, age[lane])
    new = _put(new, 128, 8, rounds)
    for low, value in ((136, stkstarve), (137, stksat), (144, have)):
        new = _put(new, low, 1, value)
    new = _put(new, 138, 2, win if have else 0)
    new = _put(new, 140, 4, servm)
    return r, x, satnow | starm, new


