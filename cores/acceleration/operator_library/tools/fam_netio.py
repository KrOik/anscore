def _m_hll(a, b, c, state):
    if (c >> 2) & 0x1FFFFFFF:
        return 0, 0, 1, state
    en0, en1 = c & 1, (c >> 1) & 1
    seed = (c >> 31) & 1
    regs = [0] * 32 if seed else [(state >> (6 * i)) & 0x3F for i in range(32)]
    xor = 0 if seed else _bits(state, 208, 24)
    acc8 = _bits(state, 192, 8)
    deg8 = _bits(state, 200, 8)
    seed8 = _bits(state, 232, 8)
    if seed and seed8 != 255:
        seed8 += 1
    fault = proc = raised = 0

    def merge(hash_value, enabled):
        nonlocal fault, proc, raised, acc8, deg8, xor
        if not enabled:
            return 0, 0, 0, 0, hash_value & 0x1F
        bucket = hash_value & 0x1F
        field = (hash_value >> 5) & 0x7FFFFFF
        proc = 1
        if field == 0:
            fault = 1
            if deg8 != 255:
                deg8 += 1
            return 0, 0, 0, 1, bucket
        rank = 27 - (field.bit_length() - 1)
        if acc8 != 255:
            acc8 += 1
        xor ^= hash_value & 0xFFFFFF
        hit = regs[bucket]
        if rank > hit:
            regs[bucket] = rank
            return rank, 1, 1, 0, bucket
        return rank, 0, 1, 0, bucket

    rho0, ra0, _, deg0, b0 = merge(a, en0)
    rho1, ra1, _, deg1, b1 = merge(b, en1)
    raised = 1 if (ra0 or ra1) else 0
    zero = sum(1 for value in regs if value == 0)
    largest = max(regs)
    total = sum(regs)
    r = (b0 | (rho0 << 5) | (ra0 << 11) | (en0 << 12) | (deg0 << 13)
         | (b1 << 14) | (rho1 << 19) | (ra1 << 25) | (en1 << 26)
         | (deg1 << 27) | (seed << 28) | (raised << 29)
         | ((1 if not (en0 or en1) else 0) << 30)
         | ((1 if zero == 0 else 0) << 31))
    x = (zero | (largest << 6) | (total << 12) | (raised << 23) | (proc << 24)
         | (seed << 25) | (fault << 26) | ((1 if zero == 0 else 0) << 27)
         | ((1 if acc8 else 0) << 28) | ((1 if deg8 else 0) << 29)
         | ((1 if seed8 else 0) << 30) | ((1 if total > 255 else 0) << 31))
    new_state = total << 240 | seed8 << 232 | xor << 208 | deg8 << 200 | acc8 << 192
    for index, value in enumerate(regs):
        new_state |= value << (6 * index)
    return r, x, fault, new_state


