def _cm_columns(key):
    """The four count-min columns of a key, derived from the kernel hash pair."""
    h0 = ((key >> 8) ^ key) & 7
    h1 = (((key >> 12) ^ (key >> 6) ^ key) & 7) | 1
    return [(h0 + probe * h1) & 7 for probe in range(4)]


def _cm_collision_pair(key):
    """A different key that lands in exactly the same four columns as key.

    Search rather than assertion: the pair is what makes the overestimate of a
    count-min sketch observable in the board set, so it has to exist for the
    row that uses it, and the search proves it.
    """
    want = _cm_columns(key)
    for delta in range(1, 0x10000):
        other = (key + delta) & 0xFFFF
        if _cm_columns(other) == want and other != key:
            return key, other
    raise AssertionError(f'no count-min collision for {key:#06x}')


def _board_rows(name):
    """The 128 rows the hardware runs: structured, exhaustive and edge cases.

    Row 0 is never all-zero for a ROM core so the testbench re-evaluates the
    combinational block after $readmemh has filled the image.
    """
    rows = []
    if name == 'lpm_trie_step':
        # 42 keys, each walked restart / continue / continued-past-complete.
        for index in range(42):
            key = (index * 0x1F01 + 0x03C7) & 0xFFFF
            rows.append((key, (key >> 8) & 0xFF, 0x8000_0000))
            rows.append((key, key & 0xFF, 0))
            rows.append((key, 0, 0))
        rows.append((0x1234_5678, 0x00, 0x8000_0000))      # bad key field
        rows.append((0x0000_1234, 0x00FF_FFFF, 0))         # bad slice field
    elif name == 'ipv4_hdr_csum':
        # 28 clean headers (3 beats each), 12 headers verified against a
        # corrupted checksum word, then the carry-out misfold and the malformed
        # reserved field.
        for header in range(28):
            rows += _csum_beats(_csum_header_words(header), check=False)
        for header in range(28, 40):
            words = _csum_header_words(header)
            words[9] ^= 0x00FF
            rows += _csum_beats(words, check=True)
        for _group in range(2):
            rows.append((0xFFFF_FFFF, 0xFFFF_FFFF, 0x8000_0000))
            for _beat in range(2):
                rows.append((0xFFFF_FFFF, 0xFFFF_FFFF, 0))
        rows.append((0x0000_0001, 0x0000_0002, 0x0001_0000))
        rows.append((0x0000_0003, 0x0000_0004, 0x8001_0000))
    elif name == 'toeplitz_rss':
        rng = Random(0x7E3071)
        for index in range(64):
            rows.append((rng.getrandbits(32), 0xF, 0))
        for index in range(32):
            rows.append((rng.getrandbits(32), 0xF, 0x8000_0000))
        for index in range(16):
            rows.append((rng.getrandbits(32), 1 << (index % 4), 0))
        for index in range(16):
            rows.append((rng.getrandbits(32), 0x5, 0))
    elif name == 'qinq_walk':
        pool = [0x8100, 0x88A8, 0x9100, 0x0800, 0x0806, 0x7707]
        vids = [0x001, 0x000, 0xFFF, 0x2AF, 0x7FF, 0x00A]
        index = 0
        for outer in range(6):
            for inner in range(6):
                for third in range(6):
                    if len(rows) >= 124:
                        break
                    slot = (index, index + 1, index + 2)
                    tags = (pool[outer], pool[inner], pool[third])
                    words = []
                    for lane in range(3):
                        vid = vids[(slot[lane] + lane * 2) % 6]
                        tci = vid | (((index + lane) & 7) << 13) | ((lane & 1) << 12)
                        words.append(tags[lane] | (tci << 16))
                    rows.append((words[0], words[1], words[2]))
                    index += 1
        # hand-picked stacks, each slot word = TCI<<16 | TPID
        rows.append((0x0FFF_88A8, 0x0FFF_8100, 0x0FFF_9100))   # depth + reserved VID
        rows.append((0x0001_8100, 0x0002_88A8, 0x0003_9100))   # depth budget
        rows.append((0x0FFF_8100, 0x0000_0800, 0x0000_0000))   # reserved VID only
        rows.append((0x0000_0800, 0x0001_8100, 0x0000_0000))   # untagged, early stop
    elif name == 'bloom4_update':
        rng = Random(0xB1005)
        for group in range(31):
            salt = (0x40 + group * 7) & 0xFF
            for beat in range(4):
                keys = [rng.getrandbits(16) for _ in range(4)]
                control = salt | (0x8000_0000 if beat == 0 else 0)
                if beat == 3:
                    control |= 0x0000_0100                       # pure query beat
                rows.append((keys[0] | (keys[1] << 16), keys[2] | (keys[3] << 16),
                             control))
        rows.append((0x0000_0001, 0x0000_0002, 0x0000_0200))     # reserved field bad
        rows.append((0x0000_0003, 0x0000_0004, 0x0008_0100))     # reserved field bad
        rows.append((0x0000_0005, 0x0000_0006, 0x4000_0000))     # reserved field bad
        rows.append((0x0000_0007, 0x0000_0008, 0x8000_0100))     # seed + query of empty set
    elif name == 'countmin_update':
        rng = Random(0xC04C17)

        def nibbles(*values):
            word = 0
            for lane, value in enumerate(values):
                word |= (value & 0xF) << (4 * lane)
            return word

        for session in range(18):                      # 4-beat flows, beat 3 queries
            for beat in range(4):
                control = nibbles(*[rng.randrange(0, 16) for _ in range(4)])
                if beat == 3:
                    control |= 0x0100_0000
                if beat == 0:
                    control |= 0x8000_0000
                rows.append((rng.getrandbits(32), rng.getrandbits(32), control))
        for session in range(4):                       # hammer: one key, all lanes, full tilt
            key = rng.getrandbits(16)
            for beat in range(4):
                control = nibbles(15, 15, 15, 15)
                if beat == 0:
                    control |= 0x8000_0000
                rows.append((key | (key << 16), key | (key << 16), control))
        for lane in range(8):                          # one lane increments, rotating
            rows.append((rng.getrandbits(32), rng.getrandbits(32),
                         nibbles(*[9 if index == lane % 4 else 0 for index in range(4)])))
        collision = _cm_collision_pair(0x2B17)
        for session in range(2):                       # two keys, one set of columns
            for beat in range(4):
                control = nibbles(9, 5, 1, 15)
                if beat == 0:
                    control |= 0x8000_0000
                pair = collision if beat & 1 else (0x2B17, 0x2B17)
                rows.append((pair[0] | (pair[1] << 16),
                             pair[0] | (pair[1] << 16), control))
        for probe in range(4):                         # seed a fresh sketch, four increments
            rows.append((rng.getrandbits(32), rng.getrandbits(32),
                         0x8000_0000 | nibbles(*[rng.randrange(1, 16) for _ in range(4)])))
        for beat in range(8):                          # zero increments: nothing may change
            control = 0x8000_0000 if beat == 0 else 0
            rows.append((rng.getrandbits(32), rng.getrandbits(32), control))
        while len(rows) < 120:
            rows.append((rng.getrandbits(32), rng.getrandbits(32),
                         nibbles(*[rng.randrange(0, 16) for _ in range(4)])
                         | (0x0100_0000 if rng.getrandbits(1) else 0)))
        for bad in (0x0200_0000, 0x0400_0000, 0x0800_0000, 0x1000_0000,
                    0x2000_0000, 0x4000_0000, 0x0001_0000, 0x0002_0000):
            rows.append((rng.getrandbits(32), rng.getrandbits(32), bad | 0x0100_0000))
    elif name == 'hll_reg_update':
        rng = Random(0x41E710)
        for session in range(24):
            for beat in range(4):
                control = 0x8000_0003 if beat == 0 else 3
                rows.append((rng.getrandbits(32), rng.getrandbits(32), control))
        for bucket in range(8):                        # lane 0 degenerate, lane 1 max rank
            rows.append((bucket, 1 << (5 + bucket), 3 | (0x8000_0000 if bucket == 0 else 0)))
        for bucket in range(8):                        # lane 0 degenerate only, seeded
            rows.append((0x8000_0000 | bucket, bucket << 5, 1))
        for lane_en in (1, 2):                         # one lane, extreme ranks
            for shift in (5, 10, 20, 25):
                rows.append(((1 << shift) | 7, (1 << (shift - 1)) | 9, lane_en))
        rows.append((0, 0, 0))                         # both lanes disabled
        rows.append((MASK, MASK, 0x8000_0000))         # seeded, both lanes disabled
        for bad in (4, 8, 0x0000_0100, 0x2000_0000, 0x4000_0000, 0x0000_000C):
            rows.append((0, 0, bad))                   # reserved control bits
    elif name == 'bitmap_scan':
        words = [0x0000_0001, 0x8000_0001, 0xFFFF_FFFF, 0x0000_0000, 0x00FF_00FF,
                 0x1234_5678, 0xDEAD_BEEF, 0x0000_FF00, 0xAAAA_AAAA, 0x5555_5555,
                 0x4000_0000, 0x0000_0002, 0x0F0F_0F0F, 0x00C0_1000, 0x8000_0000,
                 0x0000_8000, 0x1020_3040, 0x7777_8888, 0x0000_00F0, 0x0001_0000,
                 0xFFFF_FFFE, 0x0000_0000, 0xBEEF_0000, 0x0000_DEAD]
        for index, word in enumerate(words):           # rotate every word through the ring
            for beat in range(4):
                control = 0x8000_0000 if index == 0 and beat == 0 else 0
                rows.append((word, beat & 1, control))
        for pointer in (0, 1, 3, 7, 11, 16, 23, 29, 31, 5, 13, 21, 27, 30, 2, 9):
            rows.append((0x8000_0001, 0, 0x0000_0020 | pointer))
        rows.append((0, 0, 0))                         # empty bitmap, find-first-set
        rows.append((MASK, 1, 0))                      # full bitmap, find-first-clear
        rows.append((0, 1, 0x8000_0000))               # reseed, then an empty complement scan
        rows.append((0x0000_0000, 0, 0x0000_002F))     # explicit pointer 15 on an empty word
        for word in (0x8000_0000, 0x4000_0000, 0xC000_0000, 0x0000_0001,
                     0x0000_0003, 0x8888_8888):        # wrap the pointer past bit 31
            rows.append((word, 0, 0x0000_003F))
        for bad in (0x0000_0040, 0x0000_0200, 0x0100_0000, 0x0200_0000,
                    0x2000_0000, 0x4000_0000):
            rows.append((0x0000_00F0, 2, bad))         # reserved field violations
    elif name == 'radix_tree_step':
        rng = Random(0xAD1C10)
        for group in range(64):                        # every root slot, full two-level walk
            a = 0
            for lane in range(4):
                a |= (((group * 4 + lane * 41 + group // 4) & 0xFF) << (8 * lane))
            rows.append((a, 0, 0x8000_0000 if group == 0 else 0))
        for group in range(48):                        # declared orders varied per beat
            a = 0
            for lane in range(4):
                a |= (rng.getrandbits(8) << (8 * lane))
            rows.append((a, 0, rng.randrange(1, 16)))
        for expect, index in ((0x0F, 0xA0), (0x0F, 0x0A), (0x05, 0x81), (0x0A, 0xB3),
                              (0x00, 0x80), (0x00, 0xAF), (0x0F, 0xFF), (0x00, 0x00),
                              (0x03, 0x94), (0x0C, 0x4D), (0x07, 0xE6), (0x08, 0x1F)):
            rows.append((index | (index << 8) | (index << 16) | (index << 24), 0, expect))
        while len(rows) < 124:
            a = 0
            for lane in range(4):
                a |= (rng.getrandbits(8) << (8 * lane))
            rows.append((a, 0, rng.randrange(0, 16)))
        for bad in ((0x0000_0102, 0x0000_00FF, 0), (0x0102_0304, 0, 0x0000_0010),
                    (0x0102_0304, 0, 0x0000_0020), (0x0102_0304, 0, 0x4000_0000)):
            rows.append(bad)
    elif name == 'pacing_wf2q':
        rng = Random(0x9ACE01)

        def flow_words(weights, sizes, backlogged):
            a = 0
            b = 0
            for lane in range(4):
                a |= (sizes[lane] & 0xF) << (4 * lane)
                b |= (weights[lane] & 0xF) << (4 * lane)
            return a | (backlogged << 16), b

        for session in range(8):
            for beat in range(4):
                control = 0x8000_0004 if beat == 0 else 0x0000_0004
                a, b = flow_words([rng.randrange(1, 16) for _ in range(4)],
                                  [rng.randrange(0, 16) for _ in range(4)],
                                  rng.randrange(0, 16))
                rows.append((a, b, control))
        crafted = [
            ([4, 4, 4, 4], [0, 0, 0, 0], 0x0000_0004),      # all idle
            ([8, 8, 8, 8], [2, 2, 2, 2], 0x0000_000F),      # four equal deficits, a tie
            ([1, 15, 15, 15], [15, 0, 0, 0], 0x0000_000F),  # flow 0 cannot pay
            ([15, 1, 1, 1], [1, 15, 15, 15], 0x0000_0007),  # winner by weight
        ]
        for weights, sizes, backlogged in crafted:
            for _beat in range(4):
                a, b = flow_words(weights, sizes, backlogged)
                rows.append((a, b, 0x0000_0002))             # age threshold 2
        for _beat in range(74):                              # one long unseded run
            a, b = flow_words([15, 15, 15, 15], [0, 0, 0, 0], 0)
            rows.append((a, b, 0))                           # idle accrual, no threshold
        for bad in (0x0100_0000, 0x0200_0000, 0x0800_0000, 0x2000_0000,
                    0x4000_0000, 0x0000_0400):
            rows.append((0, 0, bad))                         # reserved control bits
    else:
        raise ValueError(name)
    assert len(rows) == BOARD_ROWS, f'{name}: {len(rows)} board rows'
    for row in rows:
        for value in row:
            assert 0 <= value <= MASK, f'{name}: row field out of range'
    return rows


def _csum_beats(words, check):
    """Three-beat streaming of a ten-word header: restart, continue, final."""
    out = []
    for index in range(0, 10, 4):
        chunk = list(words[index:index + 4])
        while len(chunk) < 4:
            chunk.append(0)
        control = 0x8000_0000 if index == 0 else 0
        if index == 8:
            control |= 0x4000_0000 | (0x2000_0000 if check else 0)
        out.append((chunk[0] | (chunk[1] << 16), chunk[2] | (chunk[3] << 16), control))
    return out


def _csum_header_words(header):
    """Ten 16-bit IPv4 header words for a seeded example, checksum word last."""
    rng = Random(0xC5AB9E + header)
    src = rng.getrandbits(32)
    dst = rng.getrandbits(32)
    words = [0x4500, rng.randrange(0x14, 0x600), rng.getrandbits(16),
             rng.randrange(0x4000), 0x4006,
             src & 0xFFFF, src >> 16, dst & 0xFFFF, dst >> 16, 0]
    words[9] = _ref_csum(words[:9]) ^ 0xFFFF
    return words


def _ref_csum(words):
    """RFC 1071 reference: 32-bit accumulation, then fold carries in a loop."""
    total = sum(words)
    while total >> 16:
        total = (total & 0xFFFF) + (total >> 16)
    return total & 0xFFFF


def vectors(name, count=320):
    """Structured board set first (rows 0..127), seeded random only afterwards."""
    rows = _board_rows(name)
    rng = Random(0x4E710 + sum(name.encode()))
    while len(rows) < count:
        if name == 'lpm_trie_step':
            key = rng.getrandbits(16)
            rows.append((key, rng.getrandbits(8), 0x8000_0000 if rng.getrandbits(1) else 0))
        elif name == 'ipv4_hdr_csum':
            control = (rng.getrandbits(3) << 29) | rng.randrange(4)
            rows.append((rng.getrandbits(32), rng.getrandbits(32), control))
        elif name == 'toeplitz_rss':
            control = rng.getrandbits(32) if rng.getrandbits(2) else rng.getrandbits(4)
            rows.append((rng.getrandbits(32), control, rng.getrandbits(1) << 31))
        elif name == 'qinq_walk':
            pool = [0x8100, 0x88A8, 0x9100, 0x0800, 0x0806, 0x7707, 0x88F7, 0x0F0F]
            rows.append(((rng.choice(pool) | (rng.getrandbits(16) << 16)) & MASK,
                         (rng.choice(pool) | (rng.getrandbits(16) << 16)) & MASK,
                         (rng.choice(pool) | (rng.getrandbits(16) << 16)) & MASK))
        elif name == 'bloom4_update':
            control = rng.getrandbits(8) | (0x0100 if rng.getrandbits(2) == 0 else 0)
            if rng.getrandbits(1):
                control |= 0x8000_0000
            rows.append((rng.getrandbits(32), rng.getrandbits(32), control))
        elif name == 'countmin_update':
            control = rng.getrandbits(16)
            if rng.getrandbits(2) == 0:
                control |= 0x0100_0000
            if rng.getrandbits(3) == 0:
                control |= 0x8000_0000
            if rng.getrandbits(9) == 0:
                control |= 1 << rng.randrange(16, 31)     # occasional malformed beat
            rows.append((rng.getrandbits(32), rng.getrandbits(32), control))
        elif name == 'hll_reg_update':
            control = rng.getrandbits(2)
            if rng.getrandbits(4) == 0:
                control |= 0x8000_0000
            if rng.getrandbits(7) == 0:
                control |= 1 << rng.randrange(2, 31)      # occasional malformed beat
            a = rng.getrandbits(32)
            b = rng.getrandbits(32)
            if rng.getrandbits(6) == 0:                   # an enabled degenerate hash
                a = rng.getrandbits(5)
            if rng.getrandbits(6) == 0:
                b = rng.getrandbits(5)
            rows.append((a, b, control))
        elif name == 'bitmap_scan':
            control = rng.getrandbits(6)
            if rng.getrandbits(3) == 0:
                control |= 0x8000_0000
            if rng.getrandbits(9) == 0:
                control |= 1 << rng.randrange(7, 31)      # occasional malformed beat
            rows.append((rng.choice([0, MASK, rng.getrandbits(32),
                                     1 << rng.randrange(32), rng.getrandbits(32)]),
                         rng.getrandbits(1), control))
        elif name == 'radix_tree_step':
            control = rng.randrange(16)
            if rng.getrandbits(4) == 0:
                control |= 0x8000_0000
            if rng.getrandbits(9) == 0:
                control |= 1 << rng.randrange(4, 31)      # occasional malformed beat
            a = 0
            for lane in range(4):
                a |= (rng.choice([rng.getrandbits(8), rng.getrandbits(4) << 4,
                                  0xA0 + lane, 0x80 + lane]) << (8 * lane))
            rows.append((a, 0, control))
        elif name == 'pacing_wf2q':
            control = rng.getrandbits(8) << 16
            if rng.getrandbits(3) == 0:
                control |= 0x8000_0000
            if rng.getrandbits(9) == 0:
                control |= 1 << rng.randrange(24, 31)     # occasional malformed beat
            a = rng.getrandbits(16) | (rng.randrange(16) << 16)
            b = 0
            for lane in range(4):
                b |= (rng.randrange(1, 16) << (4 * lane))
            rows.append((a, b, control))
        else:
            rows.append((rng.getrandbits(32), rng.getrandbits(32), rng.getrandbits(32)))
    return rows[:count]


