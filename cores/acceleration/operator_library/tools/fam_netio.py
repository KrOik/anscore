def _m_cm(a, b, c, state):
    if ((c >> 25) & 0x3F) or ((c >> 16) & 0xFF):
        return 0, 0, 1, state
    query = (c >> 24) & 1
    cells = [0] * 32 if (c >> 31) & 1 else [(state >> (8 * i)) & 0xFF
                                            for i in range(32)]
    keys = [a & 0xFFFF, (a >> 16) & 0xFFFF, b & 0xFFFF, (b >> 16) & 0xFFFF]
    ops = isum = clamp = 0
    if not query:
        for lane in range(4):
            key = keys[lane]
            inc = (c >> (4 * lane)) & 0xF
            h0 = ((key >> 8) ^ key) & 7
            h1 = (((key >> 12) ^ (key >> 6) ^ key) & 7) | 1
            acc = h0
            for row in range(4):
                cell = 8 * row + (acc & 7)
                old = cells[cell]
                total = old + inc
                if total > 255:
                    total = 255
                    clamp = 1
                if total != old:
                    ops += 1
                cells[cell] = total
                isum = (isum + inc) & 0xFF
                acc += h1
    r = zero = 0
    for lane in range(4):
        key = keys[lane]
        h0 = ((key >> 8) ^ key) & 7
        h1 = (((key >> 12) ^ (key >> 6) ^ key) & 7) | 1
        acc = h0
        vals = []
        for row in range(4):
            vals.append(cells[8 * row + (acc & 7)])
            acc += h1
        best = min(vals)
        r |= best << (8 * lane)
        if best == 0:
            zero += 1
    largest = max(cells)
    new_state = 0
    for index, value in enumerate(cells):
        new_state |= value << (8 * index)
    x = (ops | (largest << 8) | (query << 16) | (clamp << 17)
         | (((c >> 31) & 1) << 18) | (isum << 19) | ((1 if largest == 255 else 0) << 27)
         | (zero << 28) | ((1 if ops == 0 else 0) << 31))
    return r, x, clamp, new_state


