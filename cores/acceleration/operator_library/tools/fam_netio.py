def _m_scan(a, b, c, state):
    if ((c >> 7) & 0xFFFFFF) or (b >> 1):
        return 0, 0, 1, state
    mode = b & 1
    sw = ((~a) & MASK) if mode else (a & MASK)
    explicit = (c >> 5) & 1
    seed = (c >> 31) & 1
    if explicit:
        ptr = c & 0x1F
    else:
        ptr = 0 if seed else _bits(state, 0, 5)
    rot = ((sw << ptr) | (sw >> (32 - ptr))) & MASK
    found = 1 if rot else 0
    pos = (rot & -rot).bit_length() - 1 if rot else 0
    total = pos + ptr
    absol = total & 0x1F
    wrap = (total >> 5) & 1
    abs6 = absol + 1
    nxt = abs6 & 0x1F
    hits = _bits(state, 6, 6)
    empt = _bits(state, 12, 6)
    words = _bits(state, 220, 8)
    trans = _bits(state, 228, 8)
    sat = 0
    diff = 0 if words == 0 else ((sw ^ _bits(state, 148, 32)) & MASK)
    if found:
        if hits == 63:
            sat = 1
        else:
            hits += 1
    else:
        if empt == 63:
            sat = 1
        else:
            empt += 1
    if words == 255:
        sat = 1
    else:
        words += 1
    base_or = 0 if seed else _bits(state, 18, 32)
    base_orn = 0 if seed else _bits(state, 50, 32)
    base_and = MASK if seed else _bits(state, 82, 32)
    base_andn = MASK if seed else _bits(state, 114, 32)
    evor = (base_or | sw) & MASK
    evorn = (base_orn | (~sw & MASK)) & MASK
    evand = (base_and & sw) & MASK
    evandn = (base_andn & (~sw & MASK)) & MASK
    xor = (_bits(state, 188, 32) ^ sw) & MASK
    prev = _bits(state, 180, 6)
    pc = bin(sw).count('1')
    pco = bin(evor).count('1')
    pca = bin(evand).count('1')
    dsum = bin(diff).count('1')
    tsum = trans + dsum
    if tsum > 255:
        trans = 255
        sat = 1
    else:
        trans = tsum
    stkmiss = _bits(state, 186, 1) | (1 - found)
    stksat = _bits(state, 187, 1) | sat
