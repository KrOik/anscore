def _ref_lpm(key16, fib, limit=16):
    """Independent longest-prefix helper: right-shift compare, no masks.

    Returns (plen, index, nexthop) of the longest slot that matches key16 and
    whose length is <= limit, or None. Written against the definition of a
    longest prefix match rather than the kernel's XOR-and-mask form.
    """
    best = None
    for index, word in enumerate(fib):
        if not (word >> 29) & 1:
            continue
        plen = (word >> 24) & 0x1F
        prefix = (word >> 8) & 0xFFFF
        if plen > limit:
            continue
        if key16 >> (16 - plen) == prefix >> (16 - plen):
            if best is None or plen > best[0]:
                best = (plen, index, word & 0xFF)
    return best


def _ref_bloom_indices(key, salt):
    """Second implementation of the four Bloom positions, deliberately slow."""
    t = 0
    for bit in range(16):
        if (key >> bit) & 1:
            t ^= 1 << (bit % 8)
    h0 = (t ^ salt) & 0xFF
    nib = 0
    for shift in (0, 4, 8, 12):
        nib ^= (key >> shift) & 0x0F
    h1 = ((nib ^ (salt >> 4)) & 0x0F) | 1
    return [((h0 + step * h1) % 256) for step in range(4)]


def _ref_toeplitz(ain, key):
    """Bit-level Toeplitz through an explicit 32x32 matrix, not a shift chain."""
    matrix = [[(key >> (bit + out)) & 1 for bit in range(32)] for out in range(32)]
    out = 0
    for row in range(32):
        parity = 0
        for column in range(32):
            if (ain >> column) & 1:
                parity ^= matrix[row][column]
        out |= parity << row
    return out


def _ref_drop_fold(ain, key):
    """Reference for aux[31:16]: the product against the key windows the 32-bit
    output cannot reach (bit i+32+j), folded to 16 bits.

    Reuses the matrix reference with key >> 32, which is the same index shift
    the kernel performs with (n_key >> (i + 32)): both treat key bits above 63
    as zero, because both operands are 64-bit registers / a 64-bit integer.
    """
    drop = _ref_toeplitz(ain, key >> 32)
    return ((drop >> 16) ^ drop) & 0xFFFF


def _ref_drop_fold(ain, key):
    """Reference for aux[31:16]: the same Toeplitz product against the key
    windows the 32-bit output cannot reach (bit i+32+j, which is bit i+j of
    key>>32), then the 16-bit fold of the 32-bit product."""
    drop = _ref_toeplitz(ain, key >> 32)
    return ((drop >> 16) ^ drop) & 0xFFFF


def _ref_qinq(slots):
    """Loop-and-dict reference for the stacked tag walk."""
    classes = {0x8100: 1, 0x88A8: 2, 0x9100: 3}
    depth = 0
    etype = 0
    for tpid, _tci in slots:
        if classes.get(tpid, 0) == 0:
            etype = tpid
            break
        depth += 1
    return depth, etype


