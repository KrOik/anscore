# Table images. Line 0 of every .mem file is index 0 of the array, and the
# model below reads the same tables() function that emitted the file.
# --------------------------------------------------------------------------
FIB_LENGTHS = (2, 4, 6, 8, 8, 10, 12, 12, 14, 16, 16, 16)


def _fib_image():
    """16 forwarding-information-base slots, word = (valid<<29)|(plen<<24)
    |(prefix<<8)|nexthop, prefix left-aligned in 16 bits.

    Twelve routes plus four holes (valid=0) exercise the priority pick, the
    hole path and the not-yet-decidable rule. Prefix lengths are the derived
    FIB_LENGTHS tuple above; entry 4 is deliberately a duplicate of entry 3
    (same length, same prefix, different nexthop) so the documented tie rule
    "lowest table index wins" is exercised instead of assumed. All other
    same-length prefixes are kept distinct by the collision test below.
    """
    rng = Random(0x4C8E9E31)
    used, prefixes, values = {}, [], []
    for index, plen in enumerate(FIB_LENGTHS):
        if index == 4:
            value = prefixes[3]                    # the deliberate duplicate
        else:
            while True:
                value = (rng.getrandbits(16) >> (16 - plen)) << (16 - plen)
                if (plen, value) not in used:
                    break
            used[(plen, value)] = index
        prefixes.append(value)
        values.append((1 << 29) | (plen << 24) | (value << 8) | ((0x11 + 9 * index) & 0xFF))
    return values + [0, 0, 0, 0]


def _radix_image():
    """64 words = 4 nodes x 16 slots of a two-level, order-4 radix tree.

    word = (present<<15) | (leaf<<14) | (child<<12) | payload[11:0].
    Root (node 0) slots 0..3 point at node 1, 4..7 at node 2, 8..9 at node 3,
    slot 10 is a collapsed leaf that resolves in one indirection and 11..15 are
    holes, so an index whose high nibble lands above 10 is a genuine ENOENT.
    Nodes 1..2 hold leaves; a slot is present when (node*5 + slot) % 4 != 3 and
    its payload is node*256 + slot*16 + 7. Node 3 slots 0..2 are deliberately
    *internal* pointers back to node 1, so a walk that declares two levels and
    lands there has to chase a third indirection the tree cannot offer: that is
    the too-deep structure fault. Together the four shapes cover every cause
    code the core documents (two-step hit, ENOENT, collapsed hit, already
    resolved at the root, deeper than declared).
    """
    image = []
    for node in range(4):
        for slot in range(16):
            if node == 0:
                if slot == 10:
                    image.append((1 << 15) | (1 << 14) | 0x3E0)
                elif slot < 10:
                    image.append((1 << 15) | (0 << 14) | ((1 + (slot // 4)) << 12))
                else:
                    image.append(0)
            elif node == 3 and slot < 3:
                image.append((1 << 15) | (1 << 12))
            else:
                if (node * 5 + slot) % 4 != 3:
                    payload = (node * 256 + slot * 16 + 7) & 0xFFF
                    image.append((1 << 15) | (1 << 14) | payload)
                else:
                    image.append(0)
    return image


def _rss_key_image():
    """Two words holding the 64-bit RSS Toeplitz key, word0 = key[31:0].

    The key bitstring is made palindromic about index 31, key[t] = key[62-t]
    for t = 0..31, and bit 63 is left zero. That is not decoration: the
    Toeplitz entry the kernel uses for input bit j and output bit i is
    key[i+j], and the two entries that bit reversal swaps, key[i+31-j] and
    key[31-i+j], have indices that always sum to 62. A key palindromic about
    bit 31 therefore makes the matrix commute with bit reversal, which is the
    exact condition toeplitz_rss needs for mirror mode to return the
    bit-reversed hash of the very same key - a property of the image, so the
    RTL and the model inherit it from one definition.
    """
    rng = Random(0x55317012)
    low = [rng.getrandbits(1) for _ in range(32)]
    bits = list(low)
    for index in range(32, 63):
        bits.append(low[62 - index])
    bits.append(0)
    word0 = sum(bit << index for index, bit in enumerate(bits[:32]))
    word1 = sum(bit << index for index, bit in enumerate(bits[32:64]))
    return [word0, word1]


_IMAGES = {}


def tables(name):
    if name not in _IMAGES:
        if name == 'lpm_trie_step':
            _IMAGES[name] = {'fib': _fib_image()}
        elif name == 'radix_tree_step':
            _IMAGES[name] = {'nodes': _radix_image()}
        elif name == 'toeplitz_rss':
            _IMAGES[name] = {'key': _rss_key_image()}
        else:
            _IMAGES[name] = {}
    return _IMAGES[name]


def _bits(value, low, width):
    return (value >> low) & ((1 << width) - 1)


def _put(state, low, width, value):
    field = (1 << width) - 1
    return (state & ~(field << low)) | ((value & field) << low)


