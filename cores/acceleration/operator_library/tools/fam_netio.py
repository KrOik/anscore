def _m_lpm(a, b, c, state):
    fib = tables('lpm_trie_step')['fib']
    restart = (c >> 31) & 1
    look = _bits(state, 36, 8)
    hits = _bits(state, 44, 8)
    if (b >> 8) or (restart and (a >> 16)):
        return 0, 0, 1, state
    if not restart and _bits(state, 52, 1):
        bestv = _bits(state, 35, 1)
        r = (_bits(state, 27, 8) | (_bits(state, 22, 5) << 8) | (bestv << 13)
             | (1 << 14) | ((1 - bestv) << 15) | (look << 16) | (hits << 24))
        x = _bits(state, 53, 17) | (1 << 17) | (bestv << 18) | (1 << 29)
        return r, x, 1, state
    depth = 0 if restart else _bits(state, 0, 5)
    key = 0 if restart else _bits(state, 6, 16)
    dnew = depth + 8
    keyn = key | (((b & 0xFF) << (16 - dnew)) & 0xFFFF)
    cand = bestv = bestpl = bestnh = 0
    for word in fib:
        if not (word >> 29) & 1:
            continue
        plen = (word >> 24) & 0x1F
        if plen > dnew:
            continue
        mask = (0xFFFF << (16 - plen)) & 0xFFFF
        if ((keyn ^ ((word >> 8) & 0xFFFF)) & mask) == 0:
            cand += 1
            if not bestv or plen > bestpl:
                bestv, bestpl, bestnh = 1, plen, word & 0xFF
    node = ((1 << dnew) - 1) + (keyn >> (16 - dnew))
    complete = 1 if dnew == 16 else 0
    if complete:
        look = min(look + 1, 255)
        if bestv:
            hits = min(hits + 1, 255)
    r = (bestnh | (bestpl << 8) | (bestv << 13) | (complete << 14)
         | ((complete and not bestv) << 15) | (look << 16) | (hits << 24))
    x = node | (complete << 17) | (bestv << 18) | (cand << 24)
    new = state
    for low, width, value in ((0, 5, dnew), (6, 16, keyn), (22, 5, bestpl),
                              (27, 8, bestnh), (35, 1, bestv), (36, 8, look),
                              (44, 8, hits), (52, 1, complete), (53, 17, node)):
        new = _put(new, low, width, value)
    return r, x, 0, new


