def _m_csum(a, b, c, state):
    if (c >> 16) & 0x1FFF:
        return 0, 0, 1, state
    restart = (c >> 31) & 1
    final = (c >> 30) & 1
    check = (c >> 29) & 1
    acc = 0 if restart else (state & 0x3FFFF)
    beats = 0 if restart else _bits(state, 18, 8)
    stick = 0 if restart else _bits(state, 26, 1)
    total = (acc + (a & 0xFFFF) + ((a >> 16) & 0xFFFF)
             + (b & 0xFFFF) + ((b >> 16) & 0xFFFF))
    mis = 1 if total > 0x3FFFF else 0
    if mis:
        total = (total & 0xFFFF) + (total >> 16)
        total = (total & 0xFFFF) + (total >> 16)
    store = total & 0x3FFFF
    fin = ok = 0
    if final:
        s1 = (store & 0xFFFF) + (store >> 16)
        s2 = (s1 & 0xFFFF) + (s1 >> 16)
        fin = s2 & 0xFFFF
        ok = 1 if fin == 0xFFFF else 0
        store = fin
    if not final:
        r = store
    elif check:
        r = fin
    else:
        r = fin ^ 0xFFFF
    fault = 1 if (final and check and not ok) else 0
    if mis:
        fault = 1
    beats = min(beats + 1, 255)
    stick = 1 if (stick or mis) else 0
    x = (store | (mis << 18) | (final << 19) | (check << 20)
         | (ok << 21) | (stick << 22) | (beats << 24))
    new = store | (beats << 18) | (stick << 26)
    return r, x, fault, new


