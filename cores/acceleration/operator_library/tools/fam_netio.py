        # beat, but a lane only claims a new bit if no earlier lane of the same
        # beat already set it: two keys of one beat can collide on a position.
        progressive = before_filter
        for lane, value in enumerate(keys):
            positions = _ref_bloom_indices(value, salt)
            was = all((before_filter >> pos) & 1 for pos in positions)
            fresh = any(not (progressive >> pos) & 1 for pos in positions)
            assert ((r >> lane) & 1) == (1 if was else 0), (lane, value, hex(r))
            assert ((r >> (4 + lane)) & 1) == (1 if fresh else 0), (lane, value, hex(r))
            for pos in positions:
                progressive |= 1 << pos
