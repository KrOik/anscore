def _m_radix(a, b, c, state):
    if ((c >> 4) & 0x7FFFFFF) or b:
        return 0, 0, 1, state
    radmap = tables('radix_tree_step')['nodes']
    seed = (c >> 31) & 1
    new = 0 if seed else state
    get = lambda low, width: _bits(new, low, width)
    look, hit8, col8 = get(0, 8), get(8, 8), get(16, 8)
    abs8, fl8, ind8, beat = get(24, 8), get(32, 8), get(40, 8), get(48, 8)
    digest = get(56, 32)
    histprev, hist = get(90, 24), get(90, 24)
    hitm = absm = flm = colm = deepm = chasem = rep = 0
    xorb = first = fidx = 0
    ind = 0
    fault = 0
    anyfirst = False
    for lane in range(4):
        index = (a >> (8 * lane)) & 0xFF
        expect = (c >> lane) & 1
        pay = 0
        second = False
        addr = (index >> 4) & 0xF
        word = radmap[addr]
        ind += 1
        if ind8 != 255:
            ind8 += 1
        if not (word >> 15) & 1:
            cause = 2
        elif (word >> 14) & 1:
            pay = word & 0xFFF
            cause = 5 if expect else 3
        elif expect:
            cause = 4
        else:
            child = (word >> 12) & 3
            addr = (child << 4) | (index & 0xF)
            word = radmap[addr]
            second = True
            ind += 1
            if ind8 != 255:
                ind8 += 1
            if not (word >> 15) & 1:
                cause = 2
            elif (word >> 14) & 1:
                pay = word & 0xFFF
                cause = 1
            else:
                cause = 4
        if look != 255:
            look += 1
        if cause in (1, 5):
            hitm |= 1 << lane
            if cause == 5:
                colm |= 1 << lane
                if col8 != 255:
                    col8 += 1
            elif hit8 != 255:
                hit8 += 1
            if not anyfirst:
                anyfirst = True
                first = pay
                fidx = lane
        if cause == 2:
            absm |= 1 << lane
            if abs8 != 255:
                abs8 += 1
        if cause in (3, 4):
            flm |= 1 << lane
            if fl8 != 255:
                fl8 += 1
            fault = 1
        if cause == 4:
            deepm |= 1 << lane
        if second:
            chasem |= 1 << lane
        if not seed and cause in (1, 5):
            if addr == _bits(histprev, 6 * lane, 6):
                rep |= 1 << lane
        hist = ((hist << 6) | addr) & 0xFFFFFF
        xorb ^= pay
        digest = (digest ^ pay) & MASK
    if beat != 255:
        beat += 1
    stkfl = _bits(new, 88, 1) | (1 if flm else 0)
    stkab = _bits(new, 89, 1) | (1 if absm else 0)
    r = (hitm | (absm << 4) | (flm << 8) | (colm << 12) | (deepm << 16)
         | (ind << 20) | (seed << 24) | ((1 if chasem else 0) << 25)
         | ((1 if flm == 0 else 0) << 26) | ((1 if hitm == 0xF else 0) << 27)
         | ((1 if absm == 0xF else 0) << 28) | ((1 if hitm else 0) << 29)
         | ((1 if absm else 0) << 30) | (fault << 31))
    x = (xorb | (first << 12) | (fidx << 24) | (rep << 26)
         | (stkfl << 30) | (stkab << 31))
    new = _put(new, 0, 8, look)
    for low, width, value in ((8, 8, hit8), (16, 8, col8), (24, 8, abs8),
                              (32, 8, fl8), (40, 8, ind8), (48, 8, beat),
                              (56, 32, digest), (88, 1, stkfl), (89, 1, stkab),
                              (90, 24, hist)):
        new = _put(new, low, width, value)
    return r, x, fault, new


