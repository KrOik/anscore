def _m_bloom(a, b, c, state):
    if (c >> 9) & 0x3FFFFF:
        return 0, 0, 1, state
    query = (c >> 8) & 1
    salt = c & 0xFF
    filt = 0 if (c >> 31) & 1 else state
    read = filt
    before = bin(filt).count('1')
    keys = [a & 0xFFFF, (a >> 16) & 0xFFFF, b & 0xFFFF, (b >> 16) & 0xFFFF]
    hitm = newm = digest = 0
    for lane, key in enumerate(keys):
        h0 = ((((key >> 8) ^ key) & 0xFF) ^ salt) & 0xFF
        u = ((key >> 12) ^ (key >> 8) ^ (key >> 4) ^ key) & 0x0F
        h1 = (((u ^ (salt >> 4)) & 0x0F) | 1)
        acc = h0
        lanehit, lanenew = 1, 0
        for _ in range(4):
            pos = acc & 0xFF
            if not (read >> pos) & 1:
                lanehit = 0
            if not (filt >> pos) & 1 and not query:
                filt |= 1 << pos
                lanenew = 1
                digest ^= pos
            acc += h1
        hitm |= lanehit << lane
        newm |= lanenew << lane
    after = bin(filt).count('1')
    setcount = after - before
    saturated = 1 if after > 224 else 0
    r = hitm | (newm << 4) | (digest << 8)
    x = (after | (setcount << 9) | (query << 16) | (saturated << 17)
         | (before << 18) | (((c >> 31) & 1) << 27))
    return r, x, saturated, filt


