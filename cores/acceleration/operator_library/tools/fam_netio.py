_VLAN_TPID = {0x8100: 1, 0x88A8: 2, 0x9100: 3}


def _m_qinq(a, b, c, state):
    slots = [(a & 0xFFFF, (a >> 16) & 0xFFFF), (b & 0xFFFF, (b >> 16) & 0xFFFF),
             (c & 0xFFFF, (c >> 16) & 0xFFFF)]
    cmap = depth = etype = 0
    evid = vidin = dein = cin = nullin = 0
    run = True
    for index in range(3):
        tpid, tci = slots[index]
        cls = _VLAN_TPID.get(tpid, 0)
        cmap |= cls << (2 * index)
        if run:
            if cls:
                depth += 1
                vidin = tci & 0xFFF
                dein = (tci >> 12) & 1
                cin = cls
                nullin = 1 if vidin == 0 else 0
                if vidin == 0xFFF:
                    evid = 1
            else:
                etype = tpid
                run = False
    edepth = 1 if depth == 3 else 0
    vidout = 0 if depth == 0 else slots[0][1] & 0xFFF
    deiout = 0 if depth == 0 else (slots[0][1] >> 12) & 1
    r = (vidout | (vidin << 12) | (depth << 24) | ((1 if depth == 0 else 0) << 27)
         | ((1 if depth >= 2 else 0) << 28) | ((1 if cmap & 3 == 2 else 0) << 29)
         | ((1 if (cin == 1 and depth) else 0) << 30)
         | ((1 if (depth == 1 and (cmap & 3) == 1) else 0) << 31))
    nullout = 1 if (depth and vidout == 0) else 0
    x = (cmap | (edepth << 6) | (evid << 7) | (nullout << 8) | (nullin << 9)
         | (deiout << 10) | (dein << 11) | (etype << 16))
    return r, x, 1 if (edepth or evid) else 0, state


